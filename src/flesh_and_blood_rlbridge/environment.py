"""
rlbridge Flesh and Blood Environment (Talishar-Inspired)
====================================================
A turn-based TCG simulator inspired by Talishar-style gameplay loops.

This environment models the core Flesh and Blood gameplay loop:

- Two heroes (agent vs scripted opponent) with hand/deck/discard zones and
  draw-up-to-intellect each turn.
- Pitch economy: resources start at 0 each action phase and are generated by
  pitching cards (by their pitch value); pitched cards go to the bottom of the
  deck at end of the phase.
- Turn flow (FAB-style):
    * Setup: both players draw to intellect.
    * Player 0 opening action phase (no draw): attack; defender blocks;
      multiple attacks in one phase form a combat chain (go again / extra AP).
    * After player 0's opening phase: both players draw to full hand.
    * Player 1 opening action phase: attack; player 1 draws at end of that phase.
    * Thereafter each player turn is: defend during the opponent's attack phase,
      then your attack phase, optional arsenal stash (one card face-down), then
      draw to intellect at the end of your attack phase (no draw at phase start).
- Combat chain reaction windows per link:
    * Defense phase: the defender may block with multiple cards.
    * Reaction phase: the attacker may play attack reactions to boost power.
- Keyword effects derived from card text: ``go again``, ``dominate`` (one hand
  block), ``overpower`` (one action block), ``intimidate`` (face-down banish
  on hit), ``ward`` (destroy permanent to prevent), plus fusion/reveal hooks.

Reward signal summary:

- Terminal win: `+1.0`; terminal loss: `-1.0`.
- Dense shaping: `+0.01 * damage_dealt` and `-0.005 * damage_received` per combat resolution.
- Step penalty of `-0.005` per step discourages passive play.
- Illegal actions receive a penalty (`-0.1`, except pass is auto-coerced when it is the only legal action).
- Invalid block/play attempts apply `-0.05`.
- Blocking carries no shaping bonus; win/loss is the primary signal.

The simulator is designed for training and protocol integration, not as a full
competitive-rules implementation.
"""


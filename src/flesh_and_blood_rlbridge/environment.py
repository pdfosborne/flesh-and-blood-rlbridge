    def _consume_pending_next_attack_power(
        self,
        player_idx: int,
        card: Card,
        combat: CombatState,
        *,
        is_weapon: bool = False,
        card_power: Optional[int] = None,
    ) -> None:
        cs = self._players[player_idx].class_state
        pending_power = cs.get("NextAttackPower", 0)
        if pending_power == 0:
            return
        if cs.get("NextAttackWeaponOnly", 0) and not is_weapon:
            return
        base_power = card_power if card_power is not None else card.power
        min_base = cs.get("NextAttackMinBase", 0)
        if min_base and base_power < min_base:
            return
        max_cost = cs.get("NextAttackPowerMaxCost", -1)
        if max_cost >= 0 and card.cost > max_cost:
            return
        self._apply_combat_power_bonus(
            combat,
            player_idx,
            pending_power,
            reason=f"+{pending_power} power from prior effect",
        )
        cs["NextAttackPower"] = 0
        cs["NextAttackPowerMaxCost"] = 0
        cs["NextAttackMinBase"] = 0
        cs["NextAttackWeaponOnly"] = 0
        self._apply_named_power_bonuses(player_idx, card, combat)

    def _apply_combat_power_bonus(
        self,
        combat: CombatState,
        player_idx: int,
        amount: int,
        *,
        reason: str = "",
    ) -> int:
        """Apply a power bonus to the current attack, respecting block/reduction effects."""
        if amount == 0 or combat is None:
            return 0
        actor = self._players[player_idx]
        if amount > 0 and actor.class_state.get("BlockPowerGainThisTurn", 0):
            self._event_append("power gain blocked this turn")
            return 0
        if amount > 0 and combat.block_power_gain:
            self._event_append("attack can't gain power")
            return 0
        if amount > 0 and combat.next_power_gain_reduction > 0:
            amount = max(0, amount - combat.next_power_gain_reduction)
            combat.next_power_gain_reduction = 0
            if amount == 0:
                self._event_append("power gain reduced to zero")
                return 0
        combat.attack_bonus += amount
        if reason:
            self._event_append(reason)
        return amount

    def _legal_plays(self, actor_idx: int) -> list[int]:
        actor = self._players[actor_idx]
        if actor.action_points <= 0:
            return []
        plays: list[int] = []
        for i, cid in enumerate(actor.hand):
            card = self._cards[cid]
            if not self._is_playable_action(card):
                continue
            if self._effective_card_cost(actor_idx, card) > actor.resources:
                continue
            if self._play_blocked_reason(actor_idx, i, card):
                continue
            plays.append(i)
        return plays

    def _legal_instant_plays(self, actor_idx: int) -> list[int]:
        """Non-attack actions playable as instant while play_as_instant is set."""
        actor = self._players[actor_idx]
        if not actor.play_as_instant:
            return []
        legal: list[int] = []
        for i, cid in enumerate(actor.hand):
            card = self._cards[cid]
            if "attack_action" in card.card_types:
                continue
            if "utility_action" not in card.card_types:
                continue
            cls_filter = actor.instant_class_filter
            if cls_filter and cls_filter not in (card.card_class or "").lower():
                continue
            if self._effective_card_cost(actor_idx, card) > actor.resources:
                continue
            if self._play_blocked_reason(actor_idx, i, card):
                continue
            legal.append(i)
        return legal

    def _legal_banished_plays(self, actor_idx: int) -> list[int]:
        actor = self._players[actor_idx]
        if actor.action_points <= 0:
            return []
        legal: list[int] = []
        for i, cid in enumerate(actor.banished):
            if not self._can_play_from_banished(actor_idx, cid):
                continue
            card = self._cards[cid]
            if not self._is_playable_action(card):
                continue
            if self._effective_card_cost(actor_idx, card) > actor.resources:
                continue
            legal.append(i)
        return legal

    def _legal_graveyard_plays(self, actor_idx: int) -> list[int]:
        actor = self._players[actor_idx]
        if actor.action_points <= 0:
            return []
        legal: list[int] = []
        for i, cid in enumerate(actor.discard):
            if not self._can_play_from_graveyard(actor_idx, cid):
                continue
            card = self._cards[cid]
            if not self._is_playable_action(card):
                continue
            if self._effective_card_cost(actor_idx, card) > actor.resources:
                continue
            legal.append(i)
        return legal

    def _legal_pitches(self, actor_idx: int) -> list[int]:
        actor = self._players[actor_idx]
        return [i for i, cid in enumerate(actor.hand) if self._cards[cid].pitch > 0]

    def _is_hand_block(self, defender: PlayerState, card_id: str) -> bool:
        return card_id not in defender.equipment and card_id not in defender.arsenal

    def _defender_hand_blocks(self, combat: CombatState, defender_idx: int) -> list[tuple[int, str, int]]:
        defender = self._players[defender_idx]
        return [
            b for b in combat.blocks
            if b[0] == defender_idx and self._is_hand_block(defender, b[1])
        ]

    def _legal_blocks(self, defender_idx: int) -> list[int]:
        combat = self._pending_combat
        if combat is None:
            return []
        hand_blocks = self._defender_hand_blocks(combat, defender_idx)
        # Dominate (CR 8.3.4): at most one defending card from hand.
        if combat.dominate and hand_blocks:
            return []
        action_blocked = any(
            fab_rules.is_action_card(self._cards[b[1]].card_types) for b in hand_blocks
        )
        legal: list[int] = []
        for i, cid in enumerate(self._players[defender_idx].hand):
            card = self._cards[cid]
            if card.defense <= 0:
                continue
            if combat.defense_reactions_blocked and "defense_reaction" in card.card_types:
                continue
            # Overpower (CR 8.3.22): at most one defending action card.
            if combat.overpower and action_blocked and fab_rules.is_action_card(card.card_types):
                continue
            legal.append(i)
        return legal

    def _legal_reactions(self, attacker_idx: int) -> list[int]:
        attacker = self._players[attacker_idx]
        reactions: list[int] = []
        for i, cid in enumerate(attacker.hand):
            card = self._cards[cid]
            if "attack_reaction" in card.card_types and card.cost <= attacker.resources:
                reactions.append(i)
        return reactions

    def _can_weapon_attack(self, actor_idx: int) -> bool:
        actor = self._players[actor_idx]
        _, attack, cost, _ = self._weapon_stats(actor_idx)
        extra = actor.class_state.get("ExtraWeaponAttacks", 0)
        if attack <= 0 or actor.action_points <= 0 or actor.resources < cost:
            return False
        if actor.weapon_used and extra <= 0:
            return False
        if actor.weapon_attacks_blocked:
            return False
        return True

    def _ability_list(self, actor_idx: int) -> list[dict[str, Any]]:
        """Ordered activated abilities available from this player's arena.

        Each entry exposes a stable index used by the ``ability <i>`` action.
        Equipment slots come first (in slot order), then the hero ability.
        Only abilities whose effect we can resolve faithfully are listed.
        """
        actor = self._players[actor_idx]
        entries: list[dict[str, Any]] = []
        for cid in actor.equipment:
            card = self._cards[cid]
            for ability in effects.parse_activated_abilities(card.text):
                if ability.implemented:
                    entries.append(
                        {"token": f"equip:{cid}", "name": card.name, "ability": ability, "card_id": cid}
                    )
        if actor.weapon_id is not None:
            weapon = self._cards[actor.weapon_id]
            for wab in effects.parse_activated_abilities(weapon.text):
                if wab.implemented:
                    entries.append(
                        {
                            "token": f"weapon:{actor.weapon_id}",
                            "name": weapon.name,
                            "ability": wab,
                            "card_id": actor.weapon_id,
                        }
                    )
        for hero_ability in effects.parse_activated_abilities(actor.hero.ability_text):
            if hero_ability.implemented:
                entries.append(
                    {
                        "token": "hero",
                        "name": f"{actor.hero.name} (hero)",
                        "ability": hero_ability,
                        "card_id": "",
                    }
                )
        return entries

    def _ability_usable(self, actor_idx: int, entry: dict[str, Any]) -> bool:
        actor = self._players[actor_idx]
        ability = entry["ability"]
        reduction = actor.class_state.get("NextAbilityCostReduction", 0)
        eff_cost = max(0, ability.cost - reduction)
        if eff_cost > actor.resources:
            return False
        if ability.uses_action_point and actor.action_points <= 0:
            return False
        if ability.once_per_turn and entry["token"] in actor.arena_used:
            return False
        cid = entry.get("card_id") or ""
        if ability.counter_cost > 0 and cid:
            if self._permanent_counters(actor_idx, cid).get(ability.counter_name, 0) < ability.counter_cost:
                return False
        return True

    def _legal_abilities(self, actor_idx: int) -> list[int]:
        entries = self._ability_list(actor_idx)
        return [i for i, e in enumerate(entries) if self._ability_usable(actor_idx, e)]

    def _legal_stash(self, actor_idx: int) -> list[int]:
        """Hand indices that may be stashed face-down into the arsenal."""
        actor = self._players[actor_idx]
        if actor.arsenal:
            return []
        return list(range(len(actor.hand)))

    def _legal_gear_blocks(self, defender_idx: int) -> list[int]:
        """Equipment indices that can still block the pending attack."""
        combat = self._pending_combat
        if combat is None:
            return []
        defender = self._players[defender_idx]
        usable: list[int] = []
        for i, cid in enumerate(defender.equipment):
            card = self._cards[cid]
            if card.defense <= 0:
                continue
            if f"equip:{cid}" in defender.arena_used:
                continue
            usable.append(i)
        return usable


    def _record_opponent_pitch(self, player_idx: int, card: Card) -> None:
        if player_idx != 1:
            return
        if self._action_phase_player != 1 or self._phase != "action":
            return
        if self._last_opponent_turn is None:
            return
        pitches = self._last_opponent_turn.setdefault("pitches", [])
        pitches.append({"name": card.name, "pitch": card.pitch})

    def _record_opponent_attack(
        self,
        player_idx: int,
        *,
        attack_name: str,
        attack_power: int,
        is_weapon: bool = False,
    ) -> None:
        if player_idx != 1 or self._last_opponent_turn is None:
            return
        self._last_opponent_turn["attack_card"] = attack_name
        self._last_opponent_turn["attack_power"] = attack_power
        self._last_opponent_turn["is_weapon"] = is_weapon

    def _do_pitch(self, player_idx: int, hand_idx: int) -> float:
        p = self._players[player_idx]
        card = self._cards[p.hand[hand_idx]]
        if card.pitch <= 0:
            self._last_event = f"{card.name} cannot be pitched"
            return -0.05
        p.hand.pop(hand_idx)
        p.pitch_zone.append(card.id)
        p.resources += card.pitch
        self._record_opponent_pitch(player_idx, card)
        self._last_event = f"P{player_idx} pitches {card.name} (+{card.pitch} resources)"
        if card.power >= 6:
            p.class_state["PitchedPower6ThisTurn"] = 1
        reward = 0.0
        for trig in effects.parse_triggers(card.text):
            if trig.when != "on_pitched":
                continue
            reward += self._apply_effect(player_idx, card, trig.effect, None, player_idx)
        return reward

    @staticmethod
    def _play_suffix(fused: bool, elements: tuple[str, ...], go_again: bool) -> str:
        if fused and elements:
            return f" [fused: {', '.join(elements)}]"
        if go_again:
            return " [go again]"
        return ""

    def _note(self, message: str) -> None:
        """Record a player-facing notice (e.g. an unimplemented interaction)."""
        if message not in self._notices:
            self._notices.append(message)

    def _event_append(self, message: str) -> None:
        """Append a positive trigger result to the current event line."""
        self._last_event = f"{self._last_event} | {message}" if self._last_event else message

    @staticmethod
    def _is_lightning_action(card: Card) -> bool:
        return (card.talent or "").strip().lower() == "lightning"

    @staticmethod
    def _intrinsic_go_again(card: Card) -> bool:
        """Printed go again keyword, unless rules text gates it behind a condition."""
        if "go_again" not in card.keywords:
            return False
        text = str(card.text or "").lower()
        if re.search(r"\bif .+ get(s)? ?(?:\*\*)?go again", text):
            return False
        return True

    def _go_again_for_play(self, player_idx: int, card: Card, is_utility: bool) -> bool:
        """Whether this action should have go again when played (flags + keyword)."""
        actor = self._players[player_idx]
        cs = actor.class_state
        go_again = False
        pending = cs.get("NextActionGoAgain", 0)
        if pending > 0:
            go_again = True
            cs["NextActionGoAgain"] = pending - 1
            self._event_append("go again from pending flag")
        if is_utility and cs.get("NextNAACardGoAgain", 0) > 0:
            go_again = True
            cs["NextNAACardGoAgain"] = 0
        if self._intrinsic_go_again(card):
            go_again = True
        if actor.silenced:
            return False
        return go_again

    def _grant_go_again(
        self,
        player_idx: int,
        combat: Optional[CombatState] = None,
        *,
        this_card: bool = True,
        next_actions: int = 0,
    ) -> None:
        """Grant go again to the current chain link and/or future action(s)."""
        actor = self._players[player_idx]
        if actor.silenced:
            self._event_append("silenced — cannot gain go again")
            return
        if this_card:
            if combat is not None:
                combat.go_again = True
            else:
                actor.action_points += 1
        if next_actions > 0:
            actor.class_state["NextActionGoAgain"] = actor.class_state.get("NextActionGoAgain", 0) + next_actions
            label = "action" if next_actions == 1 else "actions"
            self._event_append(f"next {next_actions} {label} gain go again")
        self._fire_whenever_go_again_triggers(player_idx)

    def _fire_whenever_go_again_triggers(self, player_idx: int) -> None:
        """Fire 'whenever you go again this turn' on arena permanents."""
        actor = self._players[player_idx]
        sources: list[Card] = []
        for cid in actor.equipment:
            sources.append(self._cards[cid])
        if actor.weapon_id:
            sources.append(self._cards[actor.weapon_id])
        for card in sources:
            for trig in effects.parse_triggers(card.text):
                if trig.when != "whenever_go_again":
                    continue
                self._apply_effect(player_idx, card, trig.effect, self._pending_combat, player_idx)

    def _process_blood_debt(self, player_idx: int) -> None:
        """Blood Debt — lose 1 at beginning of end phase for public banished cards (CR 8.3.11)."""
        actor = self._players[player_idx]
        debt = 0
        for cid in actor.banished:
            card = self._cards[cid]
            if "blood_debt" in card.keywords or "blood debt" in card.text.lower():
                debt += 1
        if debt:
            actor.life -= debt
            self._event_append(f"blood debt: -{debt} life")

    def _do_intimidate(self, target_idx: int) -> None:
        """Intimidate — banish random hand card face-down until end phase (CR 8.5.10)."""
        target = self._players[target_idx]
        if not target.hand:
            self._event_append(f"P{target_idx} intimidated (empty hand)")
            return
        idx = self._rng.randint(0, len(target.hand) - 1)
        cid = target.hand.pop(idx)
        target.intimidated.append(cid)
        self._event_append(f"P{target_idx} intimidated: {self._cards[cid].name} face-down")

    def _do_clash(self, player_idx: int, token_name: str = "", *, loser_debuff: bool = False) -> None:
        """Clash — reveal deck tops, highest power wins (CR 8.5.45)."""
        opponent_idx = 1 - player_idx
        a_top = self._deck_top_card_id(player_idx)
        d_top = self._deck_top_card_id(opponent_idx)
        a_power = self._cards[a_top].power if a_top else None
        d_power = self._cards[d_top].power if d_top else None
        if a_top:
            self._event_append(f"clash reveal P{player_idx}: {self._cards[a_top].name} ({a_power})")
        if d_top:
            self._event_append(f"clash reveal P{opponent_idx}: {self._cards[d_top].name} ({d_power})")
        result = fab_rules.resolve_clash(a_power, d_power)
        if result.tie:
            self._event_append("clash tied")
            return
        if loser_debuff:
            loser_idx = opponent_idx if result.attacker_wins else player_idx
            self._apply_equipment_defense_debuff(loser_idx)
            return
        if result.attacker_wins and token_name:
            self._create_token(player_idx, token_name)
            self._event_append(f"clash won — created {token_name}")
        elif result.defender_wins and token_name:
            self._create_token(opponent_idx, token_name)
            self._event_append(f"clash lost — opponent gets {token_name}")

    def _do_opt(self, player_idx: int, amount: int) -> None:
        """Opt N — look at top N, put each on top or bottom (CR 8.5.22)."""
        actor = self._players[player_idx]
        looked: list[str] = []
        for _ in range(max(1, amount)):
            if not actor.deck and actor.discard:
                actor.deck = actor.discard
                actor.discard = []
                self._rng.shuffle(actor.deck)
            if not actor.deck:
                break
            looked.append(actor.deck.pop())
        if not looked:
            return
        needs_decision = (player_idx == 0 and not self._self_play) or self._self_play
        if needs_decision:
            self._opt_ctx = {
                "player": player_idx,
                "cards": looked,
                "index": 0,
                "top": [],
                "bottom": [],
            }
            self._opt_resume = {"phase": self._phase, "active": self._active_player}
            self._phase = "opt"
            self._active_player = player_idx
            card = self._cards[looked[0]]
            self._event_append(
                f"opt {len(looked)}: choose top/bottom for {card.name} (1/{len(looked)})"
            )
            return
        actor.deck.extend(reversed(looked))
        names = ", ".join(self._cards[c].name for c in looked)
        self._event_append(f"opt {len(looked)}: kept {names} on top")

    def _do_opt_choice(self, player_idx: int, *, to_bottom: bool) -> None:
        ctx = self._opt_ctx
        if not ctx or ctx.get("player") != player_idx:
            return
        i = ctx["index"]
        cid = ctx["cards"][i]
        if to_bottom:
            ctx["bottom"].append(cid)
        else:
            ctx["top"].append(cid)
        ctx["index"] += 1
        if ctx["index"] < len(ctx["cards"]):
            next_cid = ctx["cards"][ctx["index"]]
            self._event_append(
                f"opt: choose top/bottom for {self._cards[next_cid].name} "
                f"({ctx['index'] + 1}/{len(ctx['cards'])})"
            )
            return
        self._finish_opt()

    def _finish_opt(self) -> None:
        ctx = self._opt_ctx
        if not ctx:
            return
        actor = self._players[ctx["player"]]
        for cid in reversed(ctx["top"]):
            actor.deck.append(cid)
        for cid in ctx["bottom"]:
            actor.deck.insert(0, cid)
        top_names = ", ".join(self._cards[c].name for c in ctx["top"]) or "none"
        bot_names = ", ".join(self._cards[c].name for c in ctx["bottom"]) or "none"
        self._event_append(f"opt done: top=[{top_names}] bottom=[{bot_names}]")
        resume = self._opt_resume or {"phase": "action", "active": ctx["player"]}
        self._opt_ctx = {}
        self._opt_resume = None
        self._phase = resume.get("phase", "action")
        self._active_player = resume.get("active", ctx["player"])

    def _find_gambler_gloves(self) -> tuple[Optional[int], Optional[str]]:
        for owner_idx in (0, 1):
            for cid in self._players[owner_idx].equipment:
                card = self._cards[cid]
                if "gambler" not in card.name.lower():
                    continue
                for trig in effects.parse_triggers(card.text):
                    if trig.when == "on_die_roll" and trig.effect.kind == "destroy_item":
                        return owner_idx, cid
        return None, None

    def _pause_for_gambler(self, controller_idx: int) -> bool:
        """Offer Gambler's Gloves before a d6 roll. Returns True if paused."""
        owner, cid = self._find_gambler_gloves()
        if cid is None:
            return False
        pending = dict(self._pending_die_roll or {})
        pending["controller"] = controller_idx
        pending.setdefault("reroll", False)
        self._pending_die_roll = pending
        if owner == 1 and not self._self_play:
            return False
        self._pending_optionals.append(
            {
                "player": owner,
                "card_id": cid,
                "effect": effects.Effect(
                    "destroy_item",
                    banish_name="reroll_d6",
                    optional=True,
                    raw="destroy Gambler's Gloves to reroll",
                ),
                "perspective": owner,
            }
        )
        self._optional_resume = "die_roll"
        self._phase = "optional"
        self._active_player = owner
        return True

    def _roll_d6(self, controller_idx: int, *, allow_intercept: bool = True) -> int:
        """Roll a d6; tracks Rolled6ThisTurn."""
        ctx = self._pending_die_roll if isinstance(self._pending_die_roll, dict) else {}
        reroll = bool(ctx.get("reroll"))
        if reroll and isinstance(self._pending_die_roll, dict):
            self._pending_die_roll.pop("reroll", None)
        roll = self._rng.randint(1, 6)
        if reroll:
            self._event_append(f"Gambler's Gloves: rerolled {roll}")
        if roll == 6:
            self._players[controller_idx].class_state["Rolled6ThisTurn"] = 1
        return roll

    def _apply_kayo_power6(self, player_idx: int, attack_card: Card, combat: CombatState) -> None:
        actor = self._players[player_idx]
        if attack_card.power < 6:
            return
        if not any(
            t.when == "whenever_power6_attack"
            for t in effects.parse_triggers(actor.hero.ability_text)
        ):
            return
        self._pending_die_roll = {
            "controller": player_idx,
            "kind": "kayo",
            "card_id": attack_card.id,
        }
        if self._pause_for_gambler(player_idx):
            return
        self._continue_pending_die_roll()

    def _continue_pending_die_roll(self) -> None:
        ctx = dict(self._pending_die_roll or {})
        if not ctx:
            return
        kind = ctx.get("kind")
        controller = int(ctx.get("controller", 0))
        roll = self._roll_d6(controller, allow_intercept=False)
        if kind == "kayo":
            card = self._cards.get(ctx.get("card_id", ""))
            combat = self._pending_combat
            if card and combat:
                if roll <= 4:
                    combat.attack_power = card.power // 2
                else:
                    combat.attack_power = card.power * 2
                self._event_append(
                    f"Kayo roll {roll}: base power {card.power} -> {combat.attack_power}"
                )
        elif kind == "gain_ap_half":
            actor = self._players[controller]
            ap = roll // 2
            actor.action_points += ap
            self._event_append(f"rolled {roll}: gained {ap} action point(s)")
        elif kind == "prevent_d6":
            target = self._players[controller]
            target.prevent_damage += roll
            self._event_append(
                f"P{controller} rolled {roll}: will prevent {roll} damage this turn"
            )
        self._pending_die_roll = None

    def _apply_card_choice_rider(
        self,
        target_idx: int,
        card_id: str,
        rider: str,
        chooser_idx: int,
    ) -> None:
        target = self._players[target_idx]
        if card_id not in target.hand:
            return
        target.hand.remove(card_id)
        parts = (rider or "").lower().split(":")
        action = parts[0] if parts else ""
        if action == "put_bottom":
            target.deck.insert(0, card_id)
            self._event_append(f"put {self._cards[card_id].name} on bottom of deck")
            if len(parts) > 1 and parts[1] == "draw":
                self._draw_card(target_idx, from_action=True)
                self._event_append("defender drew a card")
        elif action == "discard":
            target.discard.append(card_id)
            self._event_append(f"{self._cards[card_id].name} discarded")
            if len(parts) > 1 and parts[1] == "draw":
                self._draw_card(chooser_idx, from_action=True)
        elif action == "banish":
            target.banished.append(card_id)
            self._event_append(f"banished {self._cards[card_id].name}")
        target.revealed_hand = [c for c in target.revealed_hand if c != card_id]

    def _choice_options_for_hand(
        self,
        target_idx: int,
        *,
        from_revealed: bool = False,
        filter_no_defense: bool = False,
    ) -> list[dict[str, Any]]:
        target = self._players[target_idx]
        pool = list(target.revealed_hand if from_revealed else target.hand)
        if filter_no_defense:
            pool = [cid for cid in pool if self._cards[cid].defense <= 0]
        return [
            {"index": i, "card_id": cid, "name": self._cards[cid].name}
            for i, cid in enumerate(pool)
        ]

    def _begin_card_choice(
        self,
        chooser_idx: int,
        target_idx: int,
        options: list[dict[str, Any]],
        *,
        rider: str,
        optional: bool,
        prompt: str,
        resume: str,
    ) -> bool:
        """Return True if choice phase started (paused). False if auto-resolved."""
        if not options:
            return False
        if optional and len(options) == 0:
            return False
        needs_ui = (chooser_idx == 0 and not self._self_play) or self._self_play
        if not needs_ui:
            pick = self._rng.randrange(len(options))
            cid = options[pick]["card_id"]
            self._apply_card_choice_rider(target_idx, cid, rider, chooser_idx)
            return False
        self._choice_ctx = {
            "chooser": chooser_idx,
            "target": target_idx,
            "options": options,
            "rider": rider,
            "optional": optional,
            "prompt": prompt,
            "resume": resume,
        }
        self._choice_resume = resume
        self._phase = "choice"
        self._active_player = chooser_idx
        names = ", ".join(o["name"] for o in options)
        self._event_append(f"choose a card: {names}")
        return True

    def _record_soul_banish_chain(self, player_idx: int) -> None:
        if self._pending_combat is None:
            return
        cs = self._players[player_idx].class_state
        cs["SoulBanishedThisChain"] = cs.get("SoulBanishedThisChain", 0) + 1

    def _reset_chain_soul_counters(self) -> None:
        for player in self._players:
            player.class_state["SoulBanishedThisChain"] = 0

    def _mode_pick_count(self, effect: effects.Effect, player_idx: int, card: Card) -> int:
        pick = effect.condition or ""
        actor = self._players[player_idx]
        if pick == "pick:soul_banish_chain":
            return int(actor.class_state.get("SoulBanishedThisChain", 0))
        if pick == "pick:blue_pitched":
            return sum(1 for cid in actor.pitch_zone if self._cards[cid].pitch == 3)
        if pick.startswith("pick:played_blue_other:"):
            parts = pick.split(":")
            hi, lo = int(parts[2]), int(parts[3])
            if self._effect_condition_met(player_idx, "played_blue_other", card):
                return hi
            return lo
        return 0

    def _decode_mode_specs(self, encoded: str) -> list[effects.Effect]:
        out: list[effects.Effect] = []
        for part in (encoded or "").split("|"):
            if not part:
                continue
            fields = part.split(":")
            kind = fields[0]
            if kind == "create_token" and len(fields) >= 2:
                payload = part.split(":", 1)[1]
                amt_s, rest = payload.split(":", 1)
                name, tgt = rest.rsplit(":", 1)
                out.append(
                    effects.Effect(
                        "create_token",
                        int(amt_s),
                        token_name=name,
                        target=tgt,
                    )
                )
            elif kind == "draw" and len(fields) >= 3:
                out.append(effects.Effect("draw", int(fields[1]), target=fields[2]))
            elif kind == "gain_life" and len(fields) >= 3:
                out.append(effects.Effect("gain_life", int(fields[1]), target=fields[2]))
            elif kind == "power" and len(fields) >= 2:
                out.append(effects.Effect("power", int(fields[1])))
            elif kind == "go_again":
                out.append(effects.Effect("go_again"))
            elif kind == "put_counter" and len(fields) >= 4:
                out.append(
                    effects.Effect(
                        "put_counter",
                        int(fields[1]),
                        token_name=fields[2],
                        banish_name=fields[3],
                    )
                )
            elif kind == "create_in_hand" and len(fields) >= 2:
                payload = part.split(":", 1)[1]
                amt_s, rest = payload.split(":", 1)
                name, tgt = rest.rsplit(":", 1)
                out.append(
                    effects.Effect(
                        "create_in_hand",
                        int(amt_s),
                        banish_name=name,
                        target=tgt,
                    )
                )
            elif kind == "named_power_bonus" and len(fields) >= 2:
                payload = part.split(":", 1)[1]
                amt_s, rest = payload.split(":", 1)
                name, tgt = rest.rsplit(":", 1)
                out.append(
                    effects.Effect(
                        "named_power_bonus",
                        int(amt_s),
                        token_name=name,
                        target=tgt,
                    )
                )
            elif kind == "banish_graveyard" and len(fields) >= 3:
                out.append(
                    effects.Effect(
                        "banish_graveyard",
                        int(fields[1]),
                        target=fields[2],
                    )
                )
            elif kind == "transcend":
                out.append(effects.Effect("transcend"))
        return out

    def _apply_mode_spec(
        self,
        player_idx: int,
        card: Card,
        mode_eff: effects.Effect,
        combat: Optional[CombatState],
        perspective_idx: int,
    ) -> None:
        if mode_eff.target == "each_hero":
            for idx in (0, 1):
                hero_eff = effects.Effect(
                    mode_eff.kind,
                    mode_eff.amount,
                    token_name=mode_eff.token_name,
                    target="self",
                    banish_name=mode_eff.banish_name,
                )
                self._apply_effect(idx, card, hero_eff, combat, perspective_idx)
            return
        self._apply_effect(player_idx, card, mode_eff, combat, perspective_idx)

    def _resume_after_choice(self, ctx: dict[str, Any]) -> float:
        chooser_idx = int(ctx["chooser"])
        resume = str(ctx.get("resume", ""))
        self._choice_resume = None
        if resume == "after_play":
            card_id = ctx.get("card_id")
            if card_id:
                play_card = self._cards[card_id]
                fused = bool(ctx.get("fused"))
                perspective = int(ctx.get("perspective", chooser_idx))
                self._phase = str(ctx.get("return_phase", "action"))
                self._active_player = chooser_idx
                return self._finish_attack_triggers(chooser_idx, play_card, perspective, fused)
        if resume == "after_attack":
            self._phase = str(ctx.get("return_phase", "action"))
            self._active_player = chooser_idx
            self._enter_defense()
            return 0.0
        if resume == "after_play_direct":
            self._phase = "action"
            self._active_player = chooser_idx
            return 0.0
        if resume == "after_hit_combat":
            fin = ctx.get("combat_finish") or {}
            if fin:
                return self._complete_combat_resolution(
                    float(fin.get("reward", 0.0)),
                    int(fin.get("perspective", chooser_idx)),
                    int(fin.get("attacker_idx", chooser_idx)),
                    int(fin.get("defender_idx", 1 - chooser_idx)),
                    int(fin.get("damage", 0)),
                    bool(fin.get("go_again")),
                    bool(fin.get("fused")),
                )
            self._phase = str(ctx.get("return_phase", "action"))
            self._active_player = chooser_idx
            return 0.0
        if resume == "after_hit":
            self._phase = str(ctx.get("return_phase", "action"))
            self._active_player = chooser_idx
            return 0.0
        self._phase = str(ctx.get("return_phase", "action"))
        self._active_player = chooser_idx
        return 0.0

    def _begin_mode_choice(
        self,
        chooser_idx: int,
        card: Card,
        effect: effects.Effect,
        *,
        resume: str,
        perspective_idx: int,
        combat: Optional[CombatState],
    ) -> bool:
        pick_any = (effect.condition or "") == "pick:any"
        picks = self._mode_pick_count(effect, chooser_idx, card)
        if not pick_any and picks <= 0:
            return False
        mode_specs = self._decode_mode_specs(effect.banish_name or "")
        if len(mode_specs) < 2:
            return False
        labels = (effect.token_name or "").split("|")
        options = [
            {
                "index": i,
                "name": labels[i] if i < len(labels) else (mode_specs[i].raw or f"Mode {i}"),
                "mode_idx": i,
            }
            for i in range(len(mode_specs))
        ]
        needs_ui = (chooser_idx == 0 and not self._self_play) or self._self_play
        if not needs_ui:
            picked = [0] * len(mode_specs)
            if pick_any:
                count = self._rng.randint(0, len(mode_specs))
                for idx in self._rng.sample(range(len(mode_specs)), count):
                    self._apply_mode_spec(
                        chooser_idx, card, mode_specs[idx], combat, perspective_idx
                    )
            else:
                for _ in range(picks):
                    legal = [
                        i
                        for i in range(len(mode_specs))
                        if picked[i] < max(1, effect.amount or 1)
                    ]
                    if not legal:
                        break
                    idx = legal[self._rng.randrange(len(legal))]
                    picked[idx] += 1
                    self._apply_mode_spec(
                        chooser_idx, card, mode_specs[idx], combat, perspective_idx
                    )
            return False
        prompt = effect.raw or "Choose a mode"
        if pick_any:
            prompt = f"{prompt} (pass when done)"
        elif picks > 1:
            prompt = f"{prompt} ({picks} remaining)"
        self._choice_ctx = {
            "kind": "mode",
            "chooser": chooser_idx,
            "target": chooser_idx,
            "options": options,
            "modes_enc": effect.banish_name or "",
            "max_per_mode": max(1, effect.amount or 1),
            "picks_remaining": picks,
            "pick_any": pick_any,
            "picked": [0] * len(mode_specs),
            "selected_any": [],
            "optional": pick_any,
            "prompt": prompt,
            "resume": resume,
            "card_id": card.id,
            "fused": bool(combat.fused if combat else False),
            "perspective": perspective_idx,
            "return_phase": self._phase,
        }
        self._choice_resume = resume
        self._phase = "choice"
        self._active_player = chooser_idx
        self._event_append(f"choose mode: {', '.join(o['name'] for o in options)}")
        return True

    def _resolve_mode_choice(self, choice_idx: Optional[int]) -> float:
        ctx = self._choice_ctx
        if not ctx:
            return 0.0
        chooser_idx = int(ctx["chooser"])
        pick_any = bool(ctx.get("pick_any"))
        optional = bool(ctx.get("optional"))
        mode_specs = self._decode_mode_specs(str(ctx.get("modes_enc", "")))
        card = self._cards[str(ctx["card_id"])]
        combat = self._pending_combat
        perspective = int(ctx.get("perspective", chooser_idx))
        picked = list(ctx.get("picked") or [0] * len(mode_specs))
        max_per = int(ctx.get("max_per_mode") or 1)

        if choice_idx is None:
            if pick_any or optional:
                self._choice_ctx = {}
                self._event_append("finished mode choice")
                return self._resume_after_choice(ctx)
            self._event_append("must choose a mode")
            return 0.0

        options = ctx.get("options") or []
        if choice_idx < 0 or choice_idx >= len(options):
            return 0.0
        mode_idx = int(options[choice_idx].get("mode_idx", choice_idx))
        if mode_idx < 0 or mode_idx >= len(mode_specs):
            return 0.0
        if picked[mode_idx] >= max_per:
            return 0.0

        self._apply_mode_spec(chooser_idx, card, mode_specs[mode_idx], combat, perspective)
        picked[mode_idx] += 1
        label = options[choice_idx].get("name", f"mode {mode_idx}")
        self._event_append(f"chose mode: {label}")

        if pick_any:
            selected = set(ctx.get("selected_any") or [])
            selected.add(mode_idx)
            remaining = [o for o in options if int(o.get("mode_idx", -1)) not in selected]
            if not remaining:
                self._choice_ctx = {}
                return self._resume_after_choice(ctx)
            ctx["picked"] = picked
            ctx["selected_any"] = list(selected)
            ctx["options"] = remaining
            self._choice_ctx = ctx
            return 0.0

        picks_left = int(ctx.get("picks_remaining", 0)) - 1
        if picks_left <= 0:
            self._choice_ctx = {}
            return self._resume_after_choice(ctx)
        ctx["picked"] = picked
        ctx["picks_remaining"] = picks_left
        ctx["prompt"] = f"{ctx.get('prompt', 'Choose a mode').split('(')[0].strip()} ({picks_left} remaining)"
        self._choice_ctx = ctx
        return 0.0

    def _resolve_card_choice(self, choice_idx: Optional[int]) -> float:
        ctx = self._choice_ctx
        if not ctx:
            return 0.0
        if ctx.get("kind") == "mode":
            return self._resolve_mode_choice(choice_idx)
        chooser_idx = int(ctx["chooser"])
        target_idx = int(ctx["target"])
        resume = str(ctx.get("resume", ""))
        optional = bool(ctx.get("optional"))
        self._choice_ctx = {}
        if choice_idx is None:
            if optional:
                self._event_append("declined card choice")
            else:
                self._event_append("no card chosen")
        else:
            options = ctx.get("options") or []
            if 0 <= choice_idx < len(options):
                cid = options[choice_idx]["card_id"]
                self._apply_card_choice_rider(
                    target_idx, cid, str(ctx.get("rider", "")), chooser_idx
                )
        return self._resume_after_choice(ctx)

    def _search_deck(
        self,
        player_idx: int,
        *,
        name_pattern: str = "",
        max_cost: int = 99,
        card_type: str = "",
    ) -> bool:
        actor = self._players[player_idx]
        pattern = name_pattern.lower().strip()
        for i in range(len(actor.deck) - 1, -1, -1):
            cid = actor.deck[i]
            card = self._cards[cid]
            if max_cost >= 0 and card.cost > max_cost:
                continue
            if card_type and card_type not in card.card_types:
                continue
            if pattern:
                hay = f"{card.name} {' '.join(card.card_types)}".lower()
                if pattern not in hay:
                    continue
            actor.deck.pop(i)
            actor.hand.append(cid)
            self._event_append(f"searched deck: found {card.name}")
            return True
        self._event_append("search found no matching card")
        return False

    def _return_from_gy_to_deck(
        self, player_idx: int, name_pattern: str, *, to_bottom: bool = False
    ) -> bool:
        actor = self._players[player_idx]
        pattern = name_pattern.lower().strip()
        pitch_filter: Optional[int] = None
        for color, pitch in (("red", 1), ("yellow", 2), ("blue", 3)):
            if color in pattern:
                pitch_filter = pitch
                break
        for i, cid in enumerate(actor.discard):
            card = self._cards[cid]
            if pitch_filter is not None and card.pitch != pitch_filter:
                continue
            if pattern and pitch_filter is None:
                hay = f"{card.name} {' '.join(card.card_types)}".lower()
                if pattern not in hay and pattern not in card.name.lower():
                    continue
            cid = actor.discard.pop(i)
            if to_bottom:
                actor.deck.insert(0, cid)
                self._event_append(f"put {card.name} from graveyard on bottom of deck")
            else:
                actor.deck.append(cid)
                self._event_append(f"put {card.name} from graveyard on top of deck")
            return True
        self._event_append("no matching card in graveyard")
        return False

    def _return_from_gy_to_deck_top(self, player_idx: int, name_pattern: str) -> bool:
        return self._return_from_gy_to_deck(player_idx, name_pattern, to_bottom=False)


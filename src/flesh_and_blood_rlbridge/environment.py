    def _resolve_direct(
        self,
        player_idx: int,
        card: Card,
        damage: int,
        arcane: bool,
        go_again: bool,
        dominate: bool,
        fused: bool,
        elements: tuple[str, ...],
        perspective_idx: int,
    ) -> float:
        """Resolve a non-blockable play (arcane bolt or non-attack action)."""
        go_again, dominate = self._apply_play_modifiers(
            player_idx, card, None, go_again=go_again, dominate=dominate
        )
        self._record_play_counters(
            player_idx,
            card,
            "attack_action" in card.card_types,
            "utility_action" in card.card_types,
            fused,
            elements[0] if elements else None,
        )
        can_fuse = bool(elements) and self._can_fuse(player_idx, elements)
        if can_fuse:
            self._queue_fusion_optional(player_idx, card, perspective_idx, elements)
        self._queue_play_costs(player_idx, card, perspective_idx)
        if self._pending_optionals:
            self._play_resume_ctx = {
                "player": player_idx,
                "card_id": card.id,
                "damage": damage,
                "arcane": arcane,
                "go_again": go_again,
                "dominate": dominate,
                "fused": False,
                "elements": elements,
                "perspective": perspective_idx,
            }
            self._optional_resume = "post_play_costs"
            self._phase = "optional"
            self._active_player = player_idx
            return 0.0
        return self._resolve_direct_effects(
            player_idx,
            card,
            damage,
            arcane,
            go_again,
            dominate,
            fused,
            elements,
            perspective_idx,
        )

    def _resolve_direct_effects(
        self,
        player_idx: int,
        card: Card,
        damage: int,
        arcane: bool,
        go_again: bool,
        dominate: bool,
        fused: bool,
        elements: tuple[str, ...],
        perspective_idx: int,
        *,
        skip_arcane_triggers: bool = False,
    ) -> float:
        """Apply direct-play resolution after optional play costs."""
        actor = self._players[player_idx]
        defender = self._players[1 - player_idx]
        if arcane and not skip_arcane_triggers:
            self._fire_equipment_triggers(player_idx, "whenever_arcane_play", perspective_idx)
            if self._pending_optionals:
                self._optional_post_ctx = {
                    "player": player_idx,
                    "go_again": go_again,
                    "direct": {
                        "card_id": card.id,
                        "damage": damage,
                        "arcane": arcane,
                        "go_again": go_again,
                        "dominate": dominate,
                        "fused": fused,
                        "elements": elements,
                        "perspective": perspective_idx,
                    },
                }
                self._optional_resume = "direct_arcane"
                self._phase = "optional"
                self._active_player = player_idx
                return 0.0
        self._queue_play_keywords(player_idx, card, perspective_idx)
        if arcane and actor.amp > 0:
            damage += actor.amp
            self._event_append(f"amp +{actor.amp} arcane damage")
            actor.amp = 0
        if arcane and actor.class_state.get("ArcanePlusOneThisPlay", 0):
            damage += 1
            actor.class_state["ArcanePlusOneThisPlay"] = 0
            self._event_append("Metacarpus Node: +1 arcane damage")
        if damage > 0:
            if not arcane:
                damage = self._apply_damage_floor(player_idx, damage)
            damage = self._mitigate_damage(1 - player_idx, damage, arcane=arcane)
        defender.life -= damage
        enters_arena = self._is_arena_permanent(card) and damage <= 0 and not arcane
        if enters_arena:
            actor.equipment.append(card.id)
            self._fire_enters_triggers(player_idx, card)
        else:
            actor.discard.append(card.id)

        if damage > 0:
            kind = "arcane damage" if arcane else "damage"
            verb = f"deals {damage} {kind} to P{1 - player_idx}"
            actor.class_state["ArcaneDamageDealt" if arcane else "DamageDealt"] += damage
            actor.class_state["HitCounter"] += 1
            defender.class_state["DamageTaken"] += damage
        else:
            verb = "enters the arena" if enters_arena else "resolves"
        suffix = self._play_suffix(fused, elements, go_again)
        self._last_event = f"P{player_idx} plays {card.name} ({verb}){suffix}"

        reward = 0.0
        reward += self._run_triggers(player_idx, card, "on_play", None, perspective_idx, fused)
        if self._phase == "choice":
            return reward
        if fused:
            reward += self._run_triggers(player_idx, card, "when_fused", None, perspective_idx, fused)
        if "song" in (card.type_line or "").lower():
            reward += self._fire_equipment_triggers(player_idx, "whenever_song", perspective_idx)
        if damage > 0:
            reward += self._run_triggers(player_idx, card, "on_hit", None, perspective_idx, fused)

        if self._pending_optionals:
            self._optional_post_ctx = {"player": player_idx, "go_again": go_again}
            self._optional_resume = "direct_finish"
            self._phase = "optional"
            self._active_player = player_idx
            if damage > 0:
                reward += float(damage) * 0.01 if perspective_idx == player_idx else -float(damage) * 0.01
            return reward

        if go_again:
            self._grant_go_again(player_idx, None, this_card=False)

        if not self._is_terminal():
            if actor.action_points > 0:
                self._phase = "action"
                self._active_player = player_idx
            else:
                self._begin_arsenal_step(player_idx)

        if damage > 0:
            reward += float(damage) * 0.01 if perspective_idx == player_idx else -float(damage) * 0.01
        return reward

    def _do_block(self, defender_idx: int, hand_idx: int, perspective_idx: int = 0) -> float:
        combat = self._pending_combat
        if combat is None:
            self._last_event = "No attack to defend"
            return -0.05
        blocker = self._players[defender_idx]
        card = self._cards[blocker.hand[hand_idx]]
        if card.defense <= 0:
            self._last_event = f"{card.name} cannot block"
            return -0.05
        blocker.hand.pop(hand_idx)
        self._move_card_to_gy(defender_idx, card.id)
        defense = card.defense + blocker.class_state.get("NextDefenseBonus", 0)
        action_bonus = blocker.class_state.get("ActionBlockBonusThisChain", 0)
        if action_bonus and "attack_action" in card.card_types:
            defense += action_bonus
        if blocker.class_state.get("LightBlockBonusThisChain", 0) and "light" in (
            card.talent or ""
        ).lower():
            defense += blocker.class_state["LightBlockBonusThisChain"]
        if "combo" in card.keywords:
            for cid in blocker.equipment:
                for mod in effects.parse_play_modifiers(self._cards[cid].text):
                    if mod.condition == "next_defend_combo" and mod.defense:
                        defense += mod.defense
        if blocker.class_state.get("NextDefenseBonus", 0):
            blocker.class_state["NextDefenseBonus"] = 0
            self._event_append(f"+{defense - card.defense} defense bonus on block")
        combat.blocks.append((defender_idx, card.id, defense))
        if combat.attack_card_id:
            attack_card = self._cards.get(combat.attack_card_id)
            if attack_card:
                atk_blob = " ".join(
                    (
                        attack_card.text or "",
                        attack_card.talent or "",
                        attack_card.card_class or "",
                        attack_card.name or "",
                    )
                ).lower()
                if "lightning" in atk_blob or "elemental" in atk_blob:
                    self._fire_equipment_triggers(
                        combat.attacker, "on_lightning_hand_defend", perspective_idx
                    )
                for mod in effects.parse_play_modifiers(attack_card.text):
                    if mod.condition == "defended_by_action_penalty" and mod.power < 0:
                        self._apply_combat_power_bonus(
                            combat,
                            combat.attacker,
                            mod.power,
                            reason=f"{mod.power} power (defended by action)",
                        )
        self._last_event = f"P{defender_idx} blocks with {card.name} (+{defense} defense)"
        reward = self._run_triggers(defender_idx, card, "on_defend", combat, perspective_idx, False)
        if "defense_reaction" in card.card_types:
            reward += self._run_triggers(defender_idx, card, "on_play", combat, perspective_idx, False)
        return reward

    def _do_block_gear(self, defender_idx: int, equip_idx: int, perspective_idx: int = 0) -> float:
        combat = self._pending_combat
        if combat is None:
            self._last_event = "No attack to defend"
            return -0.05
        defender = self._players[defender_idx]
        if equip_idx < 0 or equip_idx >= len(defender.equipment):
            self._last_event = "No such equipment"
            return -0.05
        cid = defender.equipment[equip_idx]
        card = self._cards[cid]
        if card.defense <= 0:
            self._last_event = f"{card.name} cannot block"
            return -0.05
        if f"equip:{cid}" in defender.arena_used:
            self._last_event = f"{card.name} already blocked this turn"
            return -0.05
        defense = self._effective_equipment_defense(defender_idx, cid, card.defense)
        defense += defender.class_state.get("NextDefenseBonus", 0)
        for mod in effects.parse_play_modifiers(card.text):
            if mod.condition and not self._effect_condition_met(
                defender_idx, mod.condition, card, condition_arg=mod.condition_arg
            ):
                continue
            if mod.defense:
                bonus = mod.defense
                if mod.condition == "blue_pitched_each":
                    n_blue = sum(
                        1 for cid in defender.pitch_zone if self._cards[cid].pitch == 3
                    )
                    bonus *= max(0, n_blue)
                defense += bonus
        if defender.class_state.get("NextDefenseBonus", 0):
            defender.class_state["NextDefenseBonus"] = 0
        combat.blocks.append((defender_idx, cid, defense))
        defender.arena_used.add(f"equip:{cid}")
        attack_card = self._cards.get(combat.attack_card_id) if combat.attack_card_id else None
        if attack_card:
            pierce = fab_rules.parse_piercing_value(attack_card.text)
            if pierce > 0:
                self._apply_combat_power_bonus(
                    combat,
                    combat.attacker,
                    pierce,
                    reason=f"piercing +{pierce} power",
                )
        # Battleworn / blade break gear is destroyed after blocking.
        fragile = {"battleworn", "blade_break"} & set(card.keywords)
        if fragile:
            defender.equipment.pop(equip_idx)
            defender.discard.append(cid)
            self._fire_on_leave_triggers(defender_idx, cid)
            self._last_event = (
                f"P{defender_idx} blocks with {card.name} (+{card.defense} defense), destroyed"
            )
        else:
            self._last_event = f"P{defender_idx} blocks with {card.name} (+{card.defense} defense)"
        return self._run_triggers(defender_idx, card, "on_defend", combat, perspective_idx, False)

    def _do_reaction(self, attacker_idx: int, hand_idx: int) -> float:
        combat = self._pending_combat
        if combat is None:
            self._last_event = "No attack in progress"
            return -0.05
        attacker = self._players[attacker_idx]
        card = self._cards[attacker.hand[hand_idx]]
        if "attack_reaction" not in card.card_types:
            self._last_event = f"{card.name} is not an attack reaction"
            return -0.05
        if card.cost > attacker.resources:
            self._last_event = f"Need {card.cost} resources for {card.name}"
            return -0.05
        attacker.resources -= card.cost
        attacker.hand.pop(hand_idx)
        self._apply_combat_power_bonus(
            combat,
            attacker_idx,
            card.power,
            reason=f"+{card.power} power from {card.name}",
        )
        combat.reaction_cards.append(card.id)
        combat.attack_reactions_played += 1
        if "go_again" in card.keywords:
            self._grant_go_again(attacker_idx, combat, this_card=True)
        self._last_event = f"P{attacker_idx} boosts with {card.name} (+{card.power} power)"
        return 0.0

    def _do_weapon_attack(self, player_idx: int, perspective_idx: int = 0) -> float:
        actor = self._players[player_idx]
        if not self._can_weapon_attack(player_idx):
            self._last_event = "Cannot attack with weapon right now"
            return -0.05
        name, attack, cost, weapon_card = self._weapon_stats(player_idx)
        actor.resources -= cost
        actor.action_points -= 1
        if actor.weapon_used:
            actor.class_state["ExtraWeaponAttacks"] = max(
                0, actor.class_state.get("ExtraWeaponAttacks", 0) - 1
            )
            self._event_append("extra weapon attack")
        else:
            actor.weapon_used = True
        actor.class_state["WeaponAttacksThisTurn"] = (
            actor.class_state.get("WeaponAttacksThisTurn", 0) + 1
        )
        keywords = set(weapon_card.keywords) if weapon_card else set()
        combat = CombatState(
            attacker=player_idx,
            defender=1 - player_idx,
            attack_card_id=weapon_card.id if weapon_card else "",
            attack_power=attack,
            blocks=[],
            go_again=("go_again" in keywords),
            dominate=("dominate" in keywords),
            is_weapon=True,
            source_name=name,
        )
        self._pending_combat = combat
        self._last_event = f"P{player_idx} attacks with {name} ({attack})"
        self._record_opponent_attack(
            player_idx,
            attack_name=name,
            attack_power=attack,
            is_weapon=True,
        )
        # A pending "next attack +power" buff also applies to weapon swings.
        if weapon_card is not None:
            self._consume_pending_next_attack_power(
                player_idx, self._cards[weapon_card.id], combat, is_weapon=True
            )
        else:
            self._consume_pending_next_attack_power(
                player_idx,
                Card(
                    id="hero_weapon",
                    name=name,
                    pitch=0,
                    cost=cost,
                    power=attack,
                    defense=0,
                    type_line="",
                    card_types=(),
                    card_class="",
                    talent=None,
                    rarity="",
                    set_code="",
                    keywords=(),
                    text="",
                    legality={},
                ),
                combat,
                is_weapon=True,
            )
        # Weapon on-attack triggers (on-hit fire later in _resolve_and_advance).
        reward = 0.0
        if weapon_card is not None:
            reward += self._run_triggers(player_idx, weapon_card, "on_attack", combat, perspective_idx, False)
        if self._pending_optionals:
            self._optional_resume = "defense"
            self._phase = "optional"
            self._active_player = player_idx
        else:
            self._enter_defense()
        return reward

    def _do_stash(self, player_idx: int, hand_idx: int) -> float:
        actor = self._players[player_idx]
        if actor.arsenal:
            self._last_event = "Arsenal already holds a card"
            return -0.05
        if hand_idx < 0 or hand_idx >= len(actor.hand):
            self._last_event = "No such card to stash"
            return -0.05
        card = self._cards[actor.hand.pop(hand_idx)]
        actor.arsenal.append(card.id)
        self._last_event = f"P{player_idx} stashes {card.name} in arsenal"
        if self._phase == "arsenal":
            self._finish_action_phase(player_idx)
        return 0.0

    def _do_ability(self, player_idx: int, ability_idx: int, perspective_idx: int = 0) -> float:
        entries = self._ability_list(player_idx)
        if ability_idx < 0 or ability_idx >= len(entries):
            self._last_event = "No such ability"
            return -0.05
        entry = entries[ability_idx]
        if not self._ability_usable(player_idx, entry):
            self._last_event = f"Cannot use {entry['name']} ability now"
            return -0.05
        actor = self._players[player_idx]
        ability = entry["ability"]
        cid = entry.get("card_id") or ""
        if ability.counter_cost > 0 and cid:
            if not self._remove_permanent_counter(
                player_idx, cid, ability.counter_name, ability.counter_cost
            ):
                self._last_event = "Not enough counters to activate"
                return -0.05
        if (
            ability.effect.kind == "put_counter"
            and (ability.effect.token_name or "").lower() == "steam"
            and cid
            and self._permanent_counters(player_idx, cid).get("steam", 0) > 0
        ):
            self._last_event = "Already has a steam counter"
            return -0.05
        actor.resources -= max(0, ability.cost - actor.class_state.get("NextAbilityCostReduction", 0))
        if actor.class_state.get("NextAbilityCostReduction", 0) > 0 and ability.cost > 0:
            actor.class_state["NextAbilityCostReduction"] = 0
        if ability.uses_action_point:
            actor.action_points -= 1
        if ability.once_per_turn:
            actor.arena_used.add(entry["token"])
        if ability.destroy_source or ability.discard_source:
            token = entry["token"]
            if token.startswith("equip:"):
                cid = token.split(":", 1)[1]
                if cid in actor.equipment:
                    actor.equipment.remove(cid)
                    actor.discard.append(cid)
                    self._fire_on_leave_triggers(player_idx, cid, perspective_idx)
            elif token.startswith("weapon:"):
                cid = token.split(":", 1)[1]
                if actor.weapon_id == cid:
                    actor.weapon_id = None
                    actor.discard.append(cid)
                    self._fire_on_leave_triggers(player_idx, cid, perspective_idx)
        self._last_event = f"P{player_idx} activates {entry['name']}"
        card_id = entry.get("card_id") or ""
        if card_id and card_id in self._cards:
            card = self._cards[card_id]
        else:
            card = Card(
                id="",
                name=entry["name"],
                pitch=0,
                cost=0,
                power=0,
                defense=0,
                type_line="",
                card_types=(),
                card_class="",
                talent=None,
                rarity="",
                set_code="",
                keywords=(),
                text="",
                legality={},
            )
        effect = ability.effect
        if effect.kind == "attack":
            if self._phase == "action" and self._can_weapon_attack(player_idx):
                return self._do_weapon_attack(player_idx, perspective_idx)
            return 0.0
        reward = self._apply_effect(player_idx, card, effect, None, perspective_idx)
        if ability.grants_go_again:
            self._grant_go_again(player_idx, None, this_card=False)
        return reward

    def _do_instant_play(self, player_idx: int, hand_idx: int, perspective_idx: int = 0) -> float:
        """Play a non-attack action as instant (no action point cost)."""
        actor = self._players[player_idx]
        if not actor.play_as_instant:
            self._last_event = "No instant play available"
            return -0.05
        if hand_idx < 0 or hand_idx >= len(actor.hand):
            self._last_event = "No such card"
            return -0.05
        card = self._cards[actor.hand[hand_idx]]
        if "attack_action" in card.card_types:
            self._last_event = "Only non-attack actions can be played as instant"
            return -0.05
        effective_cost = self._effective_card_cost(player_idx, card)
        if actor.resources < effective_cost:
            self._last_event = f"Need {effective_cost} resources"
            return -0.05
        actor.play_as_instant = False
        actor.resources -= effective_cost
        self._consume_cost_reduction(player_idx, card, effective_cost)
        played_cid = actor.hand[hand_idx]
        actor.hand.pop(hand_idx)
        self._mark_played_from_arsenal(player_idx, played_cid)
        keywords = set(card.keywords)
        go_again = self._go_again_for_play(player_idx, card, True)
        dominate = "dominate" in keywords
        fused = False
        damage, arcane = _parse_action_damage(card.text, card.power, False)
        return self._resolve_direct(
            player_idx, card, damage, arcane, go_again, dominate, fused, (), perspective_idx
        )

    def _apply_ability_effect(
        self, player_idx: int, source_name: str, effect: "effects.Effect", perspective_idx: int
    ) -> float:
        """Resolve an activated-ability effect (no combat chain attached)."""
        card = Card(
            id="",
            name=source_name,
            pitch=0,
            cost=0,
            power=0,
            defense=0,
            type_line="",
            card_types=(),
            card_class="",
            talent=None,
            rarity="",
            set_code="",
            keywords=(),
            text="",
            legality={},
        )
        if effect.kind == "attack":
            if self._phase == "action" and self._can_weapon_attack(player_idx):
                return self._do_weapon_attack(player_idx, perspective_idx)
            return 0.0
        return self._apply_effect(player_idx, card, effect, None, perspective_idx)

    # ------------------------------------------------------------------
    # Phase transitions
    # ------------------------------------------------------------------
    def _enter_defense(self) -> None:
        combat = self._pending_combat
        self._combat_chain_links += 1
        self._phase = "defense"
        self._active_player = combat.defender

    def _enter_reaction(self) -> None:
        combat = self._pending_combat
        self._phase = "reaction"
        self._active_player = combat.attacker

    def _pass_action(self, player_idx: int) -> None:
        self._begin_arsenal_step(player_idx)

    def _pass_defense(self, defender_idx: int) -> None:
        if self._pending_combat is None:
            self._phase = "action"
            return
        self._enter_reaction()

    def _hit_effects_allowed(self, combat: CombatState, attacker_idx: int) -> bool:
        if not combat.hit_effects_blocked:
            return True
        attacker = self._players[attacker_idx]
        cost = max(1, combat.hit_effects_unblock_cost)
        if attacker.resources >= cost:
            attacker.resources -= cost
            self._event_append(f"attacker paid {cost} resources to enable hit effects")
            return True
        self._event_append("hit effects blocked")
        return False

    def _complete_combat_resolution(
        self,
        reward: float,
        perspective_idx: int,
        attacker_idx: int,
        defender_idx: int,
        damage: int,
        go_again: bool,
        fused: bool,
    ) -> float:
        combat = self._pending_combat
        if combat is None:
            return reward
        attack_card = self._cards.get(combat.attack_card_id) if combat.attack_card_id else None
        if attack_card is not None:
            reward += self._fire_chain_close_triggers(
                attacker_idx, attack_card, damage, perspective_idx, fused
            )
        for block_player, b_cid, _ in combat.blocks:
            reward += self._fire_block_chain_close_triggers(
                block_player, self._cards[b_cid], damage, perspective_idx
            )

        self._pending_combat = None
        self._reset_chain_soul_counters()
        self._clear_chain_may_play_grants(attacker_idx)
        self._clear_chain_may_play_grants(defender_idx)
        self._optional_ctx = {"attacker": attacker_idx, "defender": defender_idx, "go_again": go_again}

        if self._pending_optionals:
            self._optional_resume = "advance"
            self._phase = "optional"
            self._active_player = attacker_idx
        else:
            self._finish_combat_advance()

        if damage > 0:
            reward += float(damage) * 0.01 if perspective_idx == attacker_idx else -float(damage) * 0.01
        return reward

    def _resolve_and_advance(self, perspective_idx: int) -> float:
        combat = self._pending_combat
        if combat is None:
            return 0.0
        attacker_idx = combat.attacker
        defender_idx = combat.defender
        attacker = self._players[attacker_idx]
        defender = self._players[defender_idx]
        attack_card = self._cards.get(combat.attack_card_id) if combat.attack_card_id else None

        if attack_card is not None:
            for mod in effects.parse_play_modifiers(attack_card.text):
                if mod.condition != "defended_by_ge_pay":
                    continue
                need = int(mod.condition_arg or "1")
                if len(combat.blocks) < need:
                    continue
                if attacker.resources >= 1:
                    attacker.resources -= 1
                    self._apply_combat_power_bonus(
                        combat,
                        attacker_idx,
                        mod.power,
                        reason=f"Spark Spray: +{mod.power} power",
                    )

        total_block = sum(b[2] for b in combat.blocks)
        total_power = max(
            0,
            combat.attack_power + combat.attack_bonus + combat.opposing_power_mod,
        )
        raw_damage = max(0, total_power - total_block)
        raw_damage = self._apply_damage_floor(attacker_idx, raw_damage)
        damage = self._mitigate_damage(defender_idx, raw_damage)
        defender.life -= damage
        if damage > 0:
            defender.class_state["DamageTakenThisTurn"] = (
                defender.class_state.get("DamageTakenThisTurn", 0) + damage
            )

        # Weapons stay in the arena; action attacks (and reactions) go to discard.
        fused = combat.fused
        if not combat.is_weapon and combat.attack_card_id:
            skip = attacker.class_state.get("SkipGyThisCard", 0)
            if skip == combat.attack_card_id:
                attacker.class_state["SkipGyThisCard"] = 0
            else:
                self._move_card_to_gy(attacker_idx, combat.attack_card_id)
            if attack_card is not None:
                self._run_triggers(attacker_idx, attack_card, "on_gy_enter", None, perspective_idx, fused)
        if (
            attack_card is not None
            and damage == 0
            and (
                "phantasm" in attack_card.keywords
                or "phantasm" in (attack_card.text or "").lower()
            )
        ):
            attacker.class_state["PhantasmDestroyedThisTurn"] = 1
            self._event_append(f"{attack_card.name} destroyed by phantasm")
        attacker.discard.extend(combat.reaction_cards)
        go_again = combat.go_again
        if attacker_idx != 0:
            self._last_event = (
                f"P{attacker_idx} hits P{defender_idx} for {damage} "
                f"(power {total_power} vs block {total_block})"
            )
        self._record_combat_resolution(
            combat,
            attacker_idx=attacker_idx,
            defender_idx=defender_idx,
            attack_card=attack_card,
            total_power=total_power,
            total_block=total_block,
            damage=damage,
        )

        reward = 0.0
        if damage > 0:
            attacker.class_state["LastHitDamage"] = damage
            attacker.class_state["DamageDealt"] += damage
            attacker.class_state["HitCounter"] += 1
            defender.class_state["DamageTaken"] += damage
            if combat.is_weapon:
                attacker.class_state["WeaponHitsThisTurn"] = (
                    attacker.class_state.get("WeaponHitsThisTurn", 0) + 1
                )
            bonus = attacker.class_state.get("BonusHitDamage", 0)
            if bonus > 0:
                extra = self._mitigate_damage(defender_idx, bonus)
                if extra > 0:
                    defender.life -= extra
                    attacker.class_state["DamageDealt"] += extra
                    defender.class_state["DamageTaken"] += extra
                    self._event_append(f"bonus hit damage: {extra}")
            if attack_card is not None and "intimidate" in attack_card.keywords:
                self._do_intimidate(defender_idx)
            if attack_card is not None and not combat.is_weapon:
                attacker.class_state["LastChainAttackPitch"] = attack_card.pitch
            if attack_card is not None:
                reward += self._fire_damage_triggers(
                    attacker_idx, attack_card, damage, perspective_idx, fused
                )
            hit_ok = self._hit_effects_allowed(combat, attacker_idx)
            # On-hit triggers fire only when the attack connects.
            if attack_card is not None and hit_ok:
                reward += self._run_triggers(attacker_idx, attack_card, "on_hit", combat, perspective_idx, fused)
                if self._phase == "choice":
                    self._choice_ctx["combat_finish"] = {
                        "reward": reward,
                        "perspective": perspective_idx,
                        "attacker_idx": attacker_idx,
                        "defender_idx": defender_idx,
                        "damage": damage,
                        "go_again": go_again,
                        "fused": fused,
                    }
                    return reward
            if damage > 0 and attacker.class_state.get("NextAttackOnHitExtraWeapon", 0):
                attacker.class_state["NextAttackOnHitExtraWeapon"] = 0
                attacker.class_state["ExtraWeaponAttacks"] = (
                    attacker.class_state.get("ExtraWeaponAttacks", 0) + 1
                )
                self._event_append("extra weapon attack granted on hit")
            if damage > 0 and attack_card is not None and "stealth" in attack_card.keywords:
                attacker.class_state["StealthHitThisTurn"] = 1
            if hit_ok:
                reward += self._fire_controlled_hit_triggers(attacker_idx, perspective_idx, fused)
                reward += self._fire_chain_hit_triggers(attacker_idx, perspective_idx)
                if combat.is_weapon:
                    reward += self._fire_equipment_triggers(
                        attacker_idx, "on_weapon_hit", perspective_idx
                    )
                    weapon_id = attacker.weapon_id
                    if weapon_id and "gun" in self._cards[weapon_id].name.lower():
                        reward += self._fire_equipment_triggers(
                            attacker_idx, "on_gun_hit", perspective_idx
                        )

        return self._complete_combat_resolution(
            reward,
            perspective_idx,
            attacker_idx,
            defender_idx,
            damage,
            go_again,
            fused,
        )

    # ------------------------------------------------------------------
    # Self-play transition (single policy controls the active player)
    # ------------------------------------------------------------------
    def _step_self_play(self, parsed: str) -> float:
        player = self._active_player

        if self._phase == "action":
            if parsed == "pass":
                self._last_event = f"P{player} passed turn"
                self._pass_action(player)
                return 0.0
            if parsed.startswith("pitch "):
                return self._do_pitch(player, int(parsed.split(" ")[1]))
            if parsed.startswith("play "):
                return self._do_play_card(player, int(parsed.split(" ")[1]), player)
            if parsed.startswith("banishplay "):
                return self._do_play_banished(player, int(parsed.split(" ")[1]), player)
            if parsed.startswith("gyplay "):
                return self._do_play_graveyard(player, int(parsed.split(" ")[1]), player)
            if parsed == "weapon":
                return self._do_weapon_attack(player, player)
            if parsed.startswith("ability "):
                return self._do_ability(player, int(parsed.split(" ")[1]), player)
            if parsed == "deckplay":
                return self._do_play_deck_top(player, player)
            if parsed.startswith("mayplay "):
                parts = parsed.split(" ")
                return self._do_may_play(player, parts[1], int(parts[2]), player)
            return 0.0

        if self._phase == "arsenal":
            if parsed == "pass":
                self._last_event = f"P{player} skipped arsenal stash"
                self._pass_arsenal(player)
                return 0.0
            if parsed.startswith("stash "):
                return self._do_stash(player, int(parsed.split(" ")[1]))
            return 0.0

        if self._phase == "defense":
            if parsed == "pass":
                self._pass_defense(player)
                return 0.0
            if parsed.startswith("block "):
                return self._do_block(player, int(parsed.split(" ")[1]))
            if parsed.startswith("blockgear "):
                return self._do_block_gear(player, int(parsed.split(" ")[1]))
            if parsed.startswith("instant "):
                return self._do_instant_play(player, int(parsed.split(" ")[1]), player)
            if parsed == "deckplay":
                return self._do_play_deck_top(player, player)
            if parsed.startswith("mayplay "):
                parts = parsed.split(" ")
                return self._do_may_play(player, parts[1], int(parts[2]), player)
            return 0.0

        if self._phase == "reaction":
            if parsed == "pass":
                return self._resolve_and_advance(player)
            if parsed.startswith("reaction "):
                return self._do_reaction(player, int(parsed.split(" ")[1]))
            if parsed.startswith("instant "):
                return self._do_instant_play(player, int(parsed.split(" ")[1]), player)
            if parsed == "deckplay":
                return self._do_play_deck_top(player, player)
            if parsed.startswith("mayplay "):
                parts = parsed.split(" ")
                return self._do_may_play(player, parts[1], int(parts[2]), player)
            return 0.0

        if self._phase == "optional":
            return self._do_optional(parsed == "use_optional")

        if self._phase == "choice":
            if parsed == "pass":
                return self._resolve_card_choice(None)
            if parsed.startswith("choose "):
                return self._resolve_card_choice(int(parsed.split()[1]))
            return 0.0

        if self._phase == "opt":
            if parsed == "opt_bottom":
                self._do_opt_choice(player, to_bottom=True)
            elif parsed == "opt_top":
                self._do_opt_choice(player, to_bottom=False)
            return 0.0

        return 0.0

    # ------------------------------------------------------------------
    # Opponent automation (non-self-play): drive player 1 until it is the
    # agent's turn to decide, or the game ends.
    # ------------------------------------------------------------------
    def _auto_advance(self) -> float:
        accum = 0.0
        guard = 0
        while not self._is_terminal() and guard < 2000:
            guard += 1
            phase = self._phase
            if self._active_player == 0:
                if phase == "action":
                    return accum
                if phase == "arsenal":
                    return accum
                if phase == "optional":
                    return accum
                if phase == "choice":
                    return accum
                if phase == "opt":
                    return accum
                if phase == "defense":
                    if self._legal_blocks(0) or self._legal_gear_blocks(0):
                        return accum
                    self._pass_defense(0)
                    continue
                if phase == "reaction":
                    if self._legal_reactions(0):
                        return accum
                    accum += self._resolve_and_advance(0)
                    continue
                return accum

            # Opponent (player 1) to act.
            if phase == "action":
                accum += self._opponent_action()
            elif phase == "arsenal":
                accum += self._opponent_arsenal_action()
            elif phase == "optional":
                accum += self._do_optional(True)
            elif phase == "choice":
                ctx = self._choice_ctx
                if ctx and ctx.get("options"):
                    if ctx.get("kind") == "mode":
                        if ctx.get("pick_any") and self._rng.random() < 0.3:
                            accum += self._resolve_mode_choice(None)
                        else:
                            pick = self._rng.randrange(len(ctx["options"]))
                            accum += self._resolve_mode_choice(pick)
                    else:
                        pick = self._rng.randrange(len(ctx["options"]))
                        accum += self._resolve_card_choice(pick)
            elif phase == "opt":
                self._do_opt_choice(1, to_bottom=False)
            elif phase == "defense":
                self._opponent_block()
            elif phase == "reaction":
                accum += self._resolve_and_advance(0)
            else:
                return accum
        return accum

    def _opponent_prepare_resources(self, budget: int = 3) -> None:
        """Auto-pitch low-value cards so the scripted opponent can afford a play."""
        opp = self._players[1]
        guard = 0
        while opp.resources < budget and guard < 12:
            guard += 1
            best_idx: Optional[int] = None
            best_rank: Optional[tuple[int, int]] = None
            for i, cid in enumerate(opp.hand):
                card = self._cards[cid]
                if card.pitch <= 0:
                    continue
                # Prefer pitching non-attacks and weaker cards.
                is_attack = 1 if "attack_action" in card.card_types else 0
                rank = (is_attack, card.power + card.defense)
                if best_rank is None or rank < best_rank:
                    best_rank = rank
                    best_idx = i
            if best_idx is None:
                break
            self._do_pitch(1, best_idx)

    def _opponent_action(self) -> float:
        opp = self._players[1]
        self._opponent_prepare_resources()
        try:
            idx = self._opponent_policy.select_attack_index(self)
        except Exception:
            self._opponent_type = "preset_logic"
            self._opponent_policy = self._build_opponent_policy(self._opponent_type)
            idx = self._opponent_policy.select_attack_index(self)
        # Guard against an unplayable pick (e.g. unmet requirement) so the
        # opponent never stalls the action phase.
        if (
            idx is None
            or idx < 0
            or idx >= len(opp.hand)
            or idx not in self._legal_plays(1)
        ):
            # No worthwhile card play: swing with the weapon if able, else pass.
            if self._can_weapon_attack(1):
                return self._do_weapon_attack(1, 0)
            self._last_event = "Opponent passed"
            self._pass_action(1)
            return 0.0
        return self._do_play_card(1, idx, 0)

    def _opponent_arsenal_action(self) -> float:
        legal = self._legal_stash(1)
        if not legal:
            self._pass_arsenal(1)
            return 0.0
        opp = self._players[1]
        best_idx: Optional[int] = None
        best_rank: Optional[tuple[int, int]] = None
        for i in legal:
            card = self._cards[opp.hand[i]]
            is_attack = 1 if "attack_action" in card.card_types else 0
            rank = (is_attack, -card.defense)
            if best_rank is None or rank < best_rank:
                best_rank = rank
                best_idx = i
        if best_idx is not None:
            card = self._cards[opp.hand[best_idx]]
            if card.defense >= 3 or "attack_action" not in card.card_types:
                return self._do_stash(1, best_idx)
        self._pass_arsenal(1)
        return 0.0

    def _opponent_block(self) -> None:
        combat = self._pending_combat
        if combat is None or combat.defender != 1:
            self._pass_defense(1)
            return
        defender = self._players[1]
        guard = 0
        while combat is self._pending_combat and guard < 12:
            guard += 1
            remaining = combat.attack_power + combat.attack_bonus - sum(b[2] for b in combat.blocks)
            if remaining <= 0:
                break
            if combat.dominate and self._defender_hand_blocks(combat, 1):
                break
            try:
                bidx = self._opponent_policy.select_block_index(self)
            except Exception:
                self._opponent_type = "preset_logic"
                self._opponent_policy = self._build_opponent_policy(self._opponent_type)
                bidx = self._opponent_policy.select_block_index(self)
            if bidx is None or bidx < 0 or bidx >= len(defender.hand):
                break
            self._do_block(1, bidx)
        # Soak remaining damage with equipment before taking the hit.
        guard = 0
        while combat is self._pending_combat and guard < 8:
            guard += 1
            remaining = combat.attack_power + combat.attack_bonus - sum(b[2] for b in combat.blocks)
            if remaining <= 0:
                break
            gear = self._legal_gear_blocks(1)
            if not gear:
                break
            self._do_block_gear(1, gear[0])
        self._pass_defense(1)

    def _legal_actions(self) -> list[str]:
        if self._selection_stage:
            return [f"choose_deck {o['key']}" for o in self._deck_options_for_format()]
        if not self._initialized or len(self._players) < 2:
            return ["pass"]
        if self._is_terminal():
            return []

        actor_idx = self._active_player
        if not self._self_play and actor_idx != 0:
            return ["pass"]

        if self._phase == "action":
            actions = ["pass"]
            actions.extend(f"pitch {i}" for i in self._legal_pitches(actor_idx))
            actions.extend(f"play {i}" for i in self._legal_plays(actor_idx))
            actions.extend(f"banishplay {i}" for i in self._legal_banished_plays(actor_idx))
            actions.extend(f"gyplay {i}" for i in self._legal_graveyard_plays(actor_idx))
            if self._can_weapon_attack(actor_idx):
                actions.append("weapon")
            actions.extend(f"ability {i}" for i in self._legal_abilities(actor_idx))
            if self._can_deck_top_play_now(actor_idx):
                actions.append("deckplay")
            actions.extend(self._legal_may_plays(actor_idx))
            return actions

        if self._phase == "arsenal":
            if actor_idx != self._action_phase_player:
                return ["pass"]
            actions = ["pass"]
            actions.extend(f"stash {i}" for i in self._legal_stash(actor_idx))
            return actions

        if self._phase == "defense":
            if self._pending_combat is None or self._pending_combat.defender != actor_idx:
                return ["pass"]
            actions = ["pass"]
            actions.extend(f"block {i}" for i in self._legal_blocks(actor_idx))
            actions.extend(f"blockgear {i}" for i in self._legal_gear_blocks(actor_idx))
            actions.extend(f"instant {i}" for i in self._legal_instant_plays(actor_idx))
            if self._can_deck_top_play_now(actor_idx):
                actions.append("deckplay")
            actions.extend(self._legal_may_plays(actor_idx))
            return actions

        if self._phase == "reaction":
            if self._pending_combat is None or self._pending_combat.attacker != actor_idx:
                return ["pass"]
            actions = ["pass"]
            actions.extend(f"reaction {i}" for i in self._legal_reactions(actor_idx))
            actions.extend(f"instant {i}" for i in self._legal_instant_plays(actor_idx))
            if self._can_deck_top_play_now(actor_idx):
                actions.append("deckplay")
            actions.extend(self._legal_may_plays(actor_idx))
            return actions

        if self._phase == "optional":
            if not self._pending_optionals or self._pending_optionals[0]["player"] != actor_idx:
                return ["pass"]
            return ["use_optional", "pass"]

        if self._phase == "choice":
            ctx = self._choice_ctx
            if not ctx or ctx.get("chooser") != actor_idx:
                return ["pass"]
            actions = [f"choose {o['index']}" for o in ctx.get("options", [])]
            if ctx.get("optional"):
                actions.append("pass")
            return actions or ["pass"]

        if self._phase == "opt":
            if not self._opt_ctx or self._opt_ctx.get("player") != actor_idx:
                return ["pass"]
            return ["opt_top", "opt_bottom"]

        return ["pass"]

    def _arena_view(self, player_idx: int, reveal: bool) -> dict[str, Any]:
        """Equipment / weapon / hero / arsenal zones for the observation."""
        p = self._players[player_idx]
        equipment = []
        for cid in p.equipment:
            c = self._cards[cid]
            equipment.append(
                {
                    "id": c.id,
                    "name": c.name,
                    "slot": _equipment_slot(c),
                    "defense": c.defense,
                    "keywords": list(c.keywords),
                    "text": c.text,
                    "used": f"equip:{cid}" in p.arena_used,
                }
            )
        hero_ability = next(
            (a for a in effects.parse_activated_abilities(p.hero.ability_text) if a.implemented),
            None,
        )
        wname, wattack, wcost, wcard = self._weapon_stats(player_idx)
        arena = {
            "equipment": equipment,
            "weapon": {
                "name": wname,
                "attack": wattack,
                "cost": wcost,
                "used": p.weapon_used,
                "text": wcard.text if wcard else "",
            },
            "hero_ability_text": p.hero.ability_text,
            "hero_ability_usable": bool(hero_ability),
            "arsenal_size": len(p.arsenal),
        }
        if reveal:
            arena["abilities"] = [
                {
                    "index": i,
                    "source": e["name"],
                    "summary": e["ability"].effect.raw or e["ability"].raw,
                    "cost": e["ability"].cost,
                    "usable": self._ability_usable(player_idx, e),
                }
                for i, e in enumerate(self._ability_list(player_idx))
            ]
            arena["arsenal"] = [self._cards[cid].name for cid in p.arsenal]
        return arena

    def _optional_decision_view(self) -> Optional[dict[str, Any]]:
        """Describe the pending optional decision for the agent, if any."""
        if self._phase != "optional" or not self._pending_optionals:
            return None
        opt = self._pending_optionals[0]
        if opt["player"] != 0:
            return None
        eff = opt["effect"]
        card = self._cards[opt["card_id"]]
        if eff.kind == "banish_combo":
            rider = f"+{eff.amount} power" + (" and go again" if eff.go_again else "")
            desc = f"banish {eff.banish_name} from your graveyard for {rider}"
        elif eff.kind == "destroy_item" and (eff.banish_name or "").lower() == "reroll_d6":
            desc = "destroy Gambler's Gloves to reroll the die"
        elif eff.kind in ("damage", "arcane_damage"):
            desc = f"deal {eff.amount} {'arcane ' if eff.kind == 'arcane_damage' else ''}damage"
        elif eff.kind == "power":
            desc = f"give +{eff.amount} power"
        elif eff.kind == "draw":
            desc = f"draw {eff.amount}"
        elif eff.kind == "go_again":
            desc = "gain go again"
        elif eff.kind == "boost":
            desc = "banish top of deck for boost (Mechanologist: go again)"
        elif eff.kind in ("reload", "stash_hand"):
            desc = "reload: stash a card from hand into arsenal"
        else:
            desc = eff.raw
        return {"card": card.name, "description": desc}

    def _choice_decision_view(self) -> Optional[dict[str, Any]]:
        if self._phase != "choice" or not self._choice_ctx:
            return None
        ctx = self._choice_ctx
        if ctx.get("chooser") != 0:
            return None
        return {
            "prompt": ctx.get("prompt", "Choose a card"),
            "optional": bool(ctx.get("optional")),
            "options": [
                {"index": o["index"], "name": o["name"]} for o in ctx.get("options", [])
            ],
        }

    def _is_terminal(self) -> bool:
        if not self._players:
            return False
        return self._players[0].life <= 0 or self._players[1].life <= 0

    def _normalize_action(self, action: Any) -> str:
        if self._selection_stage and isinstance(action, str):
            return action.strip().lower()
        if isinstance(action, int):
            if self._phase == "optional":
                return "use_optional" if action == 0 else "pass"
            if self._phase == "choice":
                ctx = self._choice_ctx
                if ctx and action < len(ctx.get("options", [])):
                    return f"choose {action}"
                return "pass"
            if self._phase == "opt":
                return "opt_top" if action == 0 else "opt_bottom"
            if self._phase == "action":
                return f"play {action}"
            if self._phase == "defense":
                return f"block {action}"
            if self._phase == "reaction":
                return f"reaction {action}"
        text = str(action).strip().lower()
        if text in {"pass", "end", "end turn"}:
            return "pass"
        if text in {"weapon", "attack weapon", "weapon attack"}:
            return "weapon"
        for verb in ("banishplay", "gyplay", "play", "block", "pitch", "reaction", "ability", "stash", "blockgear", "instant"):
            if text.startswith(verb):
                parts = text.split()
                if len(parts) == 2 and parts[1].isdigit():
                    return f"{verb} {parts[1]}"
        return text

    def _record_combat_resolution(
        self,
        combat: CombatState,
        *,
        attacker_idx: int,
        defender_idx: int,
        attack_card: Optional[Card],
        total_power: int,
        total_block: int,
        damage: int,
    ) -> None:
        if combat.is_weapon or not combat.attack_card_id:
            attack_name = combat.source_name or "Weapon"
        elif attack_card is not None:
            attack_name = attack_card.name
        else:
            attack_name = "Attack"
        summary = {
            "attacker": attacker_idx,
            "defender": defender_idx,
            "attack_card": attack_name,
            "attack_power": total_power,
            "total_block": total_block,
            "damage": damage,
            "blocks": [
                self._combat_block_view(block_player, cid, def_val)
                for block_player, cid, def_val in combat.blocks
            ],
        }
        if attacker_idx == 0:
            self._last_combat_summary = summary
            block_text = self._format_combat_blocks_text(summary["blocks"], defender_idx)
            outcome = f"{damage} damage" if damage > 0 else "no damage"
            self._last_event = (
                f"You attacked with {attack_name} ({total_power} power vs {total_block} block) "
                f"→ {outcome}"
                + (f" | Opponent blocked: {block_text}" if block_text else " | Opponent did not block")
            )

    @staticmethod
    def _format_combat_blocks_text(blocks: list[dict[str, Any]], defender_idx: int) -> str:
        defender_blocks = [b for b in blocks if int(b.get("player", -1)) == defender_idx]
        if not defender_blocks:
            return ""
        parts: list[str] = []
        for block in defender_blocks:
            name = block.get("name", "?")
            defense = int(block.get("defense") or 0)
            if block.get("kind") == "equipment":
                slot = block.get("slot") or "gear"
                parts.append(f"{name} [{slot}] (def {defense})")
            else:
                parts.append(f"{name} (def {defense})")
        return ", ".join(parts)

    def _combat_block_view(self, block_player: int, cid: str, defense: int) -> dict[str, Any]:
        card = self._cards[cid]
        player = self._players[block_player]
        if cid in player.equipment:
            kind = "equipment"
            slot = _equipment_slot(card) or ""
        else:
            kind = "hand"
            slot = ""
        return {
            "player": block_player,
            "name": card.name,
            "defense": defense,
            "kind": kind,
            "slot": slot,
        }

    def _observation(self) -> dict[str, Any]:
        if self._selection_stage:
            return {
                "turn": self._turn,
                "format": self._format,
                "stage": "deck_selection",
                "phase": self._phase,
                "active_player": self._active_player,
                "opponent_type": self._opponent_type,
                "deck_options": self._deck_options_for_format(),
                "selected_deck": self._selected_deck_option,
                "matchup": self._selected_opponent_deck_option,
                "legal_actions": self._legal_actions(),
                "last_event": self._last_event,
            }

        agent = self._players[0]
        opp = self._players[1]

        hand_view = []
        for i, cid in enumerate(agent.hand):
            c = self._cards[cid]
            is_attack = "attack_action" in c.card_types
            damage, arcane = _parse_action_damage(c.text, c.power, is_attack)
            elements, fusable = self._fusion_state(0, i, c)
            hand_view.append(
                {
                    "index": i,
                    "id": c.id,
                    "name": c.name,
                    "pitch": c.pitch,
                    "cost": c.cost,
                    "power": c.power,
                    "defense": c.defense,
                    "card_types": list(c.card_types),
                    "keywords": list(c.keywords),
                    "text": c.text,
                    "damage": damage,
                    "arcane": arcane,
                    "fusion_element": elements[0] if elements else None,
                    "fusion_elements": list(elements),
                    "fusable": fusable,
                }
            )

        pending = None
        if self._pending_combat is not None:
            pc = self._pending_combat
            if pc.is_weapon or not pc.attack_card_id:
                attack_name = pc.source_name or "Weapon"
            else:
                attack_name = self._cards[pc.attack_card_id].name
            pending = {
                "attacker": pc.attacker,
                "defender": pc.defender,
                "attack_card": attack_name,
                "attack_power": pc.attack_power + pc.attack_bonus,
                "attack_bonus": pc.attack_bonus,
                "total_block": sum(b[2] for b in pc.blocks),
                "go_again": pc.go_again,
                "dominate": pc.dominate,
                "chain_link": self._combat_chain_links,
                "blocks": [
                    self._combat_block_view(block_player, cid, def_val)
                    for block_player, cid, def_val in pc.blocks
                ],
            }

        return {
            "turn": self._turn,
            "format": self._format,
            "stage": "play",
            "phase": self._phase,
            "flow_stage": self._flow_stage,
            "flow_segment": self._flow_segment_label(),
            "action_phase_player": self._action_phase_player,
            "combat_chain_links": self._combat_chain_links,
            "active_player": self._active_player,
            "opponent_type": self._opponent_type,
            "selected_deck": self._selected_deck_option,
            "matchup": self._selected_opponent_deck_option,
            "agent": {
                "hero": agent.hero.name,
                "life": agent.life,
                "resources": agent.resources,
                "action_points": agent.action_points,
                "deck": len(agent.deck),
                "discard": len(agent.discard),
                "banished": [
                    {"index": i, "name": self._cards[cid].name, "playable": self._can_play_from_banished(0, cid)}
                    for i, cid in enumerate(agent.banished)
                ],
                "tokens": dict(agent.tokens),
                "gold": agent.gold,
                "hand": hand_view,
                "class_state": dict(agent.class_state),
                "arena": self._arena_view(0, reveal=True),
            },
            "opponent": {
                "hero": opp.hero.name,
                "life": opp.life,
                "resources": opp.resources,
                "action_points": opp.action_points,
                "deck": len(opp.deck),
                "discard": len(opp.discard),
                "banished": len(opp.banished),
                "tokens": dict(opp.tokens),
                "gold": opp.gold,
                "hand_size": len(opp.hand),
                "class_state": dict(opp.class_state),
                "arena": self._arena_view(1, reveal=False),
            },
            "pending_combat": pending,
            "last_combat": self._last_combat_summary,
            "last_opponent_turn": self._last_opponent_turn,
            "optional_decision": self._optional_decision_view(),
            "choice_decision": self._choice_decision_view(),
            "legal_actions": self._legal_actions(),
            "last_event": self._last_event,
            "notices": list(self._notices),
        }

    def _estimate_win_probabilities(self, obs: Optional[dict[str, Any]] = None) -> tuple[float, float]:
        """Heuristic win probability estimate from current FaB state.

        Returns ``(agent_win_prob, opponent_win_prob)``.
        """
        if obs is None:
            obs = self._observation()

        if obs.get("stage") == "deck_selection":
            return 0.5, 0.5

        agent = obs.get("agent") if isinstance(obs.get("agent"), dict) else {}
        opp = obs.get("opponent") if isinstance(obs.get("opponent"), dict) else {}

        agent_life = float(agent.get("life", 0.0))
        opp_life = float(opp.get("life", 0.0))

        if opp_life <= 0 < agent_life:
            return 1.0, 0.0
        if agent_life <= 0 < opp_life:
            return 0.0, 1.0

        agent_hand_size = len(agent.get("hand", [])) if isinstance(agent.get("hand"), list) else 0
        opp_hand_size = int(opp.get("hand_size", 0) or 0)
        agent_resources = float(agent.get("resources", 0.0))
        opp_resources = float(opp.get("resources", 0.0))
        agent_ap = float(agent.get("action_points", 0.0))
        opp_ap = float(opp.get("action_points", 0.0))
        agent_deck = float(agent.get("deck", 0.0))
        opp_deck = float(opp.get("deck", 0.0))

        agent_score = (
            1.8 * agent_life
            + 1.0 * agent_hand_size
            + 0.6 * agent_resources
            + 0.8 * agent_ap
            + 0.05 * agent_deck
        )
        opp_score = (
            1.8 * opp_life
            + 1.0 * opp_hand_size
            + 0.6 * opp_resources
            + 0.8 * opp_ap
            + 0.05 * opp_deck
        )

        pending = obs.get("pending_combat")
        if isinstance(pending, dict):
            atk = float(pending.get("attack_power", 0.0) or 0.0)
            blk = float(pending.get("total_block", 0.0) or 0.0)
            net = max(0.0, atk - blk)
            attacker = int(pending.get("attacker", 0) or 0)
            if attacker == 0:
                agent_score += 1.5 * net
            else:
                opp_score += 1.5 * net

        active_player = int(obs.get("active_player", 0) or 0)
        if active_player == 0:
            agent_score += 0.4
        else:
            opp_score += 0.4

        diff = (agent_score - opp_score) / 8.0
        agent_p = 1.0 / (1.0 + math.exp(-diff))
        agent_p = max(0.0, min(1.0, agent_p))
        return agent_p, 1.0 - agent_p

    def _render_text(self) -> str:
        obs = self._observation()
        if obs.get("stage") == "deck_selection":
            lines = [
                "Flesh and Blood (Talishar-inspired)",
                f"Format: {obs['format']} | Stage: deck_selection",
                "Choose a deck:",
            ]
            for item in obs.get("deck_options", []):
                lines.append(f"  - {item['label']} ({item['deck_size']} cards) -> choose_deck {item['key']}")
            lines.append("Legal actions: " + ", ".join(obs.get("legal_actions", [])))
            return "\n".join(lines)

        p_agent, p_opp = self._estimate_win_probabilities(obs)
        lines = [
            "Flesh and Blood (Talishar-inspired)",
            f"Turn: {obs['turn']} | Format: {obs['format']} | Phase: {obs['phase']} | Active: P{obs['active_player']}",
            f"Agent ({obs['agent']['hero']}): life={obs['agent']['life']} hand={len(obs['agent']['hand'])} resources={obs['agent']['resources']} AP={obs['agent']['action_points']}",
            f"Opponent ({obs['opponent']['hero']}): life={obs['opponent']['life']} hand={obs['opponent']['hand_size']} resources={obs['opponent']['resources']} AP={obs['opponent']['action_points']}",
            f"Win % | Agent: {p_agent:.1%}  Opponent: {p_opp:.1%}",
            f"Last event: {obs['last_event']}",
            "Legal actions: " + ", ".join(obs["legal_actions"]),
        ]
        if obs["pending_combat"]:
            lines.append(
                "Combat: "
                f"{obs['pending_combat']['attack_card']} "
                f"atk={obs['pending_combat']['attack_power']} "
                f"block={obs['pending_combat']['total_block']}"
            )
        return "\n".join(lines)

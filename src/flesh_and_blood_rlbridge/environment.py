    def _apply_hero_passives(self, player_idx: int) -> None:
        """Apply always-on hero ability text (e.g. Dash deck-top item play)."""
        actor = self._players[player_idx]
        text = actor.hero.ability_text
        if not text.strip():
            return
        proxy_id = actor.weapon_id or (actor.equipment[0] if actor.equipment else None)
        if not proxy_id:
            return
        proxy = self._cards[proxy_id]
        grants: list[dict[str, Any]] = []
        for trig in effects.parse_triggers(text):
            if trig.effect.kind == "play_from_deck_top":
                self._apply_effect(player_idx, proxy, trig.effect, None, player_idx)
            elif trig.effect.kind == "grant_may_play":
                grants.append(self._may_play_grant_from_effect(trig.effect))
        body = effects._clean(text)
        for sent in re.split(r"(?<=[.!?])\s+", body):
            eff = effects._parse_grant_may_play(
                " ".join(sent.lower().split()),
                sent.strip(),
                optional=False,
                condition="",
            )
            if eff is None or not eff.implemented:
                continue
            if eff.condition != "static" and "if it's not your turn" not in sent.lower():
                continue
            grants.append(self._may_play_grant_from_effect(eff))
        actor.hero_may_play_grants = grants
        actor.may_play_grants = list(grants)
        if grants:
            self._event_append("hero may-play abilities active")

    def _mark_played_from_arsenal(self, player_idx: int, card_id: str) -> None:
        actor = self._players[player_idx]
        if card_id in actor.hand_from_arsenal:
            actor.class_state["PlayedFromArsenal"] = 1
            actor.hand_from_arsenal.discard(card_id)

    def _deck_top_playable_card(self, player_idx: int) -> Optional[str]:
        actor = self._players[player_idx]
        if not actor.deck_top_play_class or actor.deck_top_play_used:
            return None
        cid = self._deck_top_card_id(player_idx)
        if not cid:
            return None
        card = self._cards[cid]
        if not self._is_arena_permanent(card):
            return None
        if card.cost > 1:
            return None
        if actor.deck_top_play_class not in (card.card_class or "").lower():
            return None
        return cid

    def _can_deck_top_play_now(self, player_idx: int) -> bool:
        cid = self._deck_top_playable_card(player_idx)
        if not cid:
            return False
        actor = self._players[player_idx]
        card = self._cards[cid]
        cost = card.cost + actor.deck_top_play_extra_cost
        if actor.resources < cost:
            return False
        if self._phase == "action" and self._active_player == player_idx:
            return True
        if self._phase in ("defense", "reaction") and self._active_player == player_idx:
            return True
        return False

    def _do_play_deck_top(self, player_idx: int, perspective_idx: int = 0) -> float:
        cid = self._deck_top_playable_card(player_idx)
        if not cid or not self._can_deck_top_play_now(player_idx):
            self._last_event = "Cannot play from deck top"
            return -0.05
        actor = self._players[player_idx]
        card = self._cards[cid]
        cost = card.cost + actor.deck_top_play_extra_cost
        actor.resources -= cost
        if actor.deck and actor.deck[-1] == cid:
            actor.deck.pop()
        else:
            actor.deck.remove(cid)
        actor.deck_top_play_used = True
        actor.equipment.append(cid)
        self._fire_enters_triggers(player_idx, card)
        self._last_event = f"P{player_idx} played {card.name} from deck top"
        return 0.0

    def _may_play_grant_from_effect(self, effect: "effects.Effect") -> dict[str, Any]:
        return {
            "zone": effect.target or "hand",
            "filter": (effect.banish_name or "").lower(),
            "pitch": effect.amount or 0,
            "class_filter": (effect.token_name or "").lower(),
            "chain_only": effect.condition == "chain_only",
            "not_own_turn": effect.condition == "not_own_turn",
            "free_cost": effect.condition == "free_cost",
            "static": effect.condition == "static",
        }

    def _append_may_play_grant(self, player_idx: int, effect: "effects.Effect") -> None:
        grant = self._may_play_grant_from_effect(effect)
        self._players[player_idx].may_play_grants.append(grant)
        zone = grant["zone"]
        filt = grant["filter"] or "action"
        self._event_append(f"may play {filt} from {zone} as instant")

    def _register_static_may_play_from_text(self, player_idx: int, text: str) -> None:
        if not text.strip():
            return
        grants: list[dict[str, Any]] = []
        for trig in effects.parse_triggers(text):
            if trig.effect.kind == "grant_may_play" and trig.effect.condition == "static":
                grants.append(self._may_play_grant_from_effect(trig.effect))
        body = effects._clean(text)
        for sent in re.split(r"(?<=[.!?])\s+", body):
            eff = effects._parse_grant_may_play(
                " ".join(sent.lower().split()),
                sent.strip(),
                optional=False,
                condition="",
            )
            if eff is not None and eff.implemented and eff.condition == "static":
                grants.append(
                    self._may_play_grant_from_effect(
                        effects.Effect(
                            eff.kind,
                            eff.amount,
                            eff.raw,
                            target=eff.target,
                            banish_name=eff.banish_name,
                            token_name=eff.token_name,
                            condition="static",
                        )
                    )
                )
        for grant in grants:
            self._players[player_idx].may_play_grants.append(grant)

    def _clear_chain_may_play_grants(self, player_idx: int) -> None:
        actor = self._players[player_idx]
        actor.may_play_grants = [g for g in actor.may_play_grants if not g.get("chain_only")]

    def _is_own_action_phase(self, player_idx: int) -> bool:
        return self._phase == "action" and self._action_phase_player == player_idx

    def _may_play_timing_ok(self, player_idx: int, grant: dict[str, Any]) -> bool:
        if grant.get("chain_only"):
            if self._pending_combat is None:
                return False
            if self._phase not in ("defense", "reaction", "action"):
                return False
            return True
        if grant.get("not_own_turn"):
            return not self._is_own_action_phase(player_idx)
        if self._phase in ("defense", "reaction"):
            return True
        if self._phase == "action" and self._active_player == player_idx:
            return True
        return False

    def _card_matches_may_play_grant(self, card: Card, grant: dict[str, Any]) -> bool:
        filt = grant.get("filter") or ""
        if filt == "non-attack" and "attack_action" in card.card_types:
            return False
        if filt == "aura":
            tl = (card.type_line or "").lower()
            if " aura" not in tl and not tl.endswith("aura"):
                return False
        elif filt == "evo":
            if "evo" not in card.name.lower():
                return False
        elif filt == "face_up":
            pass
        elif filt and filt not in ("non-attack", "aura", "evo", "face_up"):
            if filt not in card.name.lower() and filt not in (card.text or "").lower():
                return False
        pitch = grant.get("pitch") or 0
        if pitch and card.pitch != pitch:
            return False
        cls_filter = grant.get("class_filter") or ""
        if cls_filter and cls_filter not in (card.card_class or "").lower():
            return False
        zone = grant.get("zone") or "hand"
        if zone == "hand" and filt == "non-attack":
            if "utility_action" not in card.card_types:
                return False
        return True

    def _may_play_cards_in_zone(self, player_idx: int, zone: str) -> list[str]:
        actor = self._players[player_idx]
        if zone == "hand":
            return list(actor.hand)
        if zone == "arsenal":
            return list(actor.arsenal)
        if zone == "banished":
            return list(actor.banished)
        if zone == "opponent_banished":
            return list(self._players[1 - player_idx].banished)
        if zone == "opponent_arsenal":
            return list(self._players[1 - player_idx].arsenal)
        return []

    def _legal_may_plays(self, actor_idx: int) -> list[str]:
        actor = self._players[actor_idx]
        legal: list[str] = []
        for grant in actor.may_play_grants:
            if not self._may_play_timing_ok(actor_idx, grant):
                continue
            zone = grant.get("zone") or "hand"
            for i, cid in enumerate(self._may_play_cards_in_zone(actor_idx, zone)):
                card = self._cards[cid]
                if not self._card_matches_may_play_grant(card, grant):
                    continue
                if zone == "hand" and self._play_blocked_reason(actor_idx, i, card):
                    continue
                cost = 0 if grant.get("free_cost") else card.cost
                if cost > actor.resources:
                    continue
                legal.append(f"mayplay {zone} {i}")
        return legal

    def _do_may_play(self, player_idx: int, zone: str, idx: int, perspective_idx: int = 0) -> float:
        actor = self._players[player_idx]
        cards = self._may_play_cards_in_zone(player_idx, zone)
        if idx < 0 or idx >= len(cards):
            self._last_event = "No such card to play"
            return -0.05
        cid = cards[idx]
        card = self._cards[cid]
        grant = next(
            (
                g
                for g in actor.may_play_grants
                if self._may_play_timing_ok(player_idx, g)
                and self._card_matches_may_play_grant(card, g)
                and (g.get("zone") or "hand") == zone
            ),
            None,
        )
        free_cost = False
        if grant is None and zone == "hand" and actor.play_as_instant:
            if self._card_matches_may_play_grant(
                card,
                {
                    "zone": "hand",
                    "filter": "non-attack",
                    "class_filter": actor.instant_class_filter,
                },
            ):
                grant = {"zone": "hand", "filter": "non-attack", "free_cost": False}
        if grant is None:
            self._last_event = "No may-play grant applies"
            return -0.05
        free_cost = bool(grant.get("free_cost"))
        cost = 0 if free_cost else self._effective_card_cost(player_idx, card)
        if actor.resources < cost:
            self._last_event = f"Need {cost} resources"
            return -0.05
        if zone == "hand":
            hand_idx = actor.hand.index(cid)
            if self._play_blocked_reason(player_idx, hand_idx, card):
                self._last_event = "That card cannot be played now"
                return -0.05
        actor.resources -= cost
        if not free_cost:
            self._consume_cost_reduction(player_idx, card, cost)
        if zone == "hand":
            actor.hand.pop(actor.hand.index(cid))
            self._mark_played_from_arsenal(player_idx, cid)
        elif zone == "arsenal":
            actor.arsenal.remove(cid)
            self._players[player_idx].class_state["PlayedFromArsenal"] = 1
        elif zone == "banished":
            actor.banished.remove(cid)
            actor.playable_banished.discard(cid)
        elif zone == "opponent_banished":
            opp = self._players[1 - player_idx]
            opp.banished.remove(cid)
        elif zone == "opponent_arsenal":
            opp = self._players[1 - player_idx]
            opp.arsenal.remove(cid)
            actor.class_state["PlayedFromArsenal"] = 0
        actor.play_as_instant = False
        is_attack = "attack_action" in card.card_types
        is_utility = "utility_action" in card.card_types
        keywords = set(card.keywords)
        go_again = self._go_again_for_play(player_idx, card, is_utility)
        dominate = "dominate" in keywords
        damage, arcane = _parse_action_damage(card.text, card.power, is_attack)
        self._last_event = f"P{player_idx} may-play {card.name} from {zone}"
        if is_attack and not arcane:
            combat = CombatState(
                attacker=player_idx,
                defender=1 - player_idx,
                attack_card_id=card.id,
                attack_power=damage,
                blocks=[],
                go_again=go_again,
                dominate=dominate,
                fused=False,
            )
            self._pending_combat = combat
            go_again, dominate = self._apply_play_modifiers(
                player_idx, card, combat, go_again=go_again, dominate=dominate
            )
            combat.go_again = go_again
            combat.dominate = dominate
            self._record_play_counters(player_idx, card, True, False, False, None)
            self._consume_pending_next_attack_power(player_idx, card, combat)
            return self._finish_attack_triggers(player_idx, card, perspective_idx, False)
        return self._resolve_direct(
            player_idx, card, damage, arcane, go_again, dominate, False, (), perspective_idx
        )

    def _fire_damage_triggers(
        self,
        attacker_idx: int,
        card: Card,
        damage: int,
        perspective_idx: int,
        fused: bool,
    ) -> float:
        """Fire on_crush / on_surge triggers after combat damage is dealt."""
        reward = 0.0
        for trig in effects.parse_triggers(card.text):
            if trig.when == "on_crush" and damage >= max(1, trig.threshold):
                if not self._crush_condition_met(attacker_idx, trig.effect):
                    continue
                reward += self._apply_effect(attacker_idx, card, trig.effect, None, perspective_idx)
            elif trig.when == "on_surge" and damage > trig.threshold:
                reward += self._apply_effect(attacker_idx, card, trig.effect, None, perspective_idx)
        return reward

    def _record_play_counters(
        self, player_idx: int, card: Card, is_attack: bool, is_utility: bool, fused: bool, element: Optional[str]
    ) -> None:
        cs = self._players[player_idx].class_state
        if "runeblade" in (card.card_class or "").lower() and cs.get("NumNonAttackCards", 0) > 0:
            self._fire_equipment_triggers(player_idx, "whenever_runeblade_play", player_idx)
        cs["NumCardsPlayed"] += 1
        if is_attack:
            cs["NumActionsPlayed"] += 1
            cs["NumAttacks"] += 1
        elif is_utility:
            cs["NumActionsPlayed"] += 1
            cs["NumNonAttackCards"] += 1
        if is_attack or is_utility:
            cs["LastActionTalentLightning"] = 1 if self._is_lightning_action(card) else 0
        if "lightning" in (card.name + " " + card.text).lower():
            cs["NumLightningPlayed"] += 1
        color = {1: "NumRedPlayed", 2: "NumYellowPlayed", 3: "NumBluePlayed"}.get(card.pitch)
        if color:
            cs[color] += 1
        if fused and element:
            fkey = {"lightning": "NumFusedLightning", "ice": "NumFusedIce", "earth": "NumFusedEarth"}.get(element)
            if fkey:
                cs[fkey] += 1
            if element == "ice":
                self._fire_equipment_triggers(player_idx, "on_ice_fuse", player_idx)
        if "contract" in card.keywords or re.search(r"\bcontract\b", card.text, re.I):
            self._fire_whenever_contract_triggers(player_idx, player_idx)
        if "blood_debt" in card.keywords:
            cs["BloodDebtPlayedThisTurn"] = cs.get("BloodDebtPlayedThisTurn", 0) + 1
        if "wax on" in card.name.lower():
            cs["WaxOnPlayedThisTurn"] = 1

    def _deck_top_card_id(self, player_idx: int) -> Optional[str]:
        """Return the top card id of a player's deck, reshuffling discard if needed."""
        p = self._players[player_idx]
        if not p.deck and p.discard:
            p.deck = p.discard
            p.discard = []
            self._rng.shuffle(p.deck)
        if not p.deck:
            return None
        return p.deck[-1]

    def _banish_top_card(self, player_idx: int) -> Optional[str]:
        """Banish the top card of a player's deck into their banished zone."""
        p = self._players[player_idx]
        if not p.deck and p.discard:
            p.deck = p.discard
            p.discard = []
            self._rng.shuffle(p.deck)
        if not p.deck:
            return None
        cid = p.deck.pop()
        p.banished.append(cid)
        self._players[player_idx].class_state["CardsBanishedThisTurn"] += 1
        self._event_append(f"P{player_idx} banished {self._cards[cid].name} from deck top")
        return cid

    def _banish_defending_card(self, combat: Optional[CombatState], defender_idx: int) -> None:
        """Banish one defending card from the current combat chain."""
        if combat is None:
            return
        for i in range(len(combat.blocks) - 1, -1, -1):
            block_player, cid, _ = combat.blocks[i]
            if block_player != defender_idx:
                continue
            combat.blocks.pop(i)
            self._players[defender_idx].banished.append(cid)
            self._event_append(f"banished defending {self._cards[cid].name}")
            return

    def _create_token(self, player_idx: int, token_name: str, amount: int = 1) -> None:
        key = token_defs.normalize_token_name(token_name)
        actor = self._players[player_idx]
        actor.tokens[key] = actor.tokens.get(key, 0) + amount
        actor.tokens_controlled_turn.add(key)
        label = token_name.strip() or key
        suffix = f"x{amount} " if amount > 1 else ""
        self._event_append(f"created {suffix}{label} token")

    def _create_in_banished(
        self,
        player_idx: int,
        card_name: str,
        *,
        playable: bool = False,
        power_bonus: int = 0,
    ) -> None:
        cid = token_defs.resolve_banished_card_id(card_name, self._token_name_index)
        if cid is None:
            self._note(f"Unknown banished card to create: {card_name!r}")
            return
        actor = self._players[player_idx]
        actor.banished.append(cid)
        if playable:
            actor.playable_banished.add(cid)
        self._event_append(
            f"created {self._cards[cid].name} in banished zone"
            + (" (playable this turn)" if playable else "")
        )

    def _create_in_hand(self, player_idx: int, card_name: str, amount: int = 1) -> None:
        names = [card_name.strip()]
        if re.search(r"\s+and\s+", card_name, re.I):
            names = [n.strip() for n in re.split(r"\s+and\s+", card_name, flags=re.I)]
        actor = self._players[player_idx]
        for _ in range(max(1, amount)):
            for name in names:
                cid = token_defs.resolve_banished_card_id(name, self._token_name_index)
                if cid is None:
                    self._note(f"Unknown card to create in hand: {name!r}")
                    continue
                actor.hand.append(cid)
                self._event_append(f"created {self._cards[cid].name} in hand")

    def _apply_named_power_bonuses(
        self, player_idx: int, card: Card, combat: Optional[CombatState]
    ) -> None:
        if combat is None:
            return
        cs = self._players[player_idx].class_state
        card_low = card.name.lower()
        for key, bonus in list(cs.items()):
            if not str(key).startswith("NamedPower:") or not bonus:
                continue
            pattern = str(key).split(":", 1)[1]
            if pattern in card_low:
                self._apply_combat_power_bonus(
                    combat,
                    player_idx,
                    int(bonus),
                    reason=f"+{bonus} power ({pattern})",
                )

    def _process_token_upkeep(self, player_idx: int) -> None:
        """Resolve start-of-action-phase token upkeeps (e.g. Seismic Surge)."""
        actor = self._players[player_idx]
        key = "seismic surge"
        if actor.tokens.get(key, 0) <= 0:
            return
        actor.tokens[key] -= 1
        actor.class_state["NextGuardianAttackCostReduction"] = 1
        self._event_append("Seismic Surge: next Guardian attack costs 1 less")

    def _effective_card_cost(self, player_idx: int, card: Card) -> int:
        cost = card.cost
        actor = self._players[player_idx]
        if "attack_action" in card.card_types and (card.card_class or "").strip().lower() == "guardian":
            reduction = actor.class_state.get("NextGuardianAttackCostReduction", 0)
            cost = max(0, cost - reduction)
        play_reduction = actor.class_state.get("NextPlayCostReduction", 0)
        cost = max(0, cost - play_reduction)
        cost = max(0, cost - self._token_play_cost_reduction(player_idx, card))
        cost += actor.extra_play_cost
        if "defense_reaction" in card.card_types:
            cost += actor.extra_defense_reaction_cost
        return cost

    def _consume_cost_reduction(self, player_idx: int, card: Card, paid_cost: int) -> None:
        actor = self._players[player_idx]
        if (
            "attack_action" in card.card_types
            and (card.card_class or "").strip().lower() == "guardian"
            and paid_cost < card.cost
            and actor.class_state.get("NextGuardianAttackCostReduction", 0) > 0
        ):
            actor.class_state["NextGuardianAttackCostReduction"] = 0
        if actor.class_state.get("NextPlayCostReduction", 0) > 0 and paid_cost < card.cost:
            actor.class_state["NextPlayCostReduction"] = 0

    def _pitch_cards(self, player_idx: int, count: int) -> int:
        """Pitch up to *count* cards from hand; return number actually pitched."""
        actor = self._players[player_idx]
        pitched = 0
        for _ in range(max(0, count)):
            idx = next(
                (i for i, cid in enumerate(actor.hand) if self._cards[cid].pitch > 0),
                None,
            )
            if idx is None:
                break
            cid = actor.hand.pop(idx)
            card = self._cards[cid]
            actor.pitch_zone.append(cid)
            pitched += 1
            self._record_opponent_pitch(player_idx, card)
            self._event_append(f"pitched {card.name} to pay cost")
        return pitched

    def _gy_play_pattern_match(self, card: Card, pattern: str) -> bool:
        p = (pattern or "").strip().lower()
        if not p or p == "this":
            return True
        if p in card.name.lower():
            return True
        if p in (card.text or "").lower():
            return True
        if p in (card.type_line or "").lower():
            return True
        return False

    def _enable_graveyard_play(
        self, player_idx: int, source: Card, pattern: str
    ) -> None:
        actor = self._players[player_idx]
        pat = (pattern or "").strip().lower()
        if pat in ("", "this"):
            actor.playable_graveyard.add(source.id)
            self._event_append(f"{source.name} may be played from graveyard this turn")
            return
        enabled = 0
        for cid in actor.discard:
            if self._gy_play_pattern_match(self._cards[cid], pat):
                actor.playable_graveyard.add(cid)
                enabled += 1
        if enabled:
            self._event_append(f"{enabled} graveyard card(s) may be played this turn")
        else:
            self._event_append(f"no matching cards in graveyard for {pat!r}")

    def _can_play_from_graveyard(self, player_idx: int, card_id: str) -> bool:
        if card_id in self._players[player_idx].playable_graveyard:
            return True
        text = self._cards[card_id].text.lower()
        return "you may play this from your graveyard" in text

    def _can_play_from_banished(self, player_idx: int, card_id: str) -> bool:
        actor = self._players[player_idx]
        if card_id in actor.playable_banished:
            return True
        card = self._cards[card_id]
        text = card.text.lower()
        if "you may play this from your banished zone" in text:
            return True
        for src in [actor.hero.ability_text] + [self._cards[c].text for c in actor.equipment]:
            low = (src or "").lower()
            if "you may play evos from your banished zone" in low and "evo" in card.name.lower():
                return True
        return False

    def _effect_condition_met(
        self,
        player_idx: int,
        condition: str,
        card: Optional[Card] = None,
        *,
        condition_arg: str = "",
        combat: Optional[CombatState] = None,
    ) -> bool:
        """Evaluate a parsed play-time condition from card rules text."""
        if not condition:
            return True
        actor = self._players[player_idx]
        opponent = self._players[1 - player_idx]
        cs = actor.class_state
        if condition == "life_less":
            return actor.life < opponent.life
        if condition == "empty_deck":
            return len(actor.deck) == 0
        if condition == "played_red_other":
            red = cs.get("NumRedPlayed", 0)
            if card is not None and card.pitch == 1:
                return red >= 1
            return red > 0
        if condition == "played_blue_other":
            blue = cs.get("NumBluePlayed", 0)
            if card is not None and card.pitch == 3:
                return blue >= 1
            return blue > 0
        if condition == "pitched_power_6":
            return any(self._cards[cid].power >= 6 for cid in actor.pitch_zone)
        if condition == "last_action_lightning":
            return cs.get("LastActionTalentLightning", 0) > 0
        if condition == "controlled_seismic_surge":
            return "seismic surge" in actor.tokens_controlled_turn
        if condition == "combo_red":
            return cs.get("LastChainAttackPitch", 0) == 1
        if condition == "combo_yellow":
            return cs.get("LastChainAttackPitch", 0) == 2
        if condition == "combo_blue":
            return cs.get("LastChainAttackPitch", 0) == 3
        if condition == "cheered_this_turn":
            return actor.cheered_this_turn
        if condition.startswith("hand_ge:"):
            return len(actor.hand) >= int(condition.split(":", 1)[1])
        if condition == "no_hit_this_turn":
            return cs.get("HitCounter", 0) <= 0
        if condition == "no_gold_tokens":
            return actor.gold <= 0 and actor.tokens.get("gold", 0) <= 0
        if condition == "wax_on_played":
            return cs.get("WaxOnPlayedThisTurn", 0) > 0
        if condition == "naa_played_this_turn":
            return cs.get("NumNonAttackCards", 0) > 0
        if condition.startswith("weapon_attacks_ge:"):
            return cs.get("WeaponAttacksThisTurn", 0) >= int(condition.split(":", 1)[1])
        if condition == "once_per_turn":
            return not cs.get(f"OncePerTurn:{card.id if card else 'hero'}", 0)
        if condition == "less_gold_than_opponent":
            return actor.gold < opponent.gold
        if condition == "more_gold_than_opponent":
            return actor.gold > opponent.gold
        if condition == "scrapped_this_play":
            return actor.class_state.get("ScrappedThisPlay", 0) > 0
        if condition == "power_ge_6":
            return card is not None and card.power >= 6
        if condition == "chain_link_ge":
            threshold = int(condition_arg or "1")
            return self._combat_chain_links + 1 >= threshold
        if condition == "blue_pitched_each":
            return any(self._cards[cid].pitch == 3 for cid in actor.pitch_zone)
        if condition == "has_token":
            key = token_defs.normalize_token_name(condition_arg or "")
            return actor.tokens.get(key, 0) > 0
        if condition == "yellow_in_pitch":
            return any(self._cards[cid].pitch == 2 for cid in actor.pitch_zone)
        if condition == "banished_this_turn":
            return cs.get("CardsBanishedThisTurn", 0) > 0
        if condition == "charged_yellow":
            return cs.get("ChargedYellowThisPlay", 0) > 0
        if condition == "attack_reaction_chain":
            combat = self._pending_combat
            return combat is not None and combat.attack_reactions_played > 0
        if condition == "defending_chain_link_ge":
            threshold = int(condition_arg or "1")
            return self._combat_chain_links + 1 >= threshold
        if condition == "played_from_arsenal":
            return cs.get("PlayedFromArsenal", 0) > 0
        if condition == "rolled_6_this_turn":
            return cs.get("Rolled6ThisTurn", 0) > 0
        if condition.startswith("hyper_drivers_ge:"):
            return cs.get("LastHyperDriversTurned", 0) >= int(condition.split(":", 1)[1])
        if condition == "no_soul":
            return not actor.soul
        if condition == "light_hero":
            if combat is None:
                return False
            defender = self._players[combat.defender]
            return (defender.hero.talent or "").strip().lower() == "light"
        if condition == "has_aim_counter":
            return (
                card is not None
                and self._permanent_counters(player_idx, card.id).get("aim", 0) > 0
            )
        if condition == "stealth_hit_marked":
            defender = self._players[1 - player_idx]
            return cs.get("StealthHitThisTurn", 0) > 0 and defender.marked
        if condition == "attacking_marked":
            if combat is None:
                return False
            defender = self._players[combat.defender]
            return defender.marked
        if condition == "has_guardian_offhand":
            actor = self._players[player_idx]
            for cid in actor.equipment:
                eq = self._cards[cid]
                line = (eq.type_line or "").lower()
                cls = (eq.card_class or "").lower()
                if "off-hand" in line and "guardian" in cls:
                    return True
            return False
        if condition == "attack_power_gt_base":
            if combat is None or not combat.attack_card_id:
                return False
            attack_card = self._cards.get(combat.attack_card_id)
            if attack_card is None:
                return False
            return combat.attack_power > attack_card.power
        if condition.startswith("defends_class:"):
            if combat is None or not combat.attack_card_id:
                return False
            want = condition.split(":", 1)[1].lower()
            attack_card = self._cards.get(combat.attack_card_id)
            if attack_card is None:
                return False
            atk_class = (attack_card.card_class or "").lower()
            atk_talent = (attack_card.talent or "").lower()
            return want in (atk_class, atk_talent)
        if condition.startswith("defends_card_pitch:"):
            if combat is None or not combat.attack_card_id:
                return False
            want_pitch = int(condition.split(":", 1)[1])
            attack_card = self._cards.get(combat.attack_card_id)
            return attack_card is not None and attack_card.pitch == want_pitch
        if condition == "reaction_played_chain":
            if combat is None:
                return False
            return bool(combat.reaction_cards) or combat.attack_reactions_played > 0
        if condition == "attack_reaction_played_chain":
            if combat is None:
                return False
            return combat.attack_reactions_played > 0
        if condition == "hero_thief":
            hero = (actor.hero.hero_class or actor.hero.name or "").lower()
            return "thief" in hero
        if condition == "arsenal_crush":
            return bool(actor.arsenal) and any(
                "crush" in self._cards[cid].keywords
                or "crush" in (self._cards[cid].text or "").lower()
                for cid in actor.arsenal
            )
        if condition == "arcane_dealt_turn":
            return actor.class_state.get("ArcaneDamageDealt", 0) > 0
        if condition == "defends_weapon_attack":
            return combat is not None and combat.is_weapon
        if condition == "guardian_offhand_defending":
            if combat is None:
                return False
            defender = self._players[1 - combat.attacker]
            for cid in defender.equipment:
                eq = self._cards[cid]
                line = (eq.type_line or "").lower()
                cls = (eq.card_class or "").lower()
                if "off-hand" in line and "guardian" in cls and eq.defense >= 1:
                    return True
            return False
        if condition.startswith("defended_by_ge"):
            if combat is None:
                return False
            want = int(condition.split(":", 1)[1]) if ":" in condition else 1
            return len(combat.blocks) >= want
        if condition == "defended_by_ge_pay":
            if combat is None:
                return False
            need = int((condition_arg or "1"))
            return len(combat.blocks) >= need
        if condition == "hero_thief:pay_gold":
            if not self._effect_condition_met(player_idx, "hero_thief", card, combat=combat):
                return False
            return actor.gold >= 1
        if condition == "gy_yellow":
            return any(self._cards[cid].pitch == 2 for cid in actor.discard) or any(
                self._cards[cid].pitch == 2 for cid in self._players[1 - player_idx].discard
            )
        return False

    def _apply_play_modifiers(
        self,
        player_idx: int,
        card: Card,
        combat: Optional[CombatState],
        *,
        go_again: bool,
        dominate: bool,
    ) -> tuple[bool, bool]:
        """Apply inline play bonuses; return updated (go_again, dominate)."""
        actor = self._players[player_idx]
        for mod in effects.parse_play_modifiers(card.text):
            if mod.condition and not self._effect_condition_met(
                player_idx,
                mod.condition,
                card,
                condition_arg=mod.condition_arg,
            ):
                continue
            if mod.condition == "defended_by_action_penalty":
                continue
            if mod.condition == "arcane_dealt_turn":
                if actor.class_state.get("ArcaneDamageDealt", 0) <= 0:
                    continue
            if mod.condition == "defended_by_ge_pay":
                continue
            if mod.power and combat is not None:
                self._apply_combat_power_bonus(
                    combat,
                    player_idx,
                    mod.power,
                    reason=f"+{mod.power} power ({mod.raw[:40]})",
                )
            if mod.defense:
                actor = self._players[player_idx]
                bonus = mod.defense
                if mod.condition == "blue_pitched_each":
                    n_blue = sum(1 for cid in actor.pitch_zone if self._cards[cid].pitch == 3)
                    bonus *= max(0, n_blue)
                if bonus > 0:
                    actor.class_state["NextDefenseBonus"] = (
                        actor.class_state.get("NextDefenseBonus", 0) + bonus
                    )
                    self._event_append(f"+{bonus} defense ({mod.raw[:40]})")
            if mod.go_again:
                go_again = True
            if mod.next_action_go_again:
                actor = self._players[player_idx]
                actor.class_state["NextActionGoAgain"] = (
                    actor.class_state.get("NextActionGoAgain", 0) + mod.next_action_go_again
                )
                self._event_append(
                    f"next {mod.next_action_go_again} action(s) gain go again"
                )
            if mod.dominate:
                dominate = True
            if mod.next_attack_power:
                actor = self._players[player_idx]
                actor.class_state["NextAttackPower"] = mod.next_attack_power
                actor.class_state["NextAttackPowerMaxCost"] = mod.next_attack_max_cost
                if mod.condition == "weapon_only":
                    actor.class_state["NextAttackWeaponOnly"] = 1
                    actor.class_state["NextAttackMinBase"] = 0
                elif mod.condition == "min_base_power":
                    actor.class_state["NextAttackMinBase"] = int(mod.condition_arg or "0")
                    actor.class_state["NextAttackWeaponOnly"] = 0
                else:
                    actor.class_state["NextAttackMinBase"] = 0
                    actor.class_state["NextAttackWeaponOnly"] = 0
                self._event_append(f"next attack +{mod.next_attack_power} power")
        return go_again, dominate

    def _apply_effect(
        self,
        player_idx: int,
        card: Card,
        effect: "effects.Effect",
        combat: Optional[CombatState],
        perspective_idx: int,
    ) -> float:
        """Apply one parsed effect; return signed reward from any damage dealt."""
        if not effect.implemented:
            self._note(f"{card.name}: interaction not implemented yet (\"{effect.raw[:60]}\")")
            return 0.0
        if effect.condition and not self._effect_condition_met(
            player_idx, effect.condition, card, combat=combat
        ):
            return 0.0

        actor = self._players[player_idx]
        defender = self._players[1 - player_idx]

        if effect.kind == "go_again":
            n = max(1, effect.amount or 1)
            if combat is not None and n == 1:
                self._grant_go_again(player_idx, combat, this_card=True)
            elif combat is not None:
                combat.go_again = True
                if n > 1:
                    actor.action_points += n - 1
            else:
                actor.action_points += n
            return 0.0
        if effect.kind == "next_naa_go_again":
            actor.class_state["NextNAACardGoAgain"] = 1
            return 0.0
        if effect.kind == "next_action_go_again":
            self._grant_go_again(player_idx, combat, this_card=False, next_actions=max(1, effect.amount or 1))
            return 0.0
        if effect.kind == "next_attack_power":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            cs = self._players[target_idx].class_state
            cs["NextAttackPower"] = effect.amount
            cs["NextAttackPowerMaxCost"] = effect.max_cost
            if effect.condition == "min_base_power":
                cs["NextAttackMinBase"] = int(effect.banish_name or "0")
                cs["NextAttackWeaponOnly"] = 0
            elif effect.condition == "weapon_only" or (effect.banish_name or "").lower() == "wrench":
                cs["NextAttackMinBase"] = 0
                cs["NextAttackWeaponOnly"] = 1
            else:
                cs["NextAttackMinBase"] = 0
                cs["NextAttackWeaponOnly"] = 0
            self._event_append(f"next attack {effect.amount:+d} power on P{target_idx}")
            return 0.0
        if effect.kind == "banish_combo":
            if combat is not None:
                target = effect.banish_name.lower()
                for j, cid in enumerate(actor.discard):
                    if target in self._cards[cid].name.lower():
                        banished = self._cards[cid].name
                        actor.discard.pop(j)
                        self._apply_combat_power_bonus(
                            combat,
                            player_idx,
                            effect.amount,
                            reason=f"banished {banished} (+{effect.amount} power)",
                        )
                        if effect.go_again:
                            self._grant_go_again(player_idx, combat, this_card=True)
                        break
            return 0.0
        if effect.kind == "power":
            if (effect.banish_name or "").lower() == "attacks_targeting_you":
                actor.class_state["AttacksTargetingYouPenalty"] = abs(effect.amount or 1)
                self._event_append(
                    f"attacks targeting you get {effect.amount:+d} power this turn"
                )
            elif combat is not None:
                if (effect.banish_name or "").lower() == "chain" and effect.target == "opponent":
                    combat.opposing_power_mod += effect.amount
                    self._event_append(
                        f"opposing attacks {effect.amount:+d} power this combat chain"
                    )
                else:
                    self._apply_combat_power_bonus(
                        combat,
                        player_idx,
                        effect.amount,
                        reason=f"{effect.amount:+d} power on chain",
                    )
                if effect.go_again:
                    self._grant_go_again(player_idx, combat, this_card=True)
            return 0.0
        if effect.kind == "dominate":
            if combat is not None:
                combat.dominate = True
            return 0.0
        if effect.kind == "intimidate":
            target_idx = 1 - player_idx if effect.target != "self" else player_idx
            self._do_intimidate(target_idx)
            return 0.0
        if effect.kind == "draw":
            if effect.target == "each_hero":
                for idx in (0, 1):
                    for _ in range(max(1, effect.amount or 1)):
                        self._draw_card(idx, from_action=True)
                return 0.0
            target_idx = player_idx
            if effect.target in ("opponent", "ally"):
                target_idx = 1 - player_idx
            for _ in range(max(1, effect.amount or 1)):
                self._draw_card(target_idx, from_action=True)
            if target_idx == player_idx:
                pass  # NumCardsDrawn updated per card in _draw_card
            return 0.0
        if effect.kind in ("damage", "arcane_damage"):
            hits = 1
            if effect.condition.startswith("multi:"):
                hits = max(1, int(effect.condition.split(":")[1]))
            target_idx = self._damage_target_idx(player_idx, effect, combat)
            target = self._players[target_idx]
            total_r = 0.0
            total_dealt = 0
            for _ in range(hits):
                amount = effect.amount
                if (effect.banish_name or "").lower() == "red_reveal_double":
                    amount = actor.class_state.get("LastRevealRedCount", 0) * 2
                if effect.kind == "damage":
                    amount = self._apply_damage_floor(player_idx, amount)
                if effect.kind == "arcane_damage" and actor.amp > 0:
                    amount += actor.amp
                    self._event_append(f"amp +{actor.amp} arcane damage")
                    actor.amp = 0
                if effect.kind == "arcane_damage" and actor.class_state.get("ArcanePlusOneThisPlay", 0):
                    amount += 1
                    actor.class_state["ArcanePlusOneThisPlay"] = 0
                    self._event_append("Metacarpus Node: +1 arcane damage")
                if effect.kind == "arcane_damage":
                    amount = self._mitigate_damage(target_idx, amount, arcane=True)
                else:
                    amount = self._mitigate_damage(target_idx, amount)
                if amount <= 0:
                    continue
                target.life -= amount
                target.class_state["DamageTakenThisTurn"] = (
                    target.class_state.get("DamageTakenThisTurn", 0) + amount
                )
                total_dealt += amount
                r = float(amount) * 0.01
                total_r += r if perspective_idx == player_idx else -r
            if total_dealt:
                key = "DamageDealt" if effect.kind == "damage" else "ArcaneDamageDealt"
                actor.class_state[key] += total_dealt
                target.class_state["DamageTaken"] += total_dealt
            return total_r
        if effect.kind == "create_token":
            if effect.target == "each_hero":
                count = max(1, effect.amount or 1)
                for idx in (0, 1):
                    self._create_token(idx, effect.token_name, count)
                return 0.0
            if effect.condition == "hero_thief:pay_gold":
                if actor.gold <= 0:
                    return 0.0
                actor.gold -= 1
            if effect.target == "ally":
                target_idx = 1 - player_idx
            elif effect.target == "defender":
                target_idx = combat.defender if combat is not None else (1 - player_idx)
            elif effect.target == "opponent":
                target_idx = 1 - player_idx
            else:
                target_idx = player_idx
            count = max(1, effect.amount or 1)
            if (effect.banish_name or "").lower() == "other_heroes":
                count = 1
            elif (effect.banish_name or "").lower() == "weapon_hits":
                count = max(0, actor.class_state.get("WeaponHitsThisTurn", 0))
            elif (effect.banish_name or "").lower() == "damage_dealt":
                count = max(0, actor.class_state.get("LastHitDamage", 0))
            if count <= 0:
                return 0.0
            self._create_token(target_idx, effect.token_name, count)
            return 0.0
        if effect.kind == "create_banished":
            amount = max(1, effect.amount or 1)
            if effect.amount == 0 and effect.token_name:
                key = token_defs.normalize_token_name(effect.token_name)
                amount = max(1, actor.tokens.get(key, 0))
            for _ in range(amount):
                self._create_in_banished(
                    player_idx,
                    effect.banish_name or effect.token_name,
                    playable=effect.playable_banished,
                    power_bonus=0,
                )
            return 0.0
        if effect.kind == "create_in_hand":
            self._create_in_hand(
                player_idx,
                effect.banish_name or effect.token_name or "",
                max(1, effect.amount or 1),
            )
            return 0.0
        if effect.kind == "named_power_bonus":
            pattern = token_defs.normalize_token_name(
                effect.token_name or effect.banish_name or ""
            )
            if pattern:
                key = f"NamedPower:{pattern}"
                actor.class_state[key] = actor.class_state.get(key, 0) + max(
                    1, effect.amount or 1
                )
                self._event_append(f"{pattern} attacks get +{effect.amount or 1} power this turn")
            return 0.0
        if effect.kind == "banish_top":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            for _ in range(max(1, effect.amount or 1)):
                self._banish_top_card(target_idx)
            return 0.0
        if effect.kind == "banish_defending":
            defender_idx = 1 - player_idx
            self._banish_top_card(defender_idx)
            self._banish_defending_card(combat, defender_idx)
            return 0.0
        if effect.kind == "banish_graveyard":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            self._banish_from_graveyard(target_idx, max(1, effect.amount or 1))
            return 0.0
        if effect.kind == "banish_arsenal":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            target = self._players[target_idx]
            if target.arsenal:
                cid = target.arsenal.pop()
                target.banished.append(cid)
                self._event_append(f"banished {self._cards[cid].name} from arsenal")
            return 0.0
        if effect.kind == "discard":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            self._discard_random(target_idx, max(1, effect.amount or 1))
            return 0.0
        if effect.kind == "destroy_top":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            self._destroy_top_of_deck(target_idx, max(1, effect.amount or 1))
            return 0.0
        if effect.kind == "destroy_arsenal":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            self._destroy_arsenal(target_idx, max(1, effect.amount or 99))
            return 0.0
        if effect.kind == "destroy_hand":
            target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            target = self._players[target_idx]
            rider = (effect.banish_name or "").lower()
            if rider == "soul":
                if not target.soul:
                    self._event_append("no cards in soul to banish")
                    return 0.0
                cid = target.soul.pop()
                target.banished.append(cid)
                self._record_soul_banish_chain(target_idx)
                self._event_append(f"banished {self._cards[cid].name} from soul")
                return 0.0
            if rider.startswith("create:"):
                token = rider.split(":", 1)[1]
                if not actor.hand:
                    self._event_append("no card in hand to banish")
                    return 0.0
                cid = actor.hand.pop()
                actor.banished.append(cid)
                self._event_append(f"banished {self._cards[cid].name} from hand")
                self._create_token(player_idx, token, 1)
                return 0.0
            self._discard_random(target_idx, max(1, effect.amount or 1))
            return 0.0
        if effect.kind == "gain_resources":
            actor.resources += max(1, effect.amount or 1)
            self._event_append(f"gained {effect.amount or 1} resources")
            return 0.0
        if effect.kind == "damage_floor":
            threshold = max(1, effect.max_cost if effect.max_cost > 0 else (effect.amount or 1))
            amount = max(1, effect.amount or 1)
            actor.class_state["DamageFloorThreshold"] = threshold
            actor.class_state["DamageFloorAmount"] = amount
            self._event_append(
                f"next damage below {threshold} will become {amount} instead"
            )
            return 0.0
        if effect.kind == "prevent_damage":
            target_idx = player_idx
            if effect.target in ("opponent", "any"):
                target_idx = 1 - player_idx if effect.target == "opponent" else player_idx
            target = self._players[target_idx]
            if (effect.banish_name or "").lower() == "roll_d6":
                self._pending_die_roll = {
                    "controller": target_idx,
                    "kind": "prevent_d6",
                }
                if self._pause_for_gambler(target_idx):
                    return 0.0
                self._continue_pending_die_roll()
                return 0.0
            elif effect.condition.startswith("per_hit:"):
                charges = int(effect.condition.split(":", 1)[1])
                target.prevent_damage_charges = charges
                target.prevent_damage_per_hit = max(1, effect.amount or 1)
                self._event_append(
                    f"P{target_idx} will prevent {target.prevent_damage_per_hit} damage "
                    f"the next {charges} times they would be dealt damage"
                )
            else:
                target.prevent_damage += max(1, effect.amount or 1)
                self._event_append(f"P{target_idx} will prevent {effect.amount or 1} damage")
            return 0.0
        if effect.kind == "ward":
            # Ward is a static ability on permanents (CR 8.3.20), not a hero buff.
            self._event_append(f"{card.name}: ward {effect.amount or 1} (static on permanent)")
            return 0.0
        if effect.kind == "opt":
            self._do_opt(player_idx, max(1, effect.amount or 1))
            return 0.0
        if effect.kind == "mark":
            defender.marked = True
            self._event_append("hero marked (CR 8.5.50)")
            return 0.0
        if effect.kind == "put_soul":
            actor = self._players[player_idx]
            color_filter = (effect.banish_name or "").lower()
            if color_filter == "self_from_chain":
                soul_id = card.id
                for zone in (actor.hand, actor.discard, actor.banished):
                    if soul_id in zone:
                        zone.remove(soul_id)
                        break
                if soul_id not in actor.soul:
                    actor.soul.append(soul_id)
                self._event_append(f"{card.name} put into soul")
                return 0.0
            if color_filter == "destroyed_light":
                return 0.0
            if color_filter in ("red", "yellow", "blue"):
                pitch_map = {"red": 1, "yellow": 2, "blue": 3}
                target_pitch = pitch_map[color_filter]
                for i, cid in enumerate(actor.hand):
                    if self._cards[cid].pitch == target_pitch:
                        soul_id = actor.hand.pop(i)
                        break
                else:
                    soul_id = None
            elif card.id in actor.hand:
                actor.hand.remove(card.id)
                soul_id = card.id
            elif card.id in actor.discard:
                actor.discard.remove(card.id)
                soul_id = card.id
            elif actor.hand:
                soul_id = actor.hand.pop()
            else:
                soul_id = None
            if soul_id is None:
                self._event_append("no card available to put into soul")
                return 0.0
            if soul_id not in actor.soul:
                actor.soul.append(soul_id)
            self._event_append(f"{self._cards[soul_id].name} charged to soul")
            soul_card = self._cards[soul_id]
            if soul_card.pitch == 2:
                actor.class_state["ChargedYellowThisPlay"] = 1
                actor.class_state["YellowSoulThisTurn"] = 1
            for trig in effects.parse_triggers(soul_card.text):
                if trig.when == "on_soul_enter":
                    self._apply_effect(player_idx, soul_card, trig.effect, combat, perspective_idx)
            rider = (effect.banish_name or "")
            if rider.startswith("create_if:"):
                _, cls_filter, token_name = rider.split(":", 2)
                if cls_filter.lower() in (soul_card.card_class or "").lower():
                    self._create_token(player_idx, token_name, 1)
                    self._event_append(f"created {token_name} token")
            return 0.0
        if effect.kind == "reveal_hand":
            target_idx = 1 - player_idx if effect.target != "self" else player_idx
            target = self._players[target_idx]
            if (effect.banish_name or "").lower() == "hand_and_deck":
                hand_names = [self._cards[cid].name for cid in target.hand]
                top = self._deck_top_card_id(target_idx)
                deck_name = self._cards[top].name if top else None
                parts = []
                if hand_names:
                    who = "opponent" if target_idx != player_idx else "your"
                    parts.append(f"{who} hand: {', '.join(hand_names)}")
                if deck_name:
                    parts.append(f"deck top: {deck_name}")
                if parts:
                    self._event_append("looked at " + "; ".join(parts))
                else:
                    self._event_append("hand and deck top empty")
                return 0.0
            n = max(1, effect.amount or 1)
            if (effect.banish_name or "").lower() == "store_revealed":
                if effect.condition == "opponent_turn_all" and self._active_player != player_idx:
                    n = len(target.hand)
                revealed = list(target.hand[: min(n, len(target.hand))])
                target.revealed_hand = revealed
                names = [self._cards[cid].name for cid in revealed]
                if names:
                    who = "opponent" if target_idx != player_idx else "your"
                    self._event_append(f"{who} hand revealed: {', '.join(names)}")
                else:
                    self._event_append("no cards in hand to reveal")
                return 0.0
            sample = [self._cards[cid].name for cid in target.hand[:n]]
            if sample:
                who = "opponent" if target_idx != player_idx else "your"
                self._event_append(f"{who} hand revealed: {', '.join(sample)}")
            else:
                self._event_append("no cards in hand to reveal")
            return 0.0
        if effect.kind == "choose_card":
            target_idx = 1 - player_idx if effect.target != "self" else player_idx
            from_revealed = effect.condition == "revealed_only"
            no_defense = effect.condition == "no_defense"
            options = self._choice_options_for_hand(
                target_idx,
                from_revealed=from_revealed,
                filter_no_defense=no_defense,
            )
            rider = (effect.banish_name or "put_bottom").lower()
            prompt = effect.raw or "Choose a card"
            resume = "after_attack" if combat is not None else "after_play"
            paused = self._begin_card_choice(
                player_idx,
                target_idx,
                options,
                rider=rider,
                optional=effect.optional,
                prompt=prompt,
                resume=resume,
            )
            if paused:
                self._choice_ctx.update(
                    {
                        "return_phase": self._phase,
                        "card_id": card.id,
                        "fused": bool(combat.fused if combat else False),
                        "perspective": perspective_idx,
                    }
                )
            return 0.0
        if effect.kind == "choose_mode":
            if combat is not None:
                resume = "after_attack"
            elif self._pending_combat is not None:
                resume = "after_hit_combat"
            else:
                resume = "after_play_direct"
            paused = self._begin_mode_choice(
                player_idx,
                card,
                effect,
                resume=resume,
                perspective_idx=perspective_idx,
                combat=combat,
            )
            return 0.0
        if effect.kind == "reduce_defense":
            target_idx = 1 - player_idx if effect.target != "self" else player_idx
            self._apply_equipment_defense_debuff(target_idx, max(1, effect.amount or 1))
            return 0.0
        if effect.kind == "clash":
            loser_debuff = (effect.banish_name or "").lower() == "loser_equipment_debuff"
            self._do_clash(player_idx, effect.token_name or "", loser_debuff=loser_debuff)
            return 0.0
        if effect.kind == "amp":
            actor.amp += max(1, effect.amount or 1)
            self._event_append(f"amp {effect.amount or 1}: next arcane +{effect.amount or 1}")
            return 0.0
        if effect.kind in ("reload", "stash_hand"):
            legal = self._legal_stash(player_idx)
            if not legal:
                return 0.0

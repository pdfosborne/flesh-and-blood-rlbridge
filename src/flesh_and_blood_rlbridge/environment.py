def _card_name_key(name: str) -> str:
    """Normalize card names for robust DB matching."""
    text = " ".join(str(name or "").strip().split())
    text = text.replace("||", "//")
    text = text.replace(" // ", "//")
    return text.lower()


# Keyword tokens we recognize in card rules text. Only ``go_again`` and
# ``dominate`` are mechanically simulated; the rest are surfaced for display
# and for requirement/bonus hooks.
_KEYWORD_PATTERNS: dict[str, str] = {
    "go_again": r"\bgo again\b",
    "dominate": r"\bdominate\b",
    "overpower": r"\boverpower\b",
    "intimidate": r"\bintimidate\b",
    "ward": r"\bward\b",
    "fusion": r"\bfusion\b",
    "battleworn": r"\bbattleworn\b",
    "blade_break": r"\bblade break\b",
    "arcane_barrier": r"\barcane barrier\b",
    "temper": r"\btemper\b",
}


def _derive_keywords(text: str) -> tuple[str, ...]:
    """Extract recognized FAB keywords from a card's rules text."""
    body = str(text or "").lower()
    if not body:
        return ()
    found = [kw for kw, pat in _KEYWORD_PATTERNS.items() if re.search(pat, body)]
    return tuple(found)


@functools.lru_cache(maxsize=4096)
def _reveal_requirement(text: str) -> tuple[Optional[str], bool]:
    """Parse a 'reveal a <X> card' clause from rules text.

    Returns ``(token, hard)`` where ``token`` is the required card descriptor
    (e.g. ``"lightning"``) and ``hard`` is True when the reveal is mandatory
    (no "you may" qualifier) rather than an optional bonus.
    """
    body = str(text or "").lower()
    match = re.search(r"reveal an?\s+([a-z]+)\s+card\s+from\s+(?:your\s+)?hand", body)
    if not match:
        return None, False
    token = match.group(1)
    pre = body[max(0, match.start() - 40):match.start()]
    # "you may reveal" / "Fusion - reveal" are optional bonuses, not gates.
    optional = "may" in pre or "fusion" in pre
    return token, not optional


@functools.lru_cache(maxsize=4096)
def _fusion_elements(text: str) -> tuple[str, ...]:
    """Return fusion element(s) required (e.g. ``('lightning',)`` or ``('earth', 'lightning')``)."""
    body = str(text or "").lower()
    m = re.search(r"((?:[a-z]+(?:\s+and\s+[a-z]+)*))\s+fusion\b", body)
    if m:
        chunk = m.group(1).strip()
        if " and " in chunk:
            return tuple(p.strip() for p in re.split(r"\s+and\s+", chunk) if p.strip())
        return (chunk,)
    m = re.search(r"\b([a-z]+)\s+fusion\b", body)
    return (m.group(1),) if m else ()


@functools.lru_cache(maxsize=4096)
def _fusion_element(text: str) -> Optional[str]:
    """Return the primary fusion element (back-compat helper)."""
    elements = _fusion_elements(text)
    return elements[0] if elements else None


@functools.lru_cache(maxsize=8192)
def _parse_action_damage(text: str, power: int, is_attack: bool) -> tuple[int, bool]:
    """Damage an action deals when played, and whether it is arcane.

    Attack actions use printed power (physical, blockable). Non-attack actions
    fall back to parsing a "deal N [arcane] damage" clause from rules text.
    """
    body = str(text or "").lower()
    if is_attack:
        return int(power or 0), False
    if power and power > 0:
        return int(power), "arcane" in body
    match = re.search(r"deal (\d+)\s+(arcane\s+)?damage", body)
    if match:
        return int(match.group(1)), bool(match.group(2)) or "arcane damage" in body
    return 0, False


_EQUIP_SLOTS: tuple[str, ...] = ("head", "chest", "arms", "legs")


def _equipment_slot(card: "Card") -> Optional[str]:
    """Return the gear slot ('head'/'chest'/'arms'/'legs') for an equipment card."""
    line = (card.type_line or "").lower()
    if "equipment" not in line:
        return None
    for slot in _EQUIP_SLOTS:
        if slot in line:
            return slot
    return None


def _load_cards() -> dict[str, Card]:
    if not _CARDS_PATH.exists():
        raise FileNotFoundError(f"Missing Flesh and Blood card DB at {_CARDS_PATH}")

    raw = json.loads(_CARDS_PATH.read_text(encoding="utf-8"))
    cards: dict[str, Card] = {}
    for rec in raw:
        text = rec.get("text", "")
        keywords = tuple(rec.get("keywords", [])) or _derive_keywords(text)
        card = Card(
            id=rec["id"],
            name=rec["name"],
            pitch=int(rec.get("pitch", 0)),
            cost=int(rec.get("cost", 0)),
            power=int(rec.get("power", 0)),
            defense=int(rec.get("defense", 0)),
            type_line=rec.get("type_line", ""),
            card_types=tuple(rec.get("card_types", [])),
            card_class=rec.get("class", "Generic"),
            talent=rec.get("talent"),
            rarity=rec.get("rarity", "Common"),
            set_code=rec.get("set", "SIM"),
            keywords=keywords,
            text=text,
            legality=rec.get("legality", {}),
        )
        cards[card.id] = card
    return cards


def _load_heroes() -> dict[str, Hero]:
    if not _HEROES_PATH.exists():
        raise FileNotFoundError(f"Missing Flesh and Blood hero DB at {_HEROES_PATH}")

    raw = json.loads(_HEROES_PATH.read_text(encoding="utf-8"))
    heroes: dict[str, Hero] = {}
    for rec in raw:
        weapon = rec.get("weapon", {})
        hero = Hero(
            id=rec["id"],
            name=rec["name"],
            hero_class=rec.get("class", "Generic"),
            talent=rec.get("talent"),
            life=int(rec.get("life", 40)),
            intellect=int(rec.get("intellect", 4)),
            weapon_name=weapon.get("name", "Basic Weapon"),
            weapon_attack=int(weapon.get("attack", 3)),
            weapon_cost=int(weapon.get("cost", 1)),
        )
        heroes[hero.id] = hero
    return heroes


class FleshAndBloodEnvironment(rlbridgeEnvironment):
    """Talishar-inspired RL simulator for Flesh and Blood gameplay loops."""

    def __init__(
        self,
        *,
        seed: Optional[int] = None,
        agent_hero_id: str = "hero_dorinthea_ironsong",
        opponent_hero_id: str = "hero_rhinar_reckless_rampage",
        max_turns: int = 60,
        deck_size: int = 36,
        agent_deck_style: str = "balanced",
        opponent_deck_style: str = "balanced",
        format: str = "classic_constructed",
        two_phase_deckbuild: bool = False,
        self_play: bool = False,
        opponent_type: str = "preset_logic",
        render_mode: Optional[str] = None,
    ) -> None:
        self._cards = _load_cards()
        self._token_name_index = token_defs.build_token_name_index(self._cards)
        self._heroes = _load_heroes()
        self._attach_hero_abilities()
        self._rng = random.Random(seed)

        if agent_hero_id not in self._heroes:
            raise ValueError(f"Unknown agent_hero_id: {agent_hero_id}")
        if opponent_hero_id not in self._heroes:
            raise ValueError(f"Unknown opponent_hero_id: {opponent_hero_id}")

        self._agent_hero_id = agent_hero_id
        self._opponent_hero_id = opponent_hero_id
        self._max_turns = max_turns
        self._deck_size = deck_size
        self._agent_deck_style = str(agent_deck_style)
        self._opponent_deck_style = str(opponent_deck_style)
        self._format = self._normalize_format(format)
        self._two_phase_deckbuild = bool(two_phase_deckbuild)

        self._players: list[PlayerState] = []
        self._turn = 0
        self._active_player = 0
        self._phase = "action"
        self._flow_stage = "p0_opening"
        self._combat_chain_links = 0
        self._action_phase_player = 0
        self._pending_combat: Optional[CombatState] = None
        self._initialized = False
        self._last_event = ""
        self._last_combat_summary: Optional[dict[str, Any]] = None
        self._last_opponent_turn: Optional[dict[str, Any]] = None
        self._notices: list[str] = []
        self._pending_optionals: list[dict[str, Any]] = []
        self._optional_resume: Optional[str] = None
        self._optional_ctx: dict[str, Any] = {}
        self._opt_ctx: dict[str, Any] = {}
        self._opt_resume: Optional[dict[str, Any]] = None
        self._choice_ctx: dict[str, Any] = {}
        self._choice_resume: Optional[str] = None
        self._pending_die_roll: Optional[dict[str, Any]] = None
        self._optional_post_ctx: dict[str, Any] = {}
        self._play_resume_ctx: dict[str, Any] = {}
        self._render_mode = render_mode
        self._self_play = self_play
        self._opponent_type = self._normalize_opponent_type(opponent_type)
        self._opponent_policy = self._build_opponent_policy(self._opponent_type)
        self._selection_stage = False
        self._selected_deck_option: Optional[dict[str, Any]] = None
        self._selected_opponent_deck_option: Optional[dict[str, Any]] = None
        self._card_vault_cards_cache: Optional[list[dict[str, Any]]] = None

    def reset(
        self,
        seed: Optional[int] = None,
        options: Optional[dict[str, Any]] = None,
    ) -> ResetResult:
        if seed is not None:
            self._rng.seed(seed)

        opts = options or {}
        self._agent_hero_id = str(opts.get("agent_hero_id", self._agent_hero_id))
        self._opponent_hero_id = str(opts.get("opponent_hero_id", self._opponent_hero_id))
        self._agent_deck_style = str(opts.get("agent_deck_style", self._agent_deck_style))
        self._opponent_deck_style = str(opts.get("opponent_deck_style", self._opponent_deck_style))
        self._format = self._normalize_format(str(opts.get("format", self._format)))
        self._two_phase_deckbuild = bool(opts.get("two_phase_deckbuild", self._two_phase_deckbuild))
        self._opponent_type = self._normalize_opponent_type(str(opts.get("opponent_type", self._opponent_type)))
        self._opponent_policy = self._build_opponent_policy(self._opponent_type)
        self._max_turns = int(opts.get("max_turns", self._max_turns))
        self._deck_size = int(opts.get("deck_size", self._deck_size))

        min_cards, max_cards = self._format_deck_bounds()
        self._deck_size = max(min_cards, min(self._deck_size, max_cards))

        self._pending_combat = None
        self._selected_deck_option = None
        self._selected_opponent_deck_option = None

        if self._two_phase_deckbuild:
            self._players = []
            self._turn = 0
            self._active_player = 0
            self._phase = "deck_selection"
            self._selection_stage = True
            self._last_event = "Select a deck to begin the match"
        else:
            self._selection_stage = False
            self._start_match(
                agent_hero_id=self._agent_hero_id,
                opponent_hero_id=self._opponent_hero_id,
                agent_deck_style=self._agent_deck_style,
                opponent_deck_style=self._opponent_deck_style,
            )

        self._initialized = True
        return ResetResult(
            observation=self._observation(),
            info={
                "legal_actions": self._legal_actions(),
                "agent_hero": (self._players[0].hero.name if self._players else None),
                "opponent_hero": (self._players[1].hero.name if self._players else None),
                "format": self._format,
                "opponent_type": self._opponent_type,
                "stage": ("deck_selection" if self._selection_stage else "play"),
            },
        )

    def step(self, action: Any) -> StepResult:
        if not self._initialized:
            raise RuntimeError("Call reset() before step().")

        if self._selection_stage:
            legal = self._legal_actions()
            parsed = self._normalize_action(action)
            if parsed not in legal:
                if isinstance(action, int) and legal:
                    parsed = legal[action % len(legal)]
                else:
                    return StepResult(
                        observation=self._observation(),
                        reward=-0.1,
                        terminated=False,
                        truncated=False,
                        info={
                            "error": f"Illegal action {parsed!r}",
                            "legal_actions": legal,
                        },
                    )

            choice_key = parsed.split(" ", 1)[1]
            choice = next((o for o in self._deck_options_for_format() if o["key"] == choice_key), None)
            if choice is None:
                return StepResult(
                    observation=self._observation(),
                    reward=-0.1,
                    terminated=False,
                    truncated=False,
                    info={"error": f"Unknown deck option: {choice_key}", "legal_actions": legal},
                )

            self._selected_deck_option = dict(choice)
            self._agent_hero_id = str(choice["hero_id"])
            self._deck_size = int(choice["deck_size"])

            opp_choice = self._sample_opponent_matchup(agent_hero_id=self._agent_hero_id)
            self._selected_opponent_deck_option = dict(opp_choice)
            self._opponent_hero_id = str(opp_choice["hero_id"])

            self._selection_stage = False
            # Pass pre-resolved card IDs when a fabrary deck option was chosen.
            agent_card_ids: Optional[list[str]] = choice.get("_card_ids")  # type: ignore[assignment]
            opp_card_ids: Optional[list[str]] = opp_choice.get("_card_ids")  # type: ignore[assignment]
            self._start_match(
                agent_hero_id=self._agent_hero_id,
                opponent_hero_id=self._opponent_hero_id,
                agent_deck_style=str(choice["style"]),
                opponent_deck_style=str(opp_choice["style"]),
                agent_deck_ids=agent_card_ids,
                opponent_deck_ids=opp_card_ids,
            )
            self._last_event = f"Deck selected: {choice['label']} | Matchup: {opp_choice['label']}"

            info = {
                "legal_actions": self._legal_actions(),
                "phase": self._phase,
                "last_event": self._last_event,
                "turn": self._turn,
                "stage": "play",
            }
            return StepResult(
                observation=self._observation(),
                reward=0.0,
                terminated=False,
                truncated=False,
                info=info,
            )

        legal = self._legal_actions()
        parsed = self._normalize_action(action)
        if parsed not in legal:
            if legal == ["pass"]:
                # Only pass is legal - coerce so policies never deadlock.
                parsed = "pass"
            elif isinstance(action, int) and legal:
                # RL agents emit integer indices; treat them as indices into the
                # legal action list so out-of-range ints never get stuck.
                parsed = legal[action % len(legal)]
            else:
                return StepResult(
                    observation=self._observation(),
                    reward=-0.1,
                    terminated=False,
                    truncated=False,
                    info={
                        "error": f"Illegal action {parsed!r}",
                        "legal_actions": legal,
                    },
                )

        reward = 0.0
        self._notices = []

        if self._self_play:
            reward += self._step_self_play(parsed)
        else:
            if self._phase == "action":
                if parsed == "pass":
                    self._last_event = "Agent passed turn"
                    self._pass_action(0)
                elif parsed.startswith("pitch "):
                    reward += self._do_pitch(0, int(parsed.split(" ")[1]))
                elif parsed.startswith("play "):
                    reward += self._do_play_card(0, int(parsed.split(" ")[1]), 0)
                elif parsed.startswith("banishplay "):
                    reward += self._do_play_banished(0, int(parsed.split(" ")[1]), 0)
                elif parsed.startswith("gyplay "):
                    reward += self._do_play_graveyard(0, int(parsed.split(" ")[1]), 0)
                elif parsed == "weapon":
                    reward += self._do_weapon_attack(0, 0)
                elif parsed.startswith("ability "):
                    reward += self._do_ability(0, int(parsed.split(" ")[1]), 0)
            elif self._phase == "arsenal":
                if parsed == "pass":
                    self._pass_arsenal(0)
                elif parsed.startswith("stash "):
                    reward += self._do_stash(0, int(parsed.split(" ")[1]))
            elif self._phase == "defense":
                if parsed == "pass":
                    self._pass_defense(0)
                elif parsed.startswith("block "):
                    reward += self._do_block(0, int(parsed.split(" ")[1]))
                elif parsed.startswith("blockgear "):
                    reward += self._do_block_gear(0, int(parsed.split(" ")[1]))
                elif parsed.startswith("instant "):
                    reward += self._do_instant_play(0, int(parsed.split(" ")[1]), 0)
            elif self._phase == "reaction":
                if parsed == "pass":
                    reward += self._resolve_and_advance(0)
                elif parsed.startswith("reaction "):
                    reward += self._do_reaction(0, int(parsed.split(" ")[1]))
                elif parsed.startswith("instant "):
                    reward += self._do_instant_play(0, int(parsed.split(" ")[1]), 0)
            elif self._phase == "optional":
                reward += self._do_optional(parsed == "use_optional")
            elif self._phase == "choice":
                if parsed == "pass":
                    reward += self._resolve_card_choice(None)
                elif parsed.startswith("choose "):
                    reward += self._resolve_card_choice(int(parsed.split()[1]))
            elif self._phase == "opt":
                if parsed == "opt_bottom":
                    self._do_opt_choice(0, to_bottom=True)
                elif parsed == "opt_top":
                    self._do_opt_choice(0, to_bottom=False)
            # Drive the scripted opponent until the agent must decide again.
            reward += self._auto_advance()

        terminated = self._is_terminal()
        truncated = self._turn >= self._max_turns and not terminated
        if truncated:
            self._last_event = "Reached max turns"

        # Terminal win/loss bonus (primary signal)
        if terminated:
            if self._self_play:
                # In self-play the acting player just caused termination;
                # reward from the perspective of the player whose life just hit 0.
                loser = next(i for i, p in enumerate(self._players) if p.life <= 0)
                winner = 1 - loser
                # Reward for the policy: +1 if the last acting player won, -1 if lost.
                if self._active_player == winner:
                    reward += 1.0
                else:
                    reward -= 1.0
            elif self._players[0].life <= 0:
                reward -= 1.0  # agent lost
            else:
                reward += 1.0  # agent won
        else:
            reward -= 0.005  # step penalty to discourage passive looping

        info = {
            "legal_actions": [] if (terminated or truncated) else self._legal_actions(),
            "phase": self._phase,
            "last_event": self._last_event,
            "turn": self._turn,
        }
        return StepResult(
            observation=self._observation(),
            reward=reward,
            terminated=terminated,
            truncated=truncated,
            info=info,
        )


    def _mitigate_damage(self, defender_idx: int, damage: int, *, arcane: bool = False) -> int:
        """Apply Ward equipment, then prevent layers, before life loss."""
        if damage <= 0:
            return 0
        defender = self._players[defender_idx]
        remaining = damage
        while remaining > 0 and self._has_soul_pay_equipment(defender_idx) and defender.soul:
            soul_id = defender.soul.pop()
            defender.banished.append(soul_id)
            self._record_soul_banish_chain(defender_idx)
            remaining -= 1
            self._event_append(
                f"banished {self._cards[soul_id].name} from soul to prevent 1 damage"
            )
        # Ward (CR 8.3.20): destroy equipment/aura with Ward N to prevent N damage.
        for i in range(len(defender.equipment) - 1, -1, -1):
            if remaining <= 0:
                break
            cid = defender.equipment[i]
            card = self._cards[cid]
            has_blue = any(self._cards[cid].pitch == 3 for cid in defender.pitch_zone)
            ward_n = fab_rules.parse_ward_value(card.text, card.keywords, has_blue_pitched=has_blue)
            if ward_n <= 0:
                continue
            absorbed = min(ward_n, remaining)
            remaining -= absorbed
            defender.equipment.pop(i)
            defender.discard.append(cid)
            self._fire_on_leave_triggers(defender_idx, cid)
            self._event_append(f"ward on {card.name} prevented {absorbed} (destroyed)")
        if defender.prevent_damage_charges > 0 and defender.prevent_damage_per_hit > 0 and remaining > 0:
            absorbed = min(defender.prevent_damage_per_hit, remaining)
            remaining -= absorbed
            defender.prevent_damage_charges -= 1
            if absorbed:
                self._event_append(
                    f"prevented {absorbed} damage ({defender.prevent_damage_charges} preventions left)"
                )
        if defender.prevent_damage > 0 and remaining > 0:
            absorbed = min(defender.prevent_damage, remaining)
            defender.prevent_damage -= absorbed
            remaining -= absorbed
            if absorbed:
                self._event_append(f"prevented {absorbed} damage")
        if arcane and remaining > 0 and defender.arcane_barrier > 0:
            while remaining > 0 and defender.arcane_barrier > 0 and defender.resources > 0:
                defender.resources -= 1
                defender.arcane_barrier -= 1
                remaining -= 1
                self._event_append("arcane barrier prevented 1")
        return remaining

    def _has_soul_pay_equipment(self, player_idx: int) -> bool:
        for cid in self._players[player_idx].equipment:
            for trig in effects.parse_triggers(self._cards[cid].text):
                if (
                    trig.effect.kind == "prevent_damage"
                    and (trig.effect.banish_name or "").lower() == "soul_pay"
                ):
                    return True
        return False

    def _discard_random(self, player_idx: int, amount: int = 1) -> int:
        actor = self._players[player_idx]
        discarded = 0
        for _ in range(amount):
            if not actor.hand:
                break
            idx = self._rng.randint(0, len(actor.hand) - 1)
            cid = actor.hand.pop(idx)
            card = self._cards[cid]
            self._event_append(f"P{player_idx} discards {card.name}")
            actor.discard.append(cid)
            if card.power >= 6:
                actor.class_state["DiscardedPower6ThisTurn"] = 1
            self._fire_self_random_discard_triggers(player_idx, card, player_idx)
            self._fire_on_random_discard_triggers(player_idx, card, player_idx)
            discarded += 1
        return discarded

    def _fire_self_random_discard_triggers(
        self, player_idx: int, discarded: Card, perspective_idx: int
    ) -> float:
        reward = 0.0
        actor = self._players[player_idx]
        for trig in effects.parse_triggers(discarded.text):
            if trig.when != "on_discarded_random":
                continue
            if trig.effect.kind == "put_bottom" and discarded.id in actor.discard:
                actor.discard.remove(discarded.id)
                actor.deck.insert(0, discarded.id)
                self._event_append(f"{discarded.name} put on bottom of deck")
            else:
                reward += self._apply_effect(
                    player_idx, discarded, trig.effect, None, perspective_idx
                )
        return reward

    def _destroy_top_of_deck(self, player_idx: int, count: int = 1) -> None:
        actor = self._players[player_idx]
        for _ in range(max(1, count)):
            if not actor.deck and actor.discard:
                actor.deck = actor.discard
                actor.discard = []
                self._rng.shuffle(actor.deck)
            if not actor.deck:
                break
            cid = actor.deck.pop()
            actor.discard.append(cid)
            self._event_append(f"destroyed {self._cards[cid].name} from deck top")

    def _destroy_arsenal(self, player_idx: int, amount: int = 99) -> None:
        actor = self._players[player_idx]
        while actor.arsenal and amount > 0:
            cid = actor.arsenal.pop()
            actor.discard.append(cid)
            self._event_append(f"destroyed arsenal {self._cards[cid].name}")
            amount -= 1

    def _banish_from_graveyard(self, player_idx: int, amount: int = 1) -> None:
        actor = self._players[player_idx]
        for _ in range(amount):
            if not actor.discard:
                break
            cid = actor.discard.pop()
            actor.banished.append(cid)
            self._event_append(f"banished {self._cards[cid].name} from graveyard")

    def _fire_controlled_hit_triggers(
        self, attacker_idx: int, perspective_idx: int, fused: bool
    ) -> float:
        """Fire 'when an attack you control hits' on arena sources."""
        reward = 0.0
        defender = self._players[1 - attacker_idx]
        actor = self._players[attacker_idx]
        sources: list[Card] = [self._cards[cid] for cid in actor.equipment]
        if actor.weapon_id:
            sources.append(self._cards[actor.weapon_id])
        for card in sources:
            for trig in effects.parse_triggers(card.text):
                if trig.when != "on_controlled_hit":
                    continue
                if trig.effect.condition == "light_hero":
                    defender = self._players[1 - attacker_idx]
                    if (defender.hero.talent or "").strip().lower() != "light":
                        continue
                low = trig.raw.lower()
                if "marked" in low and not defender.marked:
                    continue
                if trig.effect.optional:
                    if self._optional_available(attacker_idx, trig.effect):
                        self._pending_optionals.append(
                            {
                                "player": attacker_idx,
                                "card_id": card.id,
                                "effect": trig.effect,
                                "perspective": perspective_idx,
                            }
                        )
                    continue
                reward += self._apply_effect(
                    attacker_idx, card, trig.effect, self._pending_combat, perspective_idx
                )
        return reward


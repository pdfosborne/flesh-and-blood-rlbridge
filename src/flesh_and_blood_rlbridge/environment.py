    def _reveal_available(self, player_idx: int, exclude_idx: int, token: str) -> bool:
        """True if the player can reveal another hand card matching ``token``."""
        token = (token or "").strip().lower()
        if not token:
            return False
        for i, cid in enumerate(self._players[player_idx].hand):
            if i == exclude_idx:
                continue
            c = self._cards[cid]
            haystack = " ".join(
                [c.name.lower(), (c.talent or "").lower(), c.text.lower(), " ".join(c.keywords)]
            )
            if token in haystack:
                return True
        return False

    def _play_blocked_reason(self, player_idx: int, hand_idx: int, card: Card) -> Optional[str]:
        """Return a reason string if a mandatory play requirement is unmet."""
        token, hard = _reveal_requirement(card.text)
        if token and hard and not self._reveal_available(player_idx, hand_idx, token):
            return f"{card.name} requires revealing a {token} card from hand"
        actor = self._players[player_idx]
        if (
            "attack_action" in card.card_types
            and actor.attack_play_power_cap >= 0
            and card.power <= actor.attack_play_power_cap
        ):
            return (
                f"{card.name} blocked: attacks with {card.power} or less base power "
                f"cannot be played this turn"
            )
        for mod in effects.parse_play_modifiers(card.text):
            if mod.condition.startswith("play_gate:") and not self._play_gate_met(
                player_idx, mod.condition
            ):
                return f"{card.name}: play requirement not met ({mod.raw[:60]})"
            if mod.condition == "play_zone:arsenal_only":
                if card.id not in actor.hand_from_arsenal and card.id not in actor.arsenal:
                    return f"{card.name} can only be played from arsenal"
        if actor.arsenal_play_blocked and card.id in actor.arsenal:
            return f"{card.name} blocked: cannot play face-up cards from arsenal this turn"
        return None

    def _count_equipped_evos(self, player_idx: int) -> int:
        actor = self._players[player_idx]
        count = 0
        for cid in actor.equipment:
            if "evo" in self._cards[cid].name.lower():
                count += 1
        if actor.weapon_id and "evo" in self._cards[actor.weapon_id].name.lower():
            count += 1
        return count

    def _count_blood_debt_in_banish(self, player_idx: int) -> int:
        actor = self._players[player_idx]
        return sum(
            1
            for cid in actor.banished
            if "blood_debt" in self._cards[cid].keywords
        )

    def _draconic_chain_links(self) -> int:
        """Chain links on the current combat chain with Draconic cards (approximation)."""
        combat = self._pending_combat
        if combat is None:
            return 0
        count = 0
        attack = self._cards.get(combat.attack_card_id)
        if attack and (attack.talent or "").lower() == "draconic":
            count += 1
        for _, cid, _ in combat.blocks:
            block = self._cards.get(cid)
            if block and (block.talent or "").lower() == "draconic":
                count += 1
        return count

    def _play_gate_met(self, player_idx: int, gate: str) -> bool:
        """Evaluate a parsed play_gate:kind:arg condition."""
        parts = gate.split(":")
        if len(parts) < 2 or parts[0] != "play_gate":
            return True
        kind = parts[1]
        arg = parts[2] if len(parts) > 2 else ""
        actor = self._players[player_idx]
        cs = actor.class_state
        if kind == "evos_ge":
            return self._count_equipped_evos(player_idx) >= int(arg or "1")
        if kind == "damage_taken_turn":
            return cs.get("DamageTakenThisTurn", 0) > 0
        if kind == "boosted_turn":
            return cs.get("BoostedThisTurn", 0) > 0
        if kind == "runechants_eq":
            key = token_defs.normalize_token_name("runechant")
            return actor.tokens.get(key, 0) == int(arg or "0")
        if kind == "discarded_power6_turn":
            return cs.get("DiscardedPower6ThisTurn", 0) > 0
        if kind == "pitched_power6_turn":
            return cs.get("PitchedPower6ThisTurn", 0) > 0
        if kind == "banished_power6_turn":
            return cs.get("BanishedPower6ThisTurn", 0) > 0
        if kind == "blood_debt_played_ge":
            return cs.get("BloodDebtPlayedThisTurn", 0) >= int(arg or "1")
        if kind == "blood_debt_banish_ge":
            return self._count_blood_debt_in_banish(player_idx) >= int(arg or "1")
        if kind == "phantasm_destroyed_turn":
            return cs.get("PhantasmDestroyedThisTurn", 0) > 0
        if kind == "fealty_ge":
            key = token_defs.normalize_token_name("fealty")
            return actor.tokens.get(key, 0) >= int(arg or "1")
        if kind == "draconic_links_ge":
            return self._draconic_chain_links() >= int(arg or "1")
        if kind == "weapon_attacks_ge":
            return cs.get("WeaponAttacksThisTurn", 0) >= int(arg or "1")
        if kind == "wagered_chain":
            return cs.get("WageredThisChain", 0) > 0
        if kind == "defending_action_chain":
            combat = self._pending_combat
            if combat is None:
                return False
            return any(
                "attack_action" in self._cards[cid].card_types
                for _, cid, _ in combat.blocks
            )
        if kind == "dealt_damage_turn":
            return cs.get("DamageDealt", 0) > 0
        if kind == "yellow_soul_turn":
            return cs.get("YellowSoulThisTurn", 0) > 0
        return True

    def _fusion_state(
        self, player_idx: int, hand_idx: int, card: Card
    ) -> tuple[tuple[str, ...], bool]:
        """Return fusion elements and whether the player can fuse right now."""
        if "fusion" not in set(card.keywords):
            return (), False
        elements = _fusion_elements(card.text)
        if not elements:
            return (), False
        return elements, self._can_fuse(player_idx, elements, exclude_idx=hand_idx)

    def _card_matches_element(self, card: Card, element: str) -> bool:
        token = (element or "").strip().lower()
        if not token:
            return False
        haystack = " ".join(
            [card.name.lower(), (card.talent or "").lower(), card.text.lower(), " ".join(card.keywords)]
        )
        return token in haystack

    def _can_fuse(
        self, player_idx: int, elements: tuple[str, ...], *, exclude_idx: int = -1
    ) -> bool:
        actor = self._players[player_idx]
        used: set[int] = set()
        for element in elements:
            found = False
            for i, cid in enumerate(actor.hand):
                if i == exclude_idx or i in used:
                    continue
                if self._card_matches_element(self._cards[cid], element):
                    used.add(i)
                    found = True
                    break
            if not found:
                return False
        return True

    def _consume_fusion_cards(self, player_idx: int, elements: tuple[str, ...]) -> bool:
        """Banish one hand card per fusion element (CR 8.3.8 reveal for Fusion)."""
        actor = self._players[player_idx]
        for element in elements:
            matched = False
            for i, cid in enumerate(actor.hand):
                if self._card_matches_element(self._cards[cid], element):
                    cid = actor.hand.pop(i)
                    actor.banished.append(cid)
                    self._event_append(f"fusion: banished {self._cards[cid].name}")
                    matched = True
                    break
            if not matched:
                return False
        return True

    def _is_playable_action(self, card: Card) -> bool:
        """Whether a card can be played from the action phase in this engine."""
        if "attack_action" in card.card_types:
            return True
        if "utility_action" not in card.card_types:
            return False
        # Only surface non-attack actions we can meaningfully resolve: those
        # that deal damage, chain (go again), or enable a fusion reveal.
        keywords = set(card.keywords)
        if "go_again" in keywords or "fusion" in keywords:
            return True
        damage, _ = _parse_action_damage(card.text, card.power, False)
        return damage > 0


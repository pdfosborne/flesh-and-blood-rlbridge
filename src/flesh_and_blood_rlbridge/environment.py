    def _load_card_vault_feed(self) -> list[dict[str, Any]]:
        """Load raw card records from the official card vault (or fallback mirror)."""
        if self._card_vault_cards_cache is not None:
            return self._card_vault_cards_cache

        try:
            importer = importlib.import_module("flesh_and_blood_rlbridge.card_db.import_from_talishar")
        except Exception:
            self._card_vault_cards_cache = []
            return self._card_vault_cards_cache

        load_cards = getattr(importer, "load_cards", None)
        if load_cards is None:
            self._card_vault_cards_cache = []
            return self._card_vault_cards_cache

        for source_url in _CARD_VAULT_FEED_URL_CANDIDATES:
            try:
                records = load_cards(path=None, source_url=source_url)
                if isinstance(records, list) and records:
                    self._card_vault_cards_cache = records
                    return records
            except Exception:
                continue

        self._card_vault_cards_cache = []
        return self._card_vault_cards_cache

    def _import_missing_cards_from_card_vault(self, card_names: list[str]) -> int:
        """Append missing cards to cards.json by scanning card-vault data."""
        targets = {_card_name_key(name) for name in card_names if str(name).strip()}
        if not targets:
            return 0

        raw_records = self._load_card_vault_feed()
        if not raw_records:
            return 0

        by_name: dict[str, list[dict[str, Any]]] = {}
        for rec in raw_records:
            if not isinstance(rec, dict):
                continue
            key = _card_name_key(rec.get("name", ""))
            if not key:
                continue
            by_name.setdefault(key, []).append(rec)

        selected: list[dict[str, Any]] = []
        for key in sorted(targets):
            selected.extend(by_name.get(key, []))
        if not selected:
            return 0

        try:
            importer = importlib.import_module("flesh_and_blood_rlbridge.card_db.import_from_talishar")
            normalize_record = getattr(importer, "normalize_record", None)
            if normalize_record is None:
                return 0
        except Exception:
            return 0

        try:
            current_cards = json.loads(_CARDS_PATH.read_text(encoding="utf-8"))
            if not isinstance(current_cards, list):
                return 0
        except Exception:
            return 0

        existing_ids = {str(rec.get("id", "")) for rec in current_cards if isinstance(rec, dict)}
        normalized_new: list[dict[str, Any]] = []
        for rec in selected:
            try:
                norm = normalize_record(rec)
            except Exception:
                continue
            card_id = str(norm.get("id", ""))
            if not card_id or card_id in existing_ids:
                continue
            existing_ids.add(card_id)
            normalized_new.append(norm)

        if not normalized_new:
            return 0

        current_cards.extend(normalized_new)
        _CARDS_PATH.write_text(json.dumps(current_cards, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")
        self._cards = _load_cards()
        self._attach_hero_abilities()
        return len(normalized_new)

    def _build_name_lookup(self, hero: Hero) -> dict[str, list[Card]]:
        """Build normalized card-name lookup restricted to hero and format legality."""
        by_name: dict[str, list[Card]] = {}
        for card in self._cards.values():
            if not self._is_card_legal_for_format(card.id):
                continue
            if not self._is_deck_candidate(card):
                continue
            if not self._is_card_compatible_with_hero(card, hero):
                continue
            by_name.setdefault(_card_name_key(card.name), []).append(card)
        return by_name

    def _resolve_fabrary_deck(self, deck_entry: dict[str, Any]) -> list[str]:
        """Map a fabrary deck entry to a list of card IDs legal for the current format.

        Strategy:
        - For each {name, count} entry look up all pitch versions of that card
          that are legal and compatible with the hero.
        - Include up to ``count`` copies of *each* pitch version found.
        - Apply the per-card-ID copy limit (2 for silver_age, 3 for CC).
        - If the list exceeds ``max_deck_size`` it is randomly trimmed.
        - If it falls below ``min_deck_size`` it is padded with generic filler.
        """
        hero_id = str(deck_entry.get("hero_id", ""))
        if hero_id not in self._heroes:
            return []
        hero = self._heroes[hero_id]

        # Build name → [Card, ...] lookup restricted to this hero + format.
        by_name = self._build_name_lookup(hero)

        missing_names: list[str] = []
        for entry in deck_entry.get("cards", []):
            raw_name = str(entry.get("name", "")).strip()
            if raw_name and _card_name_key(raw_name) not in by_name:
                missing_names.append(raw_name)
        if missing_names:
            imported = self._import_missing_cards_from_card_vault(missing_names)
            if imported > 0:
                by_name = self._build_name_lookup(hero)

        copy_limit = 2 if self._format == "silver_age" else 3
        deck: list[str] = []

        for entry in deck_entry.get("cards", []):
            raw_name = str(entry.get("name", "")).strip()
            count = max(1, int(entry.get("count", 1)))
            matches = by_name.get(_card_name_key(raw_name), [])
            if not matches:
                continue  # card not in DB or not legal/compatible for this hero+format
            per_copy = min(count, copy_limit)
            # Sort pitch=1 (red) first so trimming preserves the strongest copies.
            for card in sorted(matches, key=lambda c: c.pitch):
                deck.extend([card.id] * per_copy)

        if not deck:
            return []

        min_cards, max_cards = self._format_deck_bounds()

        # Trim excess randomly if deck exceeds format maximum.
        if len(deck) > max_cards:
            self._rng.shuffle(deck)
            deck = deck[:max_cards]

        # Pad below minimum with generic legal filler cards.
        if len(deck) < min_cards:
            existing_ids = set(deck)
            filler_pool = [
                c for c in self._cards.values()
                if self._is_card_legal_for_format(c.id)
                and self._is_deck_candidate(c)
                and self._is_card_compatible_with_hero(c, hero)
                and c.id not in existing_ids
            ]
            self._rng.shuffle(filler_pool)
            for filler in filler_pool:
                if len(deck) >= min_cards:
                    break
                deck.append(filler.id)

        return deck

    def _fabrary_deck_options_for_format(self) -> list[dict[str, Any]]:
        """Return deck option dicts for all fabrary decks matching the current format.

        Each option has the same shape as procedural options plus extra fields:
        ``source``, ``source_url``, ``description``, and ``_card_ids``
        (the pre-resolved card ID list used by ``_new_player``).
        Keys are prefixed with ``"fab_"`` to avoid collisions with procedural keys.
        """
        raw_decks = self._load_fabrary_db()
        options: list[dict[str, Any]] = []
        for deck_entry in raw_decks:
            if str(deck_entry.get("format", "")) != self._format:
                continue
            hero_id = str(deck_entry.get("hero_id", ""))
            if hero_id not in self._heroes:
                continue
            card_ids = self._resolve_fabrary_deck(deck_entry)
            if not card_ids:
                continue
            options.append(
                {
                    "key": deck_entry["id"],
                    "label": deck_entry.get("name", deck_entry["id"]),
                    "hero_id": hero_id,
                    "style": str(deck_entry.get("style", "balanced")),
                    "deck_size": len(card_ids),
                    "source": "fabrary",
                    "source_url": deck_entry.get("source_url", ""),
                    "description": deck_entry.get("description", ""),
                    "_card_ids": card_ids,
                }
            )
        return options

    def _start_match(
        self,
        *,
        agent_hero_id: str,
        opponent_hero_id: str,
        agent_deck_style: str,
        opponent_deck_style: str,
        agent_deck_ids: Optional[list[str]] = None,
        opponent_deck_ids: Optional[list[str]] = None,
    ) -> None:
        self._players = [
            self._new_player(self._heroes[agent_hero_id], hero_slot=0, deck_style=agent_deck_style, deck_ids=agent_deck_ids),
            self._new_player(self._heroes[opponent_hero_id], hero_slot=1, deck_style=opponent_deck_style, deck_ids=opponent_deck_ids),
        ]
        for idx, player in enumerate(self._players):
            for cid in player.equipment:
                self._fire_enters_triggers(idx, self._cards[cid])
            if player.weapon_id:
                self._fire_enters_triggers(idx, self._cards[player.weapon_id])
            self._apply_hero_passives(idx)
        self._turn = 1
        self._active_player = 0
        self._phase = "action"
        self._pending_combat = None
        self._flow_stage = "p0_opening"
        self._combat_chain_links = 0
        self._action_phase_player = 0
        self._last_event = "Game start — both players draw opening hands"
        self._draw_up(0)
        self._draw_up(1)
        self._begin_action_phase(0)

    def _starting_life(self, hero: Hero) -> int:
        # Talishar profile: Silver Age uses young-hero life profile.
        if self._format == "silver_age":
            return min(hero.life, 20)
        return hero.life

    def _is_deck_candidate(self, card: Card) -> bool:
        if "hero" in card.card_types:
            return False
        if "attack_action" in card.card_types:
            return True
        # Non-attack actions and reactions enable combinations (fusion, arcane
        # bolts, attack/defense reactions) so they belong in the deck too.
        if "utility_action" in card.card_types:
            return True
        if "attack_reaction" in card.card_types:
            return True
        if "defense_reaction" in card.card_types:
            return True
        if card.defense > 0:
            return True
        return False

    def _is_card_compatible_with_hero(self, card: Card, hero: Hero) -> bool:
        card_class = (card.card_class or "Generic").strip().upper()
        hero_class = (hero.hero_class or "Generic").strip().upper()
        if card_class not in {"", "GENERIC", "NONE"} and card_class != hero_class:
            return False

        card_talent = (card.talent or "").strip().upper()
        hero_talent = (hero.talent or "").strip().upper()
        if card_talent not in {"", "NONE"} and card_talent != hero_talent:
            return False

        return True

    def _select_equipment(self, hero: Hero) -> list[str]:
        """Pick one compatible piece for each gear slot at game setup.

        Prefers higher-defense pieces and avoids self-destroying gear
        (battleworn / blade break) so the loadout survives a few blocks.
        """
        by_slot: dict[str, list[Card]] = {s: [] for s in _EQUIP_SLOTS}
        for card in self._cards.values():
            slot = _equipment_slot(card)
            if slot is None:
                continue
            if not self._is_card_legal_for_format(card.id):
                continue
            if not self._is_card_compatible_with_hero(card, hero):
                continue
            by_slot[slot].append(card)

        loadout: list[str] = []
        for slot in _EQUIP_SLOTS:
            options = by_slot[slot]
            if not options:
                continue
            options.sort(
                key=lambda c: (
                    c.defense,
                    0 if ({"battleworn", "blade_break"} & set(c.keywords)) else 1,
                    -c.cost,
                ),
                reverse=True,
            )
            loadout.append(options[0].id)
        return loadout

    @staticmethod
    def _is_weapon_card(card: Card) -> bool:
        return "weapon" in (card.type_line or "").lower() and "utility_item" in card.card_types

    def _weapon_swing_cost(self, card: Card) -> int:
        """Resource cost of a weapon's printed attack ability ({r} count)."""
        for ability in effects.parse_activated_abilities(card.text):
            if "attack" in ability.raw.lower():
                return ability.cost
        return 0

    def _select_weapon(self, hero: Hero) -> Optional[str]:
        """Pick a real weapon card for the hero (else fall back to basic weapon).

        Prefers higher attack power, and rewards weapons that also carry an
        activated ability we can resolve (e.g. an arcane staff).
        """
        best: Optional[Card] = None
        best_score = float("-inf")
        hero_class = (hero.hero_class or "Generic").strip().upper()
        for card in self._cards.values():
            if not self._is_weapon_card(card):
                continue
            if not self._is_card_legal_for_format(card.id):
                continue
            if not self._is_card_compatible_with_hero(card, hero):
                continue
            has_ability = any(
                a.implemented for a in effects.parse_activated_abilities(card.text)
            )
            class_specific = (card.card_class or "Generic").strip().upper() == hero_class
            swing_cost = self._weapon_swing_cost(card)
            # Favor a thematic class weapon, then a weapon the hero can actually
            # swing (low resource cost), then attack power, then a usable ability.
            score = (
                (10 if class_specific else 0)
                + (card.power if card.power > 0 else 0)
                - swing_cost * 2
                + (3 if has_ability else 0)
            )
            if score > best_score:
                best_score, best = score, card
        return best.id if best is not None else None

    def _weapon_stats(self, player_idx: int) -> tuple[str, int, int, Optional[Card]]:
        """Return (name, attack, swing_cost, weapon_card) for a player's weapon."""
        p = self._players[player_idx]
        if p.weapon_id is not None:
            card = self._cards[p.weapon_id]
            return card.name, card.power, self._weapon_swing_cost(card), card
        hero = p.hero
        return hero.weapon_name, hero.weapon_attack, hero.weapon_cost, None

    def _attach_hero_abilities(self) -> None:
        """Populate each hero's special-ability text from its hero card."""
        index: dict[str, str] = {}
        for card in self._cards.values():
            if "hero" in card.card_types and card.text:
                index.setdefault(_card_name_key(card.name), card.text)
        for hid, hero in list(self._heroes.items()):
            if hero.ability_text:
                continue
            text = index.get(_card_name_key(hero.name), "")
            if text:
                self._heroes[hid] = dataclasses.replace(hero, ability_text=text)

    def _hero_pool_for_format(self) -> list[Hero]:
        heroes = list(self._heroes.values())
        if self._format == "silver_age":
            filtered = [h for h in heroes if h.life < 30]
        else:
            filtered = [h for h in heroes if h.life >= 30]
        if not filtered:
            filtered = heroes
        filtered.sort(key=lambda h: h.name.lower())
        return filtered

    def _is_card_legal_for_format(self, card_id: str) -> bool:
        card = self._cards[card_id]
        if self._format == "classic_constructed":
            return str(card.legality.get("classic_constructed", "legal")).lower() == "legal"

        if self._format == "silver_age":
            return str(card.legality.get("silver_age", "banned")).lower() == "legal"

        return True

    def _draw_card(self, player_idx: int, *, from_action: bool = False) -> bool:
        p = self._players[player_idx]
        if not p.deck and p.discard:
            p.deck = p.discard
            p.discard = []
            self._rng.shuffle(p.deck)
        if not p.deck:
            return False
        p.hand.append(p.deck.pop())
        p.class_state["NumCardsDrawn"] += 1
        if from_action:
            p.class_state["DrawFromActionThisTurn"] = (
                p.class_state.get("DrawFromActionThisTurn", 0) + 1
            )
            self._fire_passive_triggers(player_idx, "whenever_action_draw", 1)
        if self._phase == "action":
            self._fire_passive_triggers(player_idx, "whenever_any_draw", 1)
        return True

    def _fire_passive_triggers(
        self, player_idx: int, when: str, amount: int = 1
    ) -> None:
        actor = self._players[player_idx]
        sources: list[Card] = [self._cards[cid] for cid in actor.equipment]
        if actor.weapon_id:
            sources.append(self._cards[actor.weapon_id])
        for card in sources:
            for trig in effects.parse_triggers(card.text):
                if trig.when != when or not trig.effect.implemented:
                    continue
                eff = trig.effect
                if eff.kind == "create_token":
                    n = max(1, amount or 1)
                    self._create_token(player_idx, eff.token_name, n)
                    self._event_append(
                        f"{card.name}: created {n} {eff.token_name} token(s)"
                    )
                elif eff.kind == "lose_gold":
                    actor.gold = max(0, actor.gold - max(1, eff.amount or 1))
                    self._event_append(f"{card.name}: lost {eff.amount or 1} gold on draw")
                else:
                    self._apply_effect(player_idx, card, eff, self._pending_combat, player_idx)

    def _fire_equipment_triggers(
        self,
        player_idx: int,
        when: str,
        perspective_idx: int = 0,
    ) -> float:
        """Fire optional/mandatory triggers on equipment and weapon for a given event."""
        reward = 0.0
        actor = self._players[player_idx]
        sources: list[Card] = [self._cards[cid] for cid in actor.equipment]
        if actor.weapon_id:
            sources.append(self._cards[actor.weapon_id])
        for card in sources:
            for trig in effects.parse_triggers(card.text):
                if trig.when != when or not trig.effect.implemented:
                    continue
                eff = trig.effect
                if eff.optional:
                    if self._optional_available(player_idx, eff):
                        self._pending_optionals.append(
                            {
                                "player": player_idx,
                                "card_id": card.id,
                                "effect": eff,
                                "perspective": perspective_idx,
                            }
                        )
                    continue
                reward += self._apply_effect(
                    player_idx, card, eff, self._pending_combat, perspective_idx
                )
        return reward

    def _fire_deck_banish_item_triggers(self, player_idx: int, perspective_idx: int = 0) -> None:
        actor = self._players[player_idx]
        if not actor.banished:
            return
        card = self._cards[actor.banished[-1]]
        if not self._is_arena_permanent(card):
            return
        self._fire_equipment_triggers(player_idx, "on_deck_banish_item", perspective_idx)

    def _fire_arrow_from_deck_triggers(
        self, player_idx: int, arrow_id: str, perspective_idx: int = 0
    ) -> None:
        self._players[player_idx].class_state["LastArrowFromDeckId"] = arrow_id
        self._fire_equipment_triggers(player_idx, "on_arrow_from_deck", perspective_idx)

    def _put_arrow_from_deck_to_arsenal(self, player_idx: int) -> bool:
        actor = self._players[player_idx]
        if actor.arsenal or not actor.deck:
            return False
        top = actor.deck[-1]
        card = self._cards[top]
        tl = (card.type_line or "").lower()
        if "arrow" not in tl and "arrow" not in card.name.lower():
            return False
        cid = actor.deck.pop()
        actor.arsenal.append(cid)
        self._event_append(f"put {card.name} face-up in arsenal from deck")
        self._fire_arrow_from_deck_triggers(player_idx, cid)
        return True

    def _do_beat_chest(self, player_idx: int, perspective_idx: int = 0) -> float:
        actor = self._players[player_idx]
        if not actor.hand:
            self._last_event = "No cards to beat chest"
            return -0.05
        idx = random.randrange(len(actor.hand))
        cid = actor.hand.pop(idx)
        self._event_append(f"beat chest: discarded {self._cards[cid].name}")
        actor.discard.append(cid)
        return self._fire_equipment_triggers(player_idx, "on_beat_chest", perspective_idx)

    def _damage_target_idx(
        self,
        player_idx: int,
        effect: "effects.Effect",
        combat: Optional[CombatState],
    ) -> int:
        if effect.target == "attacking_hero" and combat is not None:
            return combat.attacker
        if effect.target in ("opponent", "ally"):
            return 1 - player_idx
        if effect.target == "self":
            return player_idx
        return 1 - player_idx

    def _draw_up(self, player_idx: int) -> None:
        p = self._players[player_idx]
        while len(p.hand) < p.hero.intellect:
            if not self._draw_card(player_idx):
                break

    def _begin_action_phase(self, player_idx: int) -> None:
        """Start a player's action (attack) phase."""
        p = self._players[player_idx]
        p.resources = 0
        p.action_points = 1
        for key in _PER_TURN_COUNTERS:
            p.class_state[key] = 0
        for key in list(p.class_state.keys()):
            if str(key).startswith("NamedPower:"):
                p.class_state[key] = 0
        p.weapon_used = False
        p.arena_used = set()
        p.playable_banished = set()
        p.playable_graveyard = set()
        p.tokens_controlled_turn = set()
        p.prevent_damage = 0
        p.prevent_damage_charges = 0
        p.prevent_damage_per_hit = 0
        p.marked = False
        p.amp = 0
        p.arcane_barrier = 0
        p.cheered_this_turn = False
        p.booed_this_turn = False
        p.play_as_instant = False
        p.extra_play_cost = 0
        p.extra_defense_reaction_cost = 0
        p.attack_play_power_cap = -1
        p.instant_class_filter = ""
        p.arsenal_play_blocked = False
        p.extra_attack_targets = 0
        p.weapon_attacks_blocked = False
        p.hand_from_arsenal = set()
        p.deck_top_play_used = False
        p.may_play_grants = list(p.hero_may_play_grants)
        self._process_token_upkeep(player_idx)
        self._fire_turn_start_triggers(player_idx)
        self._fire_action_phase_triggers(player_idx)
        if p.arsenal:
            p.hand_from_arsenal.update(p.arsenal)
            p.hand.extend(p.arsenal)
            p.arsenal = []
        self._active_player = player_idx
        self._action_phase_player = player_idx
        self._phase = "action"
        self._combat_chain_links = 0
        if player_idx == 1:
            self._last_opponent_turn = {
                "pitches": [],
                "attack_card": None,
                "attack_power": None,
                "is_weapon": False,
            }

    def _finish_action_phase(self, player_idx: int) -> None:
        """End the active player's action phase and advance the game flow."""
        p = self._players[player_idx]
        if p.pitch_zone:
            p.deck[:0] = p.pitch_zone
            p.pitch_zone = []
        p.resources = 0
        p.action_points = 0
        self._process_blood_debt(player_idx)
        if p.intimidated:
            p.hand.extend(p.intimidated)
            p.intimidated = []
            self._event_append("intimidated cards returned to hand")
        if p.silenced:
            p.silenced = False
            self._event_append("silence ended")
        self._clear_chain_may_play_grants(0)
        self._clear_chain_may_play_grants(1)
        p.may_play_grants = list(p.hero_may_play_grants)
        self._fire_end_phase_triggers(player_idx)
        self._combat_chain_links = 0
        self._turn += 1

        if self._flow_stage == "p0_opening":
            self._draw_up(0)
            self._draw_up(1)
            self._flow_stage = "p1_opening"
            self._last_event = (
                f"P{player_idx} ended opening attack phase — both players draw to full hand"
            )
            self._begin_action_phase(1)
        elif self._flow_stage == "p1_opening":
            self._draw_up(player_idx)
            self._flow_stage = "normal"
            self._last_event = (
                f"P{player_idx} ended opening attack phase — P{player_idx} draws to full hand"
            )
            self._begin_action_phase(0)
        else:
            self._draw_up(player_idx)
            next_player = 1 - player_idx
            self._last_event = (
                f"P{player_idx} ended attack phase — P{player_idx} draws to full hand; "
                f"P{next_player} attacks next"
            )
            self._begin_action_phase(next_player)

    def _begin_arsenal_step(self, player_idx: int) -> None:
        """Optional one-card arsenal stash after attacks, before end-of-phase draw."""
        p = self._players[player_idx]
        p.action_points = 0
        self._active_player = player_idx
        if not p.hand or p.arsenal:
            self._finish_action_phase(player_idx)
            return
        self._phase = "arsenal"
        self._last_event = f"P{player_idx} may stash a card in arsenal before drawing"

    def _pass_arsenal(self, player_idx: int) -> None:
        self._last_event = f"P{player_idx} skipped arsenal stash"
        self._finish_action_phase(player_idx)

    def _flow_segment_label(self) -> str:
        """Human-readable description of the current turn segment."""
        if self._phase == "defense" and self._pending_combat is not None:
            atk, dfn = self._pending_combat.attacker, self._pending_combat.defender
            link = self._combat_chain_links
            chain = f" (combat chain link {link})" if link > 1 else ""
            return f"P{dfn} defending vs P{atk}'s attack{chain}"
        if self._phase == "reaction" and self._pending_combat is not None:
            return f"P{self._pending_combat.attacker} attack reactions (combat chain link {self._combat_chain_links})"
        if self._phase == "arsenal":
            player = self._action_phase_player
            if self._flow_stage == "p0_opening":
                return f"P{player} arsenal step after opening attacks (then draw)"
            if self._flow_stage == "p1_opening":
                return f"P{player} arsenal step after opening attacks (then draw)"
            return f"P{player} arsenal step (stash optional, then draw)"
        if self._phase == "action":
            if self._flow_stage == "p0_opening":
                return "P0 opening attack phase (no draw)"
            if self._flow_stage == "p1_opening":
                return "P1 opening attack phase (no draw)"
            return f"P{self._action_phase_player} attack phase (draw after)"
        return self._phase


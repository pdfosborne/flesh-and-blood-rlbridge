"""
rlbridge Flesh and Blood Environment (Talishar-Inspired)
====================================================
A turn-based TCG simulator inspired by Talishar-style gameplay loops.

This environment models the core Flesh and Blood gameplay loop:

- Two heroes (agent vs scripted opponent) with hand/deck/discard zones and
  draw-up-to-intellect each turn.
- Pitch economy: resources start at 0 each turn and are generated by pitching
  cards (by their pitch value); pitched cards go to the bottom of the deck.
- Action phase: pitch cards, then play attack actions (cost + 1 action point).
- Combat chain with reaction windows:
    * Defense phase: the defender may block with multiple cards.
    * Reaction phase: the attacker may play attack reactions to boost power.
- Keyword effects derived from card text: ``go again`` (chain another attack),
  ``dominate`` (defender limited to one blocking card), plus a requirement hook
  for "reveal a <type> card from hand" / fusion-style conditional bonuses.

Reward signal summary:

- Terminal win: `+1.0`; terminal loss: `-1.0`.
- Dense shaping: `+0.01 * damage_dealt` and `-0.005 * damage_received` per combat resolution.
- Step penalty of `-0.005` per step discourages passive play.
- Illegal actions receive a penalty (`-0.1`, except pass is auto-coerced when it is the only legal action).
- Invalid block/play attempts apply `-0.05`.
- Blocking carries no shaping bonus; win/loss is the primary signal.

The simulator is designed for training and protocol integration, not as a full
competitive-rules implementation.
"""


    def _fire_on_leave_triggers(self, player_idx: int, card_id: str, perspective_idx: int = 0) -> None:
        """Fire on-leave triggers when a permanent leaves the arena."""
        card = self._cards[card_id]
        actor = self._players[player_idx]
        for trig in effects.parse_triggers(card.text):
            if trig.when != "on_leave":
                continue
            eff = trig.effect
            if eff.condition == "once_per_turn":
                if actor.class_state.get(f"OncePerTurn:{card.id}"):
                    continue
            if eff.optional:
                if self._optional_available(player_idx, eff):
                    self._pending_optionals.append(
                        {
                            "player": player_idx,
                            "card_id": card.id,
                            "effect": eff,
                            "perspective": perspective_idx,
                        }
                    )
                continue
            self._apply_effect(player_idx, card, eff, None, perspective_idx)
            if eff.condition == "once_per_turn":
                self._mark_once_per_turn_used(player_idx, card)

    def _check_no_frost_destroy(self, player_idx: int, card_id: str) -> None:
        card = self._cards.get(card_id)
        if card is None or "when it has no frost counters, destroy it" not in (card.text or "").lower():
            return
        if self._permanent_counters(player_idx, card_id).get("frost", 0) > 0:
            return
        actor = self._players[player_idx]
        if card_id in actor.equipment:
            actor.equipment.remove(card_id)
            actor.discard.append(card_id)
            self._fire_on_destroy_triggers(player_idx, card_id, player_idx)
            self._fire_on_leave_triggers(player_idx, card_id, player_idx)
            self._event_append(f"destroyed {card.name} (no frost counters)")

    def _fire_on_destroy_triggers(
        self, player_idx: int, card_id: str, perspective_idx: int = 0
    ) -> None:
        card = self._cards[card_id]
        for trig in effects.parse_triggers(card.text):
            if trig.when != "on_destroy":
                continue
            eff = trig.effect
            if eff.optional:
                if self._optional_available(player_idx, eff):
                    self._pending_optionals.append(
                        {
                            "player": player_idx,
                            "card_id": card.id,
                            "effect": eff,
                            "perspective": perspective_idx,
                        }
                    )
                continue
            self._apply_effect(player_idx, card, eff, None, perspective_idx)

    def _fire_controlled_destroy_triggers(
        self,
        owner_idx: int,
        destroyed: Card,
        perspective_idx: int = 0,
    ) -> None:
        tl = (destroyed.type_line or "").lower()
        if " aura" not in tl and not tl.endswith("aura") and "attack" not in tl:
            return
        owner = self._players[owner_idx]
        for cid in owner.equipment:
            if cid == destroyed.id:
                continue
            card = self._cards[cid]
            for trig in effects.parse_triggers(card.text):
                if trig.when != "on_controlled_destroy":
                    continue
                if (
                    trig.effect.kind == "put_soul"
                    and (trig.effect.banish_name or "").lower() == "destroyed_light"
                ):
                    tl = (destroyed.type_line or "").lower()
                    if (destroyed.talent or "").lower() == "light" and "token" not in tl:
                        if destroyed.id in owner.discard:
                            owner.discard.remove(destroyed.id)
                        owner.soul.append(destroyed.id)
                        self._event_append(f"{destroyed.name} put into soul")
                    continue
                self._apply_effect(owner_idx, card, trig.effect, None, perspective_idx)

    def _run_triggers(
        self,
        player_idx: int,
        card: Card,
        when: str,
        combat: Optional[CombatState],
        perspective_idx: int,
        fused: bool,
    ) -> float:
        reward = 0.0
        actor = self._players[player_idx]
        for trig in effects.parse_triggers(card.text):
            if trig.when != when:
                continue
            # Don't fire a fused-gated effect when the card wasn't fused.
            if when != "when_fused" and not fused and "fused" in trig.raw.lower():
                continue
            eff = trig.effect
            if eff.condition == "once_per_turn" and actor.class_state.get(f"OncePerTurn:{card.id}"):
                continue
            # Optional ("you may") effects become a player decision instead of
            # auto-resolving -- queue them if they could do something now.
            if eff.implemented and eff.optional:
                if self._optional_available(player_idx, eff):
                    self._pending_optionals.append(
                        {"player": player_idx, "card_id": card.id, "effect": eff, "perspective": perspective_idx}
                    )
                continue
            reward += self._apply_effect(player_idx, card, eff, combat, perspective_idx)
            if self._phase == "choice":
                if when == "on_hit" and self._pending_combat:
                    self._choice_ctx["resume"] = "after_hit_combat"
                elif when == "on_attack" and combat is not None:
                    self._choice_ctx["resume"] = "after_attack"
                elif when == "on_play":
                    self._choice_ctx["resume"] = "after_play_direct"
                return reward
            if eff.condition == "once_per_turn":
                self._mark_once_per_turn_used(player_idx, card)
        return reward

    def _optional_available(self, player_idx: int, effect: "effects.Effect") -> bool:
        """Whether an optional effect could actually do something if taken."""
        if effect.kind == "banish_combo":
            target = effect.banish_name.lower()
            return any(target in self._cards[c].name.lower() for c in self._players[player_idx].discard)
        if effect.kind in ("reload", "stash_hand"):
            actor = self._players[player_idx]
            return not actor.arsenal and bool(actor.hand)
        if effect.kind == "boost":
            return bool(self._players[player_idx].deck)
        if effect.kind == "put_item_in_arena":
            max_cost = max(1, effect.amount or 1)
            actor = self._players[player_idx]
            if effect.target == "banished":
                return any(
                    self._is_arena_permanent(self._cards[c])
                    and self._cards[c].cost <= max_cost
                    for c in actor.banished
                )
            return any(
                self._is_arena_permanent(self._cards[cid])
                and self._cards[cid].cost <= max_cost
                for cid in actor.hand
            )
        if effect.kind == "put_arrow_arsenal":
            actor = self._players[player_idx]
            return not actor.arsenal and any(
                "arrow" in (self._cards[c].type_line or "").lower()
                or "arrow" in self._cards[c].name.lower()
                for c in actor.hand
            )
        if effect.kind == "heave":
            return len(self._players[player_idx].hand) >= max(1, effect.amount or 1)
        if effect.kind == "scrap":
            return bool(self._players[player_idx].hand)
        if effect.kind == "additional_pay":
            return self._players[player_idx].resources >= max(1, effect.amount or 1)
        if effect.kind == "pitch_pay":
            actor = self._players[player_idx]
            return any(self._cards[cid].pitch > 0 for cid in actor.hand)
        if effect.kind == "fusion":
            elements = tuple(
                e.strip() for e in (effect.banish_name or "").split(",") if e.strip()
            )
            return bool(elements) and self._can_fuse(player_idx, elements)
        if effect.kind == "enable_gy_play":
            actor = self._players[player_idx]
            pat = (effect.banish_name or "this").strip().lower()
            if pat in ("", "this"):
                return True
            return any(
                self._gy_play_pattern_match(self._cards[cid], pat) for cid in actor.discard
            )
        if effect.kind == "put_soul":
            actor = self._players[player_idx]
            color_filter = (effect.banish_name or "").lower()
            if color_filter in ("red", "yellow", "blue"):
                pitch_map = {"red": 1, "yellow": 2, "blue": 3}
                target_pitch = pitch_map[color_filter]
                return any(self._cards[cid].pitch == target_pitch for cid in actor.hand)
            return bool(actor.hand)
        if effect.kind == "remove_counter":
            token = (effect.token_name or "").lower()
            return any(
                self._permanent_counters(player_idx, cid).get(token, 0) > 0
                for cid in self._players[player_idx].equipment
            )
        return True

    def _do_optional(self, accept: bool) -> float:
        """Resolve the next pending optional decision (use it or decline)."""
        if not self._pending_optionals:
            self._resume_after_optional()
            return 0.0
        opt = self._pending_optionals.pop(0)
        reward = 0.0
        card = self._cards[opt["card_id"]]
        if accept:
            reward = self._apply_effect(opt["player"], card, opt["effect"], self._pending_combat, opt["perspective"])
        else:
            self._event_append(f"declined {card.name} optional")
        if not self._pending_optionals:
            self._resume_after_optional()
        return reward

    def _finish_attack_triggers(
        self,
        player_idx: int,
        card: Card,
        perspective_idx: int,
        fused: bool,
    ) -> float:
        """Run on-play / on-attack triggers after optional play costs."""
        combat = self._pending_combat
        reward = self._run_triggers(player_idx, card, "on_play", combat, perspective_idx, fused)
        if fused:
            reward += self._run_triggers(player_idx, card, "when_fused", combat, perspective_idx, fused)
        reward += self._run_triggers(player_idx, card, "on_attack", combat, perspective_idx, fused)
        if self._phase == "choice":
            return reward
        if "song" in (card.type_line or "").lower():
            reward += self._fire_equipment_triggers(player_idx, "whenever_song", perspective_idx)
        self._queue_play_keywords(player_idx, card, perspective_idx)
        if self._pending_optionals:
            self._optional_resume = "defense"
            self._phase = "optional"
            self._active_player = player_idx
        else:
            self._enter_defense()
        return reward

    def _resume_after_optional(self) -> None:
        tag, self._optional_resume = self._optional_resume, None
        if tag == "post_play_costs":
            ctx = self._play_resume_ctx
            self._play_resume_ctx = {}
            card = self._cards[ctx["card_id"]]
            fused = ctx.get("fused", False)
            if self._pending_combat is not None:
                fused = fused or self._pending_combat.fused
                self._finish_attack_triggers(ctx["player"], card, ctx["perspective"], fused)
            else:
                ctx_fused = ctx.get("fused", False)
                self._resolve_direct_effects(
                    ctx["player"],
                    card,
                    ctx["damage"],
                    ctx["arcane"],
                    ctx["go_again"],
                    ctx["dominate"],
                    ctx_fused,
                    ctx.get("elements", ()),
                    ctx["perspective"],
                )
        elif tag == "defense":
            self._enter_defense()
        elif tag == "advance":
            self._finish_combat_advance()
        elif tag == "direct_finish":
            ctx = self._optional_post_ctx
            self._optional_post_ctx = {}
            player = ctx.get("player", self._active_player)
            if ctx.get("go_again"):
                self._grant_go_again(player, None, this_card=False)
            if not self._is_terminal():
                if self._players[player].action_points > 0:
                    self._phase = "action"
                    self._active_player = player
                else:
                    self._begin_arsenal_step(player)
        elif tag == "direct_arcane":
            dctx = self._optional_post_ctx.pop("direct", {})
            self._optional_post_ctx = {}
            card = self._cards[dctx["card_id"]]
            self._resolve_direct_effects(
                dctx["player"],
                card,
                dctx["damage"],
                dctx["arcane"],
                dctx["go_again"],
                dctx["dominate"],
                dctx["fused"],
                dctx.get("elements", ()),
                dctx["perspective"],
                skip_arcane_triggers=True,
            )
        elif tag == "die_roll":
            self._continue_pending_die_roll()
            if self._pending_combat is not None:
                self._enter_defense()
            else:
                self._phase = "action"
        else:
            self._phase = "action"

    def _finish_combat_advance(self) -> None:
        ctx = self._optional_ctx
        self._optional_ctx = {}
        attacker = self._players[ctx["attacker"]]
        if ctx.get("go_again"):
            attacker.action_points += 1
        if not self._is_terminal():
            if attacker.action_points > 0:
                self._phase = "action"
                self._active_player = ctx["attacker"]
            else:
                self._begin_arsenal_step(ctx["attacker"])

    def _do_play_card(self, player_idx: int, hand_idx: int, perspective_idx: int = 0) -> float:
        actor = self._players[player_idx]
        card = self._cards[actor.hand[hand_idx]]

        is_attack = "attack_action" in card.card_types
        is_utility = "utility_action" in card.card_types
        if not (is_attack or is_utility):
            self._last_event = f"{card.name} is not an action you can play"
            return -0.05
        if actor.action_points <= 0:
            self._last_event = "No action points remaining"
            return -0.05
        effective_cost = self._effective_card_cost(player_idx, card)
        if actor.resources < effective_cost:
            self._last_event = f"Need {effective_cost} resources (pitch cards first)"
            return -0.05
        reason = self._play_blocked_reason(player_idx, hand_idx, card)
        if reason:
            self._last_event = reason
            return -0.05

        keywords = set(card.keywords)
        elements, can_fuse = self._fusion_state(player_idx, hand_idx, card)
        fused = False
        go_again = self._go_again_for_play(player_idx, card, is_utility)
        dominate = "dominate" in keywords
        damage, arcane = _parse_action_damage(card.text, card.power, is_attack)

        actor.resources -= effective_cost
        self._consume_cost_reduction(player_idx, card, effective_cost)
        actor.action_points -= 1
        actor.class_state["ScrappedThisPlay"] = 0
        played_cid = actor.hand[hand_idx]
        actor.hand.pop(hand_idx)
        self._mark_played_from_arsenal(player_idx, played_cid)

        # Physical attacks go through the combat chain (blocks + reactions).
        # Arcane damage and non-attack actions cannot be blocked normally, so
        # they resolve immediately.
        if is_attack and not arcane:
            combat = CombatState(
                attacker=player_idx,
                defender=1 - player_idx,
                attack_card_id=card.id,
                attack_power=damage,
                blocks=[],
                go_again=go_again,
                dominate=dominate,
                fused=fused,
            )
            self._apply_defender_targeting_penalty(combat)
            self._pending_combat = combat
            suffix = self._play_suffix(fused, elements, go_again)
            self._last_event = f"P{player_idx} attacks with {card.name} ({damage}){suffix}"
            self._record_opponent_attack(
                player_idx,
                attack_name=card.name,
                attack_power=damage,
            )
            # Inline play bonuses (e.g. "if you've played another red card, go again").
            go_again, dominate = self._apply_play_modifiers(
                player_idx, card, combat, go_again=go_again, dominate=dominate
            )
            combat.go_again = go_again
            combat.dominate = dominate
            self._apply_kayo_power6(player_idx, card, combat)
            if self._phase == "optional":
                self._play_resume_ctx = {
                    "player": player_idx,
                    "card_id": card.id,
                    "perspective": perspective_idx,
                    "fused": False,
                    "elements": elements,
                }
                self._optional_resume = "post_play_costs"
                self._active_player = player_idx
                return 0.0
            self._record_play_counters(
                player_idx, card, is_attack, is_utility, fused, elements[0] if elements else None
            )
            # Consume a pending "next attack gets +power" buff (e.g. Nimblism).
            self._consume_pending_next_attack_power(player_idx, card, combat)
            if can_fuse:
                self._queue_fusion_optional(player_idx, card, perspective_idx, elements)
            self._queue_play_costs(player_idx, card, perspective_idx)
            if self._pending_optionals:
                self._play_resume_ctx = {
                    "player": player_idx,
                    "card_id": card.id,
                    "perspective": perspective_idx,
                    "fused": False,
                    "elements": elements,
                }
                self._optional_resume = "post_play_costs"
                self._phase = "optional"
                self._active_player = player_idx
                return 0.0
            trig_reward = self._finish_attack_triggers(player_idx, card, perspective_idx, fused)
            return trig_reward

        return self._resolve_direct(
            player_idx, card, damage, arcane, go_again, dominate, fused, elements, perspective_idx
        )

